use std::sync::Arc;

use nanocode_durability_core::{Sql, SqlStatement, StoreError, StoreFuture};
use nanocode_sync::Atom;

pub trait LogHost: Send + Sync {
    fn append<'a>(
        &'a self,
        scope: &'a str,
        body: &'a str,
    ) -> StoreFuture<'a, Result<u64, StoreError>>;

    fn scan<'a>(
        &'a self,
        scope: &'a str,
        after: u64,
    ) -> StoreFuture<'a, Result<Vec<(u64, String)>, StoreError>>;

    fn snapshot<'a>(
        &'a self,
        scope: &'a str,
    ) -> StoreFuture<'a, Result<Option<(u64, String)>, StoreError>>;

    fn put_snapshot<'a>(
        &'a self,
        scope: &'a str,
        seq: u64,
        body: &'a str,
    ) -> StoreFuture<'a, Result<(), StoreError>>;
}

type Dialects = [&'static str; 2];

const CREATE_LOG: Dialects = [
    "CREATE TABLE IF NOT EXISTS nanocode_log (seq INTEGER PRIMARY KEY, scope TEXT NOT NULL, body TEXT NOT NULL)",
    "CREATE TABLE IF NOT EXISTS nanocode_log (seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scope TEXT NOT NULL, body TEXT NOT NULL)",
];
const CREATE_SNAP: Dialects = [
    "CREATE TABLE IF NOT EXISTS nanocode_snap (scope TEXT PRIMARY KEY, seq INTEGER NOT NULL, body TEXT NOT NULL) WITHOUT ROWID",
    "CREATE TABLE IF NOT EXISTS nanocode_snap (scope TEXT PRIMARY KEY, seq BIGINT NOT NULL, body TEXT NOT NULL)",
];
const APPEND: Dialects = [
    "INSERT INTO nanocode_log (scope, body) VALUES (?1, ?2) RETURNING CAST(seq AS TEXT)",
    "INSERT INTO nanocode_log (scope, body) VALUES ($1::text, $2::text) RETURNING CAST(seq AS TEXT)",
];
const SCAN: Dialects = [
    "SELECT CAST(seq AS TEXT), body FROM nanocode_log WHERE scope = ?1 AND seq > CAST(?2 AS INTEGER) ORDER BY seq",
    "SELECT CAST(seq AS TEXT), body FROM nanocode_log WHERE scope = $1::text AND seq > CAST($2::text AS BIGINT) ORDER BY seq",
];
const SNAPSHOT: Dialects = [
    "SELECT CAST(seq AS TEXT), body FROM nanocode_snap WHERE scope = ?1",
    "SELECT CAST(seq AS TEXT), body FROM nanocode_snap WHERE scope = $1::text",
];
const PUT_SNAPSHOT: Dialects = [
    "INSERT INTO nanocode_snap (scope, seq, body) VALUES (?1, CAST(?2 AS INTEGER), ?3) ON CONFLICT (scope) DO UPDATE SET seq = excluded.seq, body = excluded.body",
    "INSERT INTO nanocode_snap (scope, seq, body) VALUES ($1::text, CAST($2::text AS BIGINT), $3::text) ON CONFLICT (scope) DO UPDATE SET seq = excluded.seq, body = excluded.body",
];

pub struct SqlLog<H: ?Sized> {
    host: Arc<H>,
}

impl<H: Sql + ?Sized> SqlLog<H> {
    pub const fn new(host: Arc<H>) -> Self {
        Self { host }
    }

    fn pick(&self, statements: &Dialects) -> &'static str {
        self.host.dialect().pick(statements)
    }
}

fn invalid(detail: impl std::fmt::Display) -> StoreError {
    StoreError::Backend(format!(
        "SQL host answered an invalid turn log row: {detail}"
    ))
}

fn row(cells: &[Option<String>]) -> Result<(u64, String), StoreError> {
    match cells {
        [Some(seq), Some(body)] => Ok((
            seq.parse()
                .map_err(|error| invalid(format!("seq {seq}: {error}")))?,
            body.clone(),
        )),
        _ => Err(invalid(format!("{} cells", cells.len()))),
    }
}

impl<H: Sql + Send + Sync + ?Sized> LogHost for SqlLog<H> {
    fn append<'a>(
        &'a self,
        scope: &'a str,
        body: &'a str,
    ) -> StoreFuture<'a, Result<u64, StoreError>> {
        Box::pin(async move {
            let statements = [SqlStatement {
                sql: self.pick(&APPEND),
                params: vec![scope, body],
            }];
            let rows = self
                .host
                .transaction("turn_log_append", &statements)
                .await?;
            match rows.first().map(Vec::as_slice) {
                Some([cells]) => match cells.as_slice() {
                    [Some(seq)] => seq
                        .parse()
                        .map_err(|error| invalid(format!("seq {seq}: {error}"))),
                    _ => Err(invalid("append returned no seq")),
                },
                _ => Err(invalid("append returned no row")),
            }
        })
    }

    fn scan<'a>(
        &'a self,
        scope: &'a str,
        after: u64,
    ) -> StoreFuture<'a, Result<Vec<(u64, String)>, StoreError>> {
        Box::pin(async move {
            let after = after.to_string();
            let statements = [SqlStatement {
                sql: self.pick(&SCAN),
                params: vec![scope, &after],
            }];
            let rows = self.host.transaction("turn_log_scan", &statements).await?;
            rows.into_iter()
                .next()
                .ok_or_else(|| invalid("scan returned no result"))?
                .iter()
                .map(|cells| row(cells))
                .collect()
        })
    }

    fn snapshot<'a>(
        &'a self,
        scope: &'a str,
    ) -> StoreFuture<'a, Result<Option<(u64, String)>, StoreError>> {
        Box::pin(async move {
            let statements = [
                SqlStatement {
                    sql: self.pick(&CREATE_LOG),
                    params: Vec::new(),
                },
                SqlStatement {
                    sql: self.pick(&CREATE_SNAP),
                    params: Vec::new(),
                },
                SqlStatement {
                    sql: self.pick(&SNAPSHOT),
                    params: vec![scope],
                },
            ];
            let rows = self
                .host
                .transaction("turn_log_snapshot", &statements)
                .await?;
            match rows.get(2).map(Vec::as_slice) {
                Some([]) => Ok(None),
                Some([cells]) => row(cells).map(Some),
                Some(_) => Err(invalid("several snapshots for one scope")),
                None => Err(invalid("snapshot returned no result")),
            }
        })
    }

    fn put_snapshot<'a>(
        &'a self,
        scope: &'a str,
        seq: u64,
        body: &'a str,
    ) -> StoreFuture<'a, Result<(), StoreError>> {
        Box::pin(async move {
            let seq = seq.to_string();
            let statements = [SqlStatement {
                sql: self.pick(&PUT_SNAPSHOT),
                params: vec![scope, &seq, body],
            }];
            self.host
                .transaction("turn_log_put_snapshot", &statements)
                .await
                .map(drop)
        })
    }
}

#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct MemoryWrites {
    pub bytes: u64,
    pub rows: u64,
    pub snapshot_bytes: u64,
    pub snapshots: u64,
}

#[derive(Clone, Default)]
struct Memory {
    rows: imbl::Vector<(u64, Arc<str>, Arc<str>)>,
    snapshots: imbl::OrdMap<Arc<str>, (u64, Arc<str>)>,
    writes: MemoryWrites,
}

#[derive(Default)]
pub struct MemoryLog {
    memory: Atom<Memory>,
}

impl MemoryLog {
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    #[must_use]
    pub fn writes(&self) -> MemoryWrites {
        self.memory.read(|memory| memory.writes)
    }

    pub fn truncate(&self, seq: u64) {
        self.memory.update(|memory| {
            memory.rows.retain(|(row, _, _)| *row <= seq);
            memory.snapshots = memory
                .snapshots
                .iter()
                .filter(|(_, (row, _))| *row <= seq)
                .map(|(scope, snapshot)| (Arc::clone(scope), snapshot.clone()))
                .collect();
        });
    }
}

impl LogHost for MemoryLog {
    fn append<'a>(
        &'a self,
        scope: &'a str,
        body: &'a str,
    ) -> StoreFuture<'a, Result<u64, StoreError>> {
        let scope = Arc::<str>::from(scope);
        let body = Arc::<str>::from(body);
        let seq = self.memory.update(|memory| {
            let seq = memory.rows.last().map_or(1, |(seq, _, _)| seq + 1);
            memory
                .rows
                .push_back((seq, Arc::clone(&scope), Arc::clone(&body)));
            memory.writes.rows += 1;
            memory.writes.bytes += body.len() as u64;
            seq
        });
        Box::pin(async move { Ok(seq) })
    }

    fn scan<'a>(
        &'a self,
        scope: &'a str,
        after: u64,
    ) -> StoreFuture<'a, Result<Vec<(u64, String)>, StoreError>> {
        let rows = self.memory.read(|memory| {
            memory
                .rows
                .iter()
                .filter(|(seq, owner, _)| *seq > after && **owner == *scope)
                .map(|(seq, _, body)| (*seq, body.to_string()))
                .collect()
        });
        Box::pin(async move { Ok(rows) })
    }

    fn snapshot<'a>(
        &'a self,
        scope: &'a str,
    ) -> StoreFuture<'a, Result<Option<(u64, String)>, StoreError>> {
        let snapshot = self.memory.read(|memory| {
            memory
                .snapshots
                .get(scope)
                .map(|(seq, body)| (*seq, body.to_string()))
        });
        Box::pin(async move { Ok(snapshot) })
    }

    fn put_snapshot<'a>(
        &'a self,
        scope: &'a str,
        seq: u64,
        body: &'a str,
    ) -> StoreFuture<'a, Result<(), StoreError>> {
        let scope = Arc::<str>::from(scope);
        let body = Arc::<str>::from(body);
        self.memory.update(|memory| {
            memory
                .snapshots
                .insert(Arc::clone(&scope), (seq, Arc::clone(&body)));
            memory.writes.snapshots += 1;
            memory.writes.snapshot_bytes += body.len() as u64;
        });
        Box::pin(async move { Ok(()) })
    }
}
