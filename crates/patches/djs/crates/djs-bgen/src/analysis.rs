//! Resume-point inference: which call sites may run user code, and which builtins are
//! therefore reentrant (transitively). The Rust backend will split functions into
//! states at these points; for the JS backend it is a review aid and a check.

use crate::ast::*;
use crate::check::{Callee, Program};
use crate::diag::{Sources, Span};

#[derive(Debug, Clone, PartialEq)]
pub struct ResumePoint {
    pub span: Span,
    pub callee: String,
    /// "intrinsic" or "builtin"
    pub kind: &'static str,
}

#[derive(Debug, Clone, PartialEq)]
pub struct FnAnalysis {
    /// Index into `Program::builtins`.
    pub builtin: usize,
    pub reentrant: bool,
    pub resume_points: Vec<ResumePoint>,
}

/// Analyzes every builtin, in program order.
pub fn analyze(p: &Program) -> Vec<FnAnalysis> {
    let calls: Vec<Vec<(Span, String, Callee)>> = p
        .builtins
        .iter()
        .map(|b| {
            let mut out = Vec::new();
            for s in &p.function(b).body.stmts {
                stmt_calls(s, p, &mut out);
            }
            out
        })
        .collect();
    // Least fixpoint: start with everything leaf.
    let mut reentrant = vec![false; p.builtins.len()];
    loop {
        let mut changed = false;
        for (i, cs) in calls.iter().enumerate() {
            if !reentrant[i] && cs.iter().any(|(_, _, c)| is_reentrant(*c, &reentrant)) {
                reentrant[i] = true;
                changed = true;
            }
        }
        if !changed {
            break;
        }
    }
    calls
        .iter()
        .enumerate()
        .map(|(i, cs)| FnAnalysis {
            builtin: i,
            reentrant: reentrant[i],
            resume_points: cs
                .iter()
                .filter(|(_, _, c)| is_reentrant(*c, &reentrant))
                .map(|(span, name, c)| ResumePoint {
                    span: *span,
                    callee: name.clone(),
                    kind: if matches!(c, Callee::Intrinsic { .. }) {
                        "intrinsic"
                    } else {
                        "builtin"
                    },
                })
                .collect(),
        })
        .collect()
}

fn is_reentrant(c: Callee, builtins: &[bool]) -> bool {
    match c {
        Callee::Intrinsic { reentrant } => reentrant,
        Callee::Builtin(i) => builtins[i],
    }
}

/// The text report (`djs-bgen --report`, checked in as builtins/gen/resume-points.txt).
pub fn report(p: &Program, analysis: &[FnAnalysis], sources: &Sources) -> String {
    let mut out = String::from(
        "# Generated by djs-bgen: builtins and the call sites that may run user code (resume points).\n",
    );
    for a in analysis {
        let b = &p.builtins[a.builtin];
        let mut notes = Vec::new();
        for i in &b.installs {
            notes.push(i.label());
        }
        if b.intrinsic {
            notes.push(format!("%{}", b.name));
        }
        if b.native {
            notes.push("@native".into());
        }
        let notes = if notes.is_empty() {
            String::new()
        } else {
            format!(" ({})", notes.join(", "))
        };
        out.push_str(&format!(
            "\n{}: {}{notes}\n",
            b.name,
            if a.reentrant { "reentrant" } else { "leaf" }
        ));
        for r in &a.resume_points {
            out.push_str(&format!(
                "  {}  {} ({})\n",
                sources.position(r.span),
                r.callee,
                r.kind
            ));
        }
    }
    out
}

fn stmt_calls(s: &Stmt, p: &Program, out: &mut Vec<(Span, String, Callee)>) {
    let mut e = |x: &Expr| expr_calls(x, p, out);
    match s {
        Stmt::Decl { init, .. } => e(init),
        Stmt::Assign { value, .. } => e(value),
        Stmt::Update { .. } | Stmt::Break(_) | Stmt::Continue(_) => {}
        Stmt::Expr(x) => e(x),
        Stmt::If {
            cond, then, els, ..
        } => {
            e(cond);
            stmt_calls(then, p, out);
            if let Some(s) = els {
                stmt_calls(s, p, out);
            }
        }
        Stmt::While { cond, body, .. } => {
            e(cond);
            stmt_calls(body, p, out);
        }
        Stmt::DoWhile { body, cond, .. } => {
            stmt_calls(body, p, out);
            expr_calls(cond, p, out);
        }
        Stmt::For {
            init,
            cond,
            update,
            body,
            ..
        } => {
            if let Some(s) = init {
                stmt_calls(s, p, out);
            }
            if let Some(c) = cond {
                expr_calls(c, p, out);
            }
            stmt_calls(body, p, out);
            if let Some(s) = update {
                stmt_calls(s, p, out);
            }
        }
        Stmt::Return { value, .. } => {
            if let Some(v) = value {
                e(v);
            }
        }
        Stmt::Throw { value, .. } => e(value),
        Stmt::Try {
            body,
            catch,
            finally,
            ..
        } => {
            for s in &body.stmts {
                stmt_calls(s, p, out);
            }
            if let Some(c) = catch {
                for s in &c.body.stmts {
                    stmt_calls(s, p, out);
                }
            }
            if let Some(f) = finally {
                for s in &f.stmts {
                    stmt_calls(s, p, out);
                }
            }
        }
        Stmt::Block(b) => {
            for s in &b.stmts {
                stmt_calls(s, p, out);
            }
        }
    }
}

/// Calls in evaluation order (arguments before the call itself).
fn expr_calls(e: &Expr, p: &Program, out: &mut Vec<(Span, String, Callee)>) {
    match &e.kind {
        ExprKind::Unary(_, x) | ExprKind::Paren(x) => expr_calls(x, p, out),
        ExprKind::Binary(_, a, b) => {
            expr_calls(a, p, out);
            expr_calls(b, p, out);
        }
        ExprKind::Cond(c, a, b) => {
            expr_calls(c, p, out);
            expr_calls(a, p, out);
            expr_calls(b, p, out);
        }
        ExprKind::Call {
            callee,
            callee_span,
            args,
        } => {
            for a in args {
                expr_calls(a, p, out);
            }
            if let Some((c, _)) = p.callees.get(callee) {
                out.push((*callee_span, callee.clone(), *c));
            }
        }
        _ => {}
    }
}
