//! The bytecode backend: plain JS with `%Name(...)` intrinsic calls (docs/compiler.md
//! 7.3), compiled by djs in privileged mode.
//!
//! The output is one Script: a strict IIFE that declares every builtin as a local
//! function (so builtins call each other directly and nothing leaks into the global
//! object) and then installs them (D1172):
//!
//! ```text
//! %InstallMethod("Array.prototype", "map", ArrayPrototypeMap, 1);
//! %InstallIntrinsic("ToPrimitive", ToPrimitive);
//! ```
//!
//! `%InstallMethod(target, key, fn, length)` defines `fn` as a method on the object at
//! the dotted path `target` (resolved from the global object) with the attributes of
//! builtin methods (writable, configurable, not enumerable) and sets its `name` to
//! `key` and its `length`. `%InstallIntrinsic(name, fn)` registers a builtin that
//! privileged code (and the interpreter's slow paths) call as `%name(...)`.
//!
//! D1310 adds `%InstallConstructor(target, key, fn, length, parent)` (`@constructor`),
//! `%InstallAccessor(target, key, fn, isSetter)` (`@getter`/`@setter`) and
//! `%InstallValue(target, key, fn(), attrs)` (`@value`). Installs onto the global object
//! come first. A constructor's own statics follow it right away, then
//! `%InstallPrototype(target, key, parent)` defines its `prototype` last, as qjs orders a
//! constructor's own properties (D2052).

use crate::ast::*;
use crate::check::{Builtin, Callee, Install, InstallKind, Program};
use crate::diag::Sources;
use std::cell::{Cell, RefCell};
use std::collections::HashMap;

pub const HEADER: &str =
    "// Generated by djs-bgen from builtins/*.ts; do not edit. Regenerate with scripts/bgen.sh.\n";

/// `omit`: builtin files (by source name) whose builtins are left out, for the slim
/// build's prelude (D2411). Calls into them from the others stay as they are; they become
/// global reads that no slim run reaches (they sit behind checks for values only the
/// omitted builtins make), and the header lists them so that a new one shows in review.
///
/// `slim`: also leave out the builtins tagged @slim-omit (the slim prelude); without it,
/// `omit` are the files a build without djs-core's `embed` leaves out (`// @embed-only`,
/// D3175).
pub fn emit(p: &Program, sources: &Sources, omit: &[&str], slim: bool) -> String {
    let file_of = |b: &Builtin| sources.file(p.function(b).span).name.as_str();
    let gone = |b: &Builtin| (slim && b.slim_omit) || omit.contains(&file_of(b));
    let e = Emitter::new(p, p.builtins.iter().map(|b| !gone(b)).collect());
    let kept: Vec<&Builtin> = p.builtins.iter().filter(|b| !gone(b)).collect();
    // The constructors the omitted builtins make: kept builtins installed onto them
    // (`%TypedArray%.prototype.toString` is Array's) go too.
    let gone_ctors: Vec<&str> = p
        .builtins
        .iter()
        .filter(|b| gone(b))
        .flat_map(|b| &b.installs)
        .filter(|i| i.on_global() && matches!(i.kind, InstallKind::Constructor { .. }))
        .map(|i| i.key.as_str())
        .collect();
    let on_gone = |i: &Install| {
        let root = i.target.split('.').next().unwrap_or("");
        gone_ctors.contains(&root)
    };
    let mut out = String::from(HEADER);
    if !slim && !omit.is_empty() {
        out.push_str("// The prelude of full builds without `embed` (D3175): without ");
        out.push_str(&omit.join(", "));
        out.push_str(".\n");
    }
    if slim {
        out.push_str("// The slim build's prelude (D2411): without ");
        out.push_str(&omit.join(", "));
        out.push_str(" and the builtins tagged @slim-omit.\n");
        let gone: Vec<&str> = p
            .builtins
            .iter()
            .filter(|b| gone(b))
            .map(|b| b.name.as_str())
            .collect();
        let mut dangling: Vec<String> = Vec::new();
        for b in &kept {
            for l in e.function(p.function(b)) {
                for g in &gone {
                    let call = format!("{g}(");
                    let mut at = 0;
                    while let Some(i) = l[at..].find(&call) {
                        let j = at + i;
                        let before = l[..j].chars().next_back();
                        if !before.is_some_and(|c| c.is_alphanumeric() || c == '_')
                            && !dangling.iter().any(|d| d == &format!("{} -> {g}", b.name))
                        {
                            dangling.push(format!("{} -> {g}", b.name));
                        }
                        at = j + call.len();
                    }
                }
            }
        }
        if !dangling.is_empty() {
            out.push_str("// Calls into the omitted files (unreachable without their values):\n");
            for d in dangling {
                out.push_str(&format!("//   {d}\n"));
            }
        }
    }
    out.push_str("\"use strict\";\n(function () {\n");
    for b in kept.iter().copied() {
        let f = p.function(b);
        let mut what: String = b
            .installs
            .iter()
            .map(|i| format!(" {}", i.label()))
            .collect();
        if b.intrinsic {
            what.push_str(&format!(" %{}", b.name));
        }
        let file = sources.file(f.span);
        let (line, _) = file.line_col(f.span.start);
        out.push_str(&format!("\n// {}:{line}{what}\n", file.name));
        for l in e.function(f) {
            out.push_str(&l);
            out.push('\n');
        }
    }
    out.push('\n');
    // Installs onto the global object (constructors, namespaces, global functions)
    // first, so that the paths of the others resolve; then the rest, in source order.
    // A constructor's statics (installs onto the constructor itself) come right after
    // it, then its `prototype` (D2052).
    let ctor_keys: Vec<&str> = kept
        .iter()
        .flat_map(|b| &b.installs)
        .filter(|i| i.on_global() && matches!(i.kind, InstallKind::Constructor { .. }))
        .map(|i| i.key.as_str())
        .collect();
    for &b in &kept {
        for i in b.installs.iter().filter(|i| i.on_global()) {
            out.push_str(&install(b, i));
            if let InstallKind::Constructor { parent } = &i.kind {
                let mut statics = Vec::new();
                for &sb in &kept {
                    for si in sb.installs.iter().filter(|si| si.target == i.key) {
                        statics.push((si.target.clone(), si.key.clone(), install(sb, si)));
                    }
                }
                // qjs's order of the statics (D2072).
                crate::qjs_order::reorder(&mut statics);
                for (_, _, line) in statics {
                    out.push_str(&line);
                }
                out.push_str(&format!(
                    "%InstallPrototype({}, {}, {});\n",
                    js_str(&i.target),
                    js_str(&i.key),
                    parent.as_deref().map(js_str).unwrap_or("undefined".into())
                ));
            }
        }
    }
    let mut rest = Vec::new();
    for &b in &kept {
        for i in b
            .installs
            .iter()
            .filter(|i| !i.on_global() && !ctor_keys.contains(&i.target.as_str()) && !on_gone(i))
        {
            rest.push((i.target.clone(), i.key.clone(), install(b, i)));
        }
    }
    // Each prototype's `constructor`, after its methods unless qjs's order says
    // otherwise (D2150).
    for &b in &kept {
        for i in &b.installs {
            if i.on_global()
                && let InstallKind::Constructor { .. } = i.kind
                && i.key != "Proxy"
            {
                rest.push((
                    format!("{}.prototype", i.key),
                    "constructor".to_string(),
                    format!("%InstallPrototypeConstructor({});\n", js_str(&i.key)),
                ));
            }
        }
    }
    // Namespace objects (Math, JSON) and prototypes in qjs's order too (D2072, D2150).
    crate::qjs_order::reorder(&mut rest);
    for (_, _, line) in rest {
        out.push_str(&line);
    }
    for b in kept.iter().filter(|b| b.intrinsic) {
        out.push_str(&format!(
            "%InstallIntrinsic({}, {});\n",
            js_string(&b.name.encode_utf16().collect::<Vec<_>>()),
            b.name
        ));
    }
    // The Rust backend's builtins, in the order of its table (0063).
    // (The index is the full table's: the slim prelude marks the same natives.)
    for (i, b) in p.builtins.iter().filter(|b| b.native).enumerate() {
        if kept.iter().any(|k| std::ptr::eq(*k, b)) {
            out.push_str(&format!("%MarkNative({}, {i});\n", b.name));
        }
    }
    // Leaf fast paths (D1850), by name: builtins/fast.rs has the table.
    for b in kept.iter().filter(|b| b.fast) {
        out.push_str(&format!("%MarkFast({});\n", b.name));
    }
    out.push_str("})();\n");
    out
}

/// The installation call of `b` at `i` (D1172, D1310).
fn install(b: &Builtin, i: &Install) -> String {
    let t = js_str(&i.target);
    let k = match crate::check::symbol_key(&i.key) {
        Some(name) => format!("%WellKnownSymbol({})", js_str(name)),
        None => js_str(&i.key),
    };
    let f = &b.name;
    match &i.kind {
        InstallKind::Method { attrs: None } => {
            format!("%InstallMethod({t}, {k}, {f}, {});\n", i.length)
        }
        // Other attributes: install, then redefine the property.
        InstallKind::Method { attrs: Some(a) } => format!(
            "%InstallMethod({t}, {k}, {f}, {});\n%InstallValue({t}, {k}, {f}, {a});\n",
            i.length
        ),
        InstallKind::Constructor { parent } => format!(
            "%InstallConstructor({t}, {k}, {f}, {}, {});\n",
            i.length,
            parent.as_deref().map(js_str).unwrap_or("undefined".into())
        ),
        InstallKind::Getter | InstallKind::Setter => format!(
            "%InstallAccessor({t}, {k}, {f}, {});\n",
            i.kind == InstallKind::Setter
        ),
        InstallKind::Value { attrs } => format!("%InstallValue({t}, {k}, {f}(), {attrs});\n"),
    }
}

fn js_str(s: &str) -> String {
    js_string(&s.encode_utf16().collect::<Vec<_>>())
}

/// A double-quoted JS string; everything outside printable ASCII is escaped, so the
/// output is ASCII and lone surrogates survive.
pub fn js_string(units: &[u16]) -> String {
    let mut s = String::from("\"");
    for &u in units {
        match u {
            0x22 => s.push_str("\\\""),
            0x5c => s.push_str("\\\\"),
            0x0a => s.push_str("\\n"),
            0x09 => s.push_str("\\t"),
            0x0d => s.push_str("\\r"),
            0x20..=0x7e => s.push(u as u8 as char),
            _ => s.push_str(&format!("\\u{u:04x}")),
        }
    }
    s.push('"');
    s
}

struct Emitter<'a> {
    p: &'a Program,
    /// Per builtin: whether its calls may be inlined (it is in this prelude).
    kept: Vec<bool>,
    /// The temporaries of the function being emitted (`$1` ..), which hold the
    /// arguments and locals of the helpers inlined into it.
    temps: Cell<u32>,
    /// The names of the helper bodies being inlined (innermost last): their parameters
    /// and locals, as the caller's temporaries or argument expressions.
    subst: RefCell<Vec<HashMap<String, String>>>,
    /// The helpers being inlined, innermost last.
    inlining: RefCell<Vec<usize>>,
}

/// The largest helper body (in statements, `inline_size`) that is inlined.
const INLINE_SIZE: usize = 8;
/// How deep inlined helpers nest.
const INLINE_DEPTH: usize = 4;
/// The longest inlined call, in characters of JS: every call site gets a copy, so only
/// short bodies pay for themselves (0230: 160 kept most of the gain on the string and
/// Math methods for ~1 KB gz of base image; 260 cost 1.4 KB more for little).
const INLINE_TEXT: usize = 160;

fn indented(lines: Vec<String>) -> impl Iterator<Item = String> {
    lines.into_iter().map(|l| format!("  {l}"))
}

impl<'a> Emitter<'a> {
    fn new(p: &'a Program, kept: Vec<bool>) -> Emitter<'a> {
        Emitter {
            p,
            kept,
            temps: Cell::new(0),
            subst: RefCell::new(Vec::new()),
            inlining: RefCell::new(Vec::new()),
        }
    }

    fn function(&self, f: &Function) -> Vec<String> {
        self.temps.set(0);
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                if p.rest {
                    format!("...{}", p.name)
                } else {
                    p.name.clone()
                }
            })
            .collect();
        let mut out = vec![format!("function {}({}) {{", f.name, params.join(", "))];
        let body = self.stmts(&f.body.stmts);
        let n = self.temps.get();
        if n > 0 {
            let temps: Vec<String> = (1..=n).map(|i| format!("${i}")).collect();
            out.push(format!("  let {};", temps.join(", ")));
        }
        out.extend(indented(body));
        out.push("}".into());
        out
    }

    /// Variable `n`: in an inlined body, the temporary or argument that stands for it.
    fn name(&self, n: &str) -> String {
        match self.subst.borrow().last().and_then(|m| m.get(n)) {
            Some(v) => v.clone(),
            None => n.to_string(),
        }
    }

    fn temp(&self) -> String {
        self.temps.set(self.temps.get() + 1);
        format!("${}", self.temps.get())
    }

    /// Whether calls of builtin `b` are inlined (0230): a small internal helper (no
    /// installs, so it never shows in a stack trace, D2371) without `this`, rest
    /// parameters, `new.target` or `%ArgumentCount` (both read the frame), no twin of
    /// its own (`@native`, `@fast`) and no `@frame` (the engine looks for its frame),
    /// not already being inlined.
    fn inlinable(&self, b: usize) -> bool {
        let bi = &self.p.builtins[b];
        let f = self.p.function(bi);
        let inlining = self.inlining.borrow();
        self.kept[b]
            && !bi.native
            && !bi.fast
            && !bi.frame
            && bi.installs.is_empty()
            && f.this_ty.is_none()
            && !f.params.iter().any(|p| p.rest)
            && inlining.len() < INLINE_DEPTH
            && !inlining.contains(&b)
            && inline_size(&f.body.stmts) <= INLINE_SIZE
            && !reads_frame(&f.body.stmts)
    }

    /// A call of helper `b` as one expression: its arguments into temporaries (in
    /// order, as the call would evaluate them; plain names and literals are used as
    /// they are), then its body as a conditional expression, `%Throw` for a `throw`.
    /// `None` when the body has no such form (a loop, an `if` that falls through).
    fn inline(&self, b: usize, args: &[Expr]) -> Option<String> {
        let p: &'a Program = self.p;
        let f = p.function(&p.builtins[b]);
        if args.len() > f.params.len() {
            return None;
        }
        let (temps0, mut parts, mut map) = (self.temps.get(), Vec::new(), HashMap::new());
        for (k, param) in f.params.iter().enumerate() {
            let value = match args.get(k) {
                Some(a) if trivial(a) && !assigns(&f.body.stmts, &param.name) => self.expr(a),
                Some(a) => {
                    let t = self.temp();
                    parts.push(format!("{t} = {}", self.expr(a)));
                    t
                }
                None => "undefined".into(),
            };
            map.insert(param.name.clone(), value);
        }
        self.subst.borrow_mut().push(map);
        self.inlining.borrow_mut().push(b);
        let stmts: Vec<&'a Stmt> = f.body.stmts.iter().collect();
        let body = self.tail(&stmts);
        self.inlining.borrow_mut().pop();
        self.subst.borrow_mut().pop();
        let Some(body) = body else {
            self.temps.set(temps0);
            return None;
        };
        parts.push(body);
        let out = format!("({})", parts.join(", "));
        if out.len() > INLINE_TEXT {
            self.temps.set(temps0);
            return None;
        }
        Some(out)
    }

    /// `stmts` (the rest of an inlined body) as an expression.
    fn tail(&self, stmts: &[&'a Stmt]) -> Option<String> {
        let Some((first, rest)) = stmts.split_first() else {
            return Some("undefined".into());
        };
        let then_rest = |s: &'a Stmt| -> Vec<&'a Stmt> {
            let mut v: Vec<&'a Stmt> = match s {
                Stmt::Block(b) => b.stmts.iter().collect(),
                other => vec![other],
            };
            v.extend_from_slice(rest);
            v
        };
        Some(match first {
            // Bare: the whole is parenthesized once, and a branch of `?:` needs none.
            Stmt::Return { value: Some(v), .. } => self.expr(v),
            Stmt::Return { value: None, .. } => "undefined".into(),
            Stmt::Throw { value, .. } => format!("%Throw({})", self.expr(value)),
            Stmt::Decl { name, init, .. } => {
                let init = self.expr(init);
                let t = self.temp();
                self.subst
                    .borrow_mut()
                    .last_mut()
                    .expect("inlining")
                    .insert(name.clone(), t.clone());
                format!("({t} = {init}, {})", self.tail(rest)?)
            }
            Stmt::Assign { .. } | Stmt::Update { .. } | Stmt::Expr(_) => {
                format!("({}, {})", self.simple(first), self.tail(rest)?)
            }
            Stmt::Block(b) => {
                let mut v: Vec<&'a Stmt> = b.stmts.iter().collect();
                v.extend_from_slice(rest);
                self.tail(&v)
            }?,
            Stmt::If {
                cond, then, els, ..
            } => {
                let c = self.expr(cond);
                let a = self.tail(&then_rest(then))?;
                let b = match els {
                    Some(e) => self.tail(&then_rest(e))?,
                    None => self.tail(rest)?,
                };
                format!("({c}) ? {a} : {b}")
            }
            _ => return None,
        })
    }

    fn stmts(&self, stmts: &[Stmt]) -> Vec<String> {
        stmts.iter().flat_map(|s| self.stmt(s)).collect()
    }

    /// `head {`, the body (a block's statements, or the single statement), `}`. Bodies
    /// always get braces.
    fn braced(&self, head: String, body: &Stmt) -> Vec<String> {
        let inner = match body {
            Stmt::Block(b) => self.stmts(&b.stmts),
            other => self.stmt(other),
        };
        let mut out = vec![format!("{head} {{")];
        out.extend(indented(inner));
        out.push("}".into());
        out
    }

    fn block(&self, head: &str, b: &Block) -> Vec<String> {
        let mut out = vec![format!("{head} {{")];
        out.extend(indented(self.stmts(&b.stmts)));
        out.push("}".into());
        out
    }

    /// Appends `next` (which starts with a keyword continuing the statement, like
    /// `else` or `catch`) after the closing `}` of `out`.
    fn chain(out: &mut Vec<String>, next: Vec<String>) {
        let mut next = next.into_iter();
        let first = next.next().unwrap_or_default();
        let last = out.pop().unwrap_or_default();
        out.push(format!("{last} {first}"));
        out.extend(next);
    }

    fn stmt(&self, s: &Stmt) -> Vec<String> {
        match s {
            Stmt::If {
                cond, then, els, ..
            } => {
                let mut out = self.braced(format!("if ({})", self.expr(cond)), then);
                if let Some(e) = els {
                    let rest = match &**e {
                        Stmt::If { .. } => {
                            let mut nested = self.stmt(e);
                            nested[0] = format!("else {}", nested[0]);
                            nested
                        }
                        other => self.braced("else".into(), other),
                    };
                    Self::chain(&mut out, rest);
                }
                out
            }
            Stmt::While { cond, body, .. } => {
                self.braced(format!("while ({})", self.expr(cond)), body)
            }
            Stmt::DoWhile { body, cond, .. } => {
                let mut out = self.braced("do".into(), body);
                Self::chain(&mut out, vec![format!("while ({});", self.expr(cond))]);
                out
            }
            Stmt::For {
                init,
                cond,
                update,
                body,
                ..
            } => {
                let init = init.as_ref().map(|s| self.simple(s)).unwrap_or_default();
                let cond = cond
                    .as_ref()
                    .map(|c| format!(" {}", self.expr(c)))
                    .unwrap_or_default();
                let update = update
                    .as_ref()
                    .map(|s| format!(" {}", self.simple(s)))
                    .unwrap_or_default();
                self.braced(format!("for ({init};{cond};{update})"), body)
            }
            Stmt::Try {
                body,
                catch,
                finally,
                ..
            } => {
                let mut out = self.block("try", body);
                if let Some(c) = catch {
                    let head = match &c.name {
                        Some((n, _)) => format!("catch ({n})"),
                        None => "catch".into(),
                    };
                    Self::chain(&mut out, self.block(&head, &c.body));
                }
                if let Some(f) = finally {
                    Self::chain(&mut out, self.block("finally", f));
                }
                out
            }
            Stmt::Block(b) => {
                let mut out = self.block("", b);
                out[0] = "{".into();
                out
            }
            Stmt::Return { value: Some(v), .. } => vec![format!("return {};", self.expr(v))],
            Stmt::Return { value: None, .. } => vec!["return;".into()],
            Stmt::Throw { value, .. } => vec![format!("throw {};", self.expr(value))],
            Stmt::Break(_) => vec!["break;".into()],
            Stmt::Continue(_) => vec!["continue;".into()],
            other => vec![format!("{};", self.simple(other))],
        }
    }

    /// Declarations, assignments, updates and expression statements, without `;`.
    fn simple(&self, s: &Stmt) -> String {
        match s {
            Stmt::Decl {
                kind, name, init, ..
            } => {
                format!(
                    "{} {name} = {}",
                    if *kind == DeclKind::Const {
                        "const"
                    } else {
                        "let"
                    },
                    self.expr(init)
                )
            }
            Stmt::Assign {
                target, op, value, ..
            } => format!("{} {} {}", self.name(target), op.as_str(), self.expr(value)),
            Stmt::Update { target, inc, .. } => {
                format!("{}{}", self.name(target), if *inc { "++" } else { "--" })
            }
            Stmt::Expr(e) => self.expr(e),
            _ => unreachable!("not a simple statement"),
        }
    }

    fn expr(&self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Ident(n) => self.name(n),
            ExprKind::This => "this".into(),
            ExprKind::NewTarget => "new.target".into(),
            ExprKind::Undefined => "undefined".into(),
            ExprKind::Null => "null".into(),
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Num(_, text) => text.clone(),
            ExprKind::Str(v) => js_string(v),
            ExprKind::Paren(x) => format!("({})", self.expr(x)),
            // `- -x` must not become `--x`.
            ExprKind::Unary(op, x) if matches!(x.kind, ExprKind::Unary(..)) => {
                format!("{}({})", op.as_str(), self.expr(x))
            }
            ExprKind::Unary(op, x) => format!("{}{}", op.as_str(), self.expr(x)),
            ExprKind::Binary(op, a, b) => {
                format!("{} {} {}", self.expr(a), op.as_str(), self.expr(b))
            }
            ExprKind::Cond(c, a, b) => {
                format!("{} ? {} : {}", self.expr(c), self.expr(a), self.expr(b))
            }
            ExprKind::Call { callee, args, .. } => {
                let prefix = match self.p.callees.get(callee) {
                    Some((Callee::Intrinsic { .. }, _)) => "%",
                    Some((Callee::Builtin(b), _)) => {
                        if self.inlinable(*b)
                            && let Some(e) = self.inline(*b, args)
                        {
                            return e;
                        }
                        ""
                    }
                    _ => "",
                };
                let args: Vec<String> = args.iter().map(|a| self.expr(a)).collect();
                format!("{prefix}{callee}({})", args.join(", "))
            }
        }
    }
}

/// An argument that an inlined body may use in place of its parameter: it reads nothing
/// that the body could change, and costs no more to evaluate twice.
fn trivial(e: &Expr) -> bool {
    matches!(
        e.kind,
        ExprKind::Ident(_)
            | ExprKind::This
            | ExprKind::Undefined
            | ExprKind::Null
            | ExprKind::Bool(_)
            | ExprKind::Num(..)
            | ExprKind::Str(_)
    )
}

/// Statements, counting nested ones (as the Rust backend's inliner does).
fn inline_size(stmts: &[Stmt]) -> usize {
    stmts
        .iter()
        .map(|s| match s {
            Stmt::Block(b) => inline_size(&b.stmts),
            Stmt::If { then, els, .. } => {
                1 + inline_size(std::slice::from_ref(then))
                    + els
                        .as_deref()
                        .map_or(0, |e| inline_size(std::slice::from_ref(e)))
            }
            Stmt::While { body, .. } | Stmt::DoWhile { body, .. } | Stmt::For { body, .. } => {
                1 + inline_size(std::slice::from_ref(body))
            }
            Stmt::Try { .. } => 1000,
            _ => 1,
        })
        .sum()
}

/// Walks every statement and expression of `stmts`.
fn walk(stmts: &[Stmt], f: &mut dyn FnMut(Option<&Stmt>, Option<&Expr>)) {
    fn expr(e: &Expr, f: &mut dyn FnMut(Option<&Stmt>, Option<&Expr>)) {
        f(None, Some(e));
        match &e.kind {
            ExprKind::Unary(_, x) | ExprKind::Paren(x) => expr(x, f),
            ExprKind::Binary(_, a, b) => {
                expr(a, f);
                expr(b, f);
            }
            ExprKind::Cond(c, a, b) => {
                expr(c, f);
                expr(a, f);
                expr(b, f);
            }
            ExprKind::Call { args, .. } => args.iter().for_each(|a| expr(a, f)),
            _ => {}
        }
    }
    fn stmt(s: &Stmt, f: &mut dyn FnMut(Option<&Stmt>, Option<&Expr>)) {
        f(Some(s), None);
        match s {
            Stmt::Decl { init: e, .. }
            | Stmt::Assign { value: e, .. }
            | Stmt::Expr(e)
            | Stmt::Throw { value: e, .. }
            | Stmt::Return { value: Some(e), .. } => expr(e, f),
            Stmt::If {
                cond, then, els, ..
            } => {
                expr(cond, f);
                stmt(then, f);
                if let Some(e) = els {
                    stmt(e, f);
                }
            }
            Stmt::While { cond, body, .. } | Stmt::DoWhile { body, cond, .. } => {
                expr(cond, f);
                stmt(body, f);
            }
            Stmt::For {
                init,
                cond,
                update,
                body,
                ..
            } => {
                for s in [init, update].into_iter().flatten() {
                    stmt(s, f);
                }
                if let Some(c) = cond {
                    expr(c, f);
                }
                stmt(body, f);
            }
            Stmt::Try {
                body,
                catch,
                finally,
                ..
            } => {
                body.stmts.iter().for_each(|s| stmt(s, f));
                if let Some(c) = catch {
                    c.body.stmts.iter().for_each(|s| stmt(s, f));
                }
                if let Some(b) = finally {
                    b.stmts.iter().for_each(|s| stmt(s, f));
                }
            }
            Stmt::Block(b) => b.stmts.iter().for_each(|s| stmt(s, f)),
            _ => {}
        }
    }
    stmts.iter().for_each(|s| stmt(s, f));
}

/// Whether `stmts` read their own frame: `new.target`, `this`, `%ArgumentCount`.
fn reads_frame(stmts: &[Stmt]) -> bool {
    let mut found = false;
    walk(stmts, &mut |_, e| {
        if let Some(e) = e {
            found |= match &e.kind {
                ExprKind::NewTarget | ExprKind::This => true,
                ExprKind::Call { callee, .. } => callee == "ArgumentCount",
                _ => false,
            };
        }
    });
    found
}

/// Whether `stmts` assign `name`.
fn assigns(stmts: &[Stmt], name: &str) -> bool {
    let mut found = false;
    walk(stmts, &mut |s, _| {
        found |= matches!(s, Some(Stmt::Assign { target, .. } | Stmt::Update { target, .. }) if target == name);
    });
    found
}
