pub const HEADER: &str = "\
// Generated by djs-bgen from builtins/*.ts (the @native builtins and the leaf builtins
// they call); do not edit. Regenerate with scripts/bgen.sh. The runtime is
// crates/djs-core/src/interp/run/native.rs (ARCH \"Generated state machines\").
";

/// The Rust representation of a subset type.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Rep {
    Val,
    Bool,
    I32,
    U32,
    F64,
}

fn rep(t: Type) -> Rep {
    match t {
        Type::Bool => Rep::Bool,
        Type::I32 => Rep::I32,
        Type::U32 => Rep::U32,
        Type::F64 | Type::NumLit | Type::IntLit(_) => Rep::F64,
        _ => Rep::Val,
    }
}

fn rust_type(r: Rep) -> &'static str {
    match r {
        Rep::Val => "Value",
        Rep::Bool => "bool",
        Rep::I32 => "i32",
        Rep::U32 => "u32",
        Rep::F64 => "f64",
    }
}

/// Rust code of an expression. `effect`: it calls something (it may throw or allocate),
/// so it must be evaluated in source order.
#[derive(Debug, Clone)]
struct Code {
    s: String,
    effect: bool,
}

impl Code {
    fn pure(s: impl Into<String>) -> Code {
        Code {
            s: s.into(),
            effect: false,
        }
    }
    fn effect(s: impl Into<String>) -> Code {
        Code {
            s: s.into(),
            effect: true,
        }
    }
}

/// Converts `s` of representation `from` to `want`.
fn coerce(s: String, from: Rep, want: Rep) -> String {
    match (from, want) {
        _ if from == want => s,
        (Rep::Bool, Rep::Val) => format!("Value::bool({s})"),
        (Rep::I32, Rep::Val) => format!("Value::int({s})"),
        (Rep::U32, Rep::Val) => format!("u32_value({s})"),
        (Rep::F64, Rep::Val) => format!("num({s})"),
        (Rep::I32 | Rep::U32, Rep::F64) => format!("({s} as f64)"),
        _ => panic!("bgen: no conversion from {from:?} to {want:?} ({s})"),
    }
}

/// Decodes a Value (`s`) as type `t`.
fn decode(s: String, t: Type) -> String {
    decode_rep(s, rep(t))
}

/// The Rust variable of a `Storage::Reg` local (D2000): `l<slot><b|i|u|f>`.
fn reg_name(slot: u32, r: Rep) -> String {
    let c = match r {
        Rep::Bool => 'b',
        Rep::I32 => 'i',
        Rep::U32 => 'u',
        Rep::F64 => 'f',
        Rep::Val => unreachable!("a Value local is not a register"),
    };
    format!("l{slot}{c}")
}

/// The register reads and writes in `code`, in order: (slot, rep, is a write). Writes
/// are emitted as `<reg> = ` and nothing else is.
fn reg_uses(code: &str) -> Vec<(u32, Rep, bool)> {
    let b = code.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        let starts = b[i] == b'l'
            && (i == 0 || !(b[i - 1].is_ascii_alphanumeric() || b[i - 1] == b'_'))
            && b.get(i + 1).is_some_and(u8::is_ascii_digit);
        if !starts {
            i += 1;
            continue;
        }
        let mut j = i + 1;
        while b.get(j).is_some_and(u8::is_ascii_digit) {
            j += 1;
        }
        let r = match b.get(j) {
            Some(b'b') => Rep::Bool,
            Some(b'i') => Rep::I32,
            Some(b'u') => Rep::U32,
            Some(b'f') => Rep::F64,
            _ => {
                i = j;
                continue;
            }
        };
        if b.get(j + 1)
            .is_some_and(|&c| c.is_ascii_alphanumeric() || c == b'_')
        {
            i = j + 1;
            continue;
        }
        let slot: u32 = code[i + 1..j].parse().unwrap();
        let write = code[j + 1..].starts_with(" = ");
        out.push((slot, r, write));
        i = j + 1;
    }
    out
}

fn decode_rep(s: String, r: Rep) -> String {
    match r {
        Rep::Val => s,
        Rep::Bool => format!("bool_of({s})"),
        Rep::I32 => format!("i32_of({s})"),
        Rep::U32 => format!("u32_of({s})"),
        Rep::F64 => format!("f64_of({s})"),
    }
}

fn f64_lit(v: f64) -> String {
    let s = format!("{v:?}");
    let s = if s.contains(['.', 'e', 'i', 'N']) {
        s
    } else {
        format!("{s}.0")
    };
    if v.is_sign_negative() {
        format!("({s}_f64)")
    } else {
        format!("{s}_f64")
    }
}

fn literal(v: f64, want: Rep) -> String {
    match want {
        Rep::F64 => f64_lit(v),
        Rep::I32 => format!("{}_i32", v as i32),
        Rep::U32 => format!("{}_u32", v as u32),
        Rep::Val => {
            if v.fract() == 0.0
                && v >= i32::MIN as f64
                && v <= i32::MAX as f64
                && !(v == 0.0 && v.is_sign_negative())
            {
                format!("Value::int({})", v as i32)
            } else {
                format!("num({})", f64_lit(v))
            }
        }
        Rep::Bool => panic!("bgen: a number literal as a boolean"),
    }
}

/// A Rust string literal for UTF-16 units; None for lone surrogates.
fn rust_str(units: &[u16]) -> Option<String> {
    let s = String::from_utf16(units).ok()?;
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            ' '..='~' => out.push(c),
            _ => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
        }
    }
    out.push('"');
    Some(out)
}

/// Leaf intrinsics with an inline Rust form (each mirrors `call_intrinsic`): the
/// template takes the argument Values as `{0}`, `{1}`.
fn inline_leaf(name: &str) -> Option<&'static str> {
    Some(match name {
        "IsObject" => "{0}.as_object().is_some()",
        "IsNumber" => "{0}.is_number()",
        "IsString" => "{0}.as_string().is_some()",
        "IsSymbol" => "{0}.as_symbol().is_some()",
        "IsBoolean" => "{0}.as_bool().is_some()",
        "IsCallable" => "ex.n_is_callable({0})",
        "ToBoolean" => "ex.n_to_boolean({0})",
        "AsObj" => "ex.n_as_obj({0})?",
        "AsNumber" => "ex.n_as_number({0})?",
        "AsFn" => "ex.n_as_fn({0})?",
        "AsStr" => "ex.n_as_str({0})?",
        "ToObject" => "ex.n_to_object({0})?",
        // The comparator sort's leaves, once per comparison (D3125).
        "SortStep" => "ex.n_sort_step({0}, {1})?",
        "SortOperand" => "ex.n_sort_operand({0}, {1})?",
        _ => return None,
    })
}

/// Reentrant callees with an inline fast path in the runtime (`ex.<helper>(&[args],
/// next)`, falling back to the call).
fn fast_reentrant(name: &str) -> Option<&'static str> {
    Some(match name {
        "Get" => "n_get",
        "HasProperty" => "n_has_property",
        "CreateDataPropertyOrThrow" => "n_create_data_property_or_throw",
        "LengthOfArrayLike" => "n_length_of_array_like",
        "Set" => "n_set",
        _ => return None,
    })
}

/// The Rust function names of a builtin.
fn native_fn(name: &str) -> String {
    format!("native_{name}")
}
fn handler_fn(name: &str) -> String {
    format!("handler_{name}")
}
fn leaf_fn(name: &str) -> String {
    format!("leaf_{name}")
}
fn iid_const(name: &str) -> String {
    let mut s = String::from("I_");
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            s.push('_');
        }
        s.push(c.to_ascii_uppercase());
    }
    s
}

/// Emits natives.rs. Errors: constructs the backend does not support in a `@native`
/// builtin (or in a leaf builtin it calls).
pub fn emit(
    p: &Program,
    analysis: &[FnAnalysis],
    sources: &Sources,
) -> Result<String, Vec<Diagnostic>> {
    let reentrant: Vec<bool> = analysis.iter().map(|a| a.reentrant).collect();
    let mut cx = Cx {
        p,
        reentrant: &reentrant,
        ids: BTreeSet::new(),
        leaves: Vec::new(),
        leaf_done: Default::default(),
        errors: Vec::new(),
        virtual_rest: None,
    };
    let mut fsms = Vec::new();
    for (i, b) in p.builtins.iter().enumerate() {
        if !b.native {
            continue;
        }
        let f = p.function(b);
        let file = sources.file(f.span);
        let (line, _) = file.line_col(f.span.start);
        let what: Vec<String> = b.installs.iter().map(|i| i.label()).collect();
        let origin = format!(
            "{}:{line}{}",
            file.name,
            if what.is_empty() {
                String::new()
            } else {
                format!(" ({})", what.join(", "))
            }
        );
        if let Some(code) = Fsm::emit(&mut cx, i, f, sources, &origin) {
            fsms.push((f.name.clone(), code));
        }
    }
    // Leaf builtins found while emitting (transitively).
    let mut leaf_code = Vec::new();
    while let Some(i) = cx.leaves.pop() {
        let b = &p.builtins[i];
        let f = p.function(b);
        let file = sources.file(f.span);
        let (line, _) = file.line_col(f.span.start);
        if let Some(code) = Direct::emit(&mut cx, f, &format!("{}:{line}", file.name)) {
            leaf_code.push((f.name.clone(), code));
        }
    }
    if !cx.errors.is_empty() {
        return Err(cx.errors);
    }
    leaf_code.sort();
    let mut out = String::from(HEADER);
    out.push_str(
        "\nuse crate::interp::conv::Fault;\nuse crate::interp::run::{Exec, Step};\nuse crate::interp::run::native::*;\nuse crate::value::Value;\n",
    );
    out.push('\n');
    for name in &cx.ids {
        let _ = writeln!(out, "const {}: u16 = iid(\"{name}\");", iid_const(name));
    }
    out.push_str(
        "\n/// The native builtins; `%MarkNative(f, index)` in the prelude refers to them.\n",
    );
    out.push_str("pub(crate) static NATIVES: &[NativeFn] = &[\n");
    for (name, code) in &fsms {
        let _ = writeln!(
            out,
            "    NativeFn {{ name: \"{name}\", params: {}, locals: {}, run: {}, handler: {} }},",
            code.params,
            code.locals,
            native_fn(name),
            handler_fn(name)
        );
    }
    out.push_str("];\n");
    for (_, code) in &fsms {
        out.push('\n');
        out.push_str(&code.text);
    }
    for (_, code) in &leaf_code {
        out.push('\n');
        out.push_str(code);
    }
    Ok(out)
}

struct Cx<'a> {
    p: &'a Program,
    reentrant: &'a [bool],
    /// Intrinsic ids the code refers to.
    ids: BTreeSet<String>,
    /// Leaf builtins still to emit, and those already queued.
    leaves: Vec<usize>,
    leaf_done: std::collections::HashSet<usize>,
    errors: Vec<Diagnostic>,
    /// The rest parameter of the function being emitted when it is virtual: (name,
    /// index of the first rest argument). Only `LengthOfArrayLike(rest)` and
    /// `Get(rest, i)` use it, which read the arguments directly.
    virtual_rest: Option<(String, u32)>,
}

impl Cx<'_> {
    fn callee(&self, name: &str) -> (Callee, Sig) {
        self.p.callees[name].clone()
    }

    fn is_reentrant(&self, name: &str) -> bool {
        match self.p.callees.get(name) {
            Some((Callee::Intrinsic { reentrant }, _)) => *reentrant,
            Some((Callee::Builtin(i), _)) => self.reentrant[*i],
            None => false,
        }
    }

    fn id(&mut self, name: &str) -> String {
        self.ids.insert(name.to_string());
        iid_const(name)
    }

    /// `LengthOfArrayLike(rest)` or `Get(rest, i)` of a virtual rest parameter.
    fn virtual_rest_use(&self, callee: &str, args: &[Expr]) -> Option<u32> {
        let (name, k) = self.virtual_rest.as_ref()?;
        match (callee, args.first().map(|a| &a.kind)) {
            ("LengthOfArrayLike" | "Get", Some(ExprKind::Ident(n))) if n == name => Some(*k),
            _ => None,
        }
    }

    /// A call that is itself a resume point.
    fn resume_call(&self, callee: &str, args: &[Expr]) -> bool {
        self.is_reentrant(callee) && self.virtual_rest_use(callee, args).is_none()
    }

    fn contains_reentrant(&self, e: &Expr) -> bool {
        match &e.kind {
            ExprKind::Call { callee, args, .. }
                if self.virtual_rest_use(callee, args).is_some() =>
            {
                args[1..].iter().any(|a| self.contains_reentrant(a))
            }
            ExprKind::Call { callee, args, .. } => {
                self.is_reentrant(callee) || args.iter().any(|a| self.contains_reentrant(a))
            }
            ExprKind::Unary(_, x) | ExprKind::Paren(x) => self.contains_reentrant(x),
            ExprKind::Binary(_, a, b) => self.contains_reentrant(a) || self.contains_reentrant(b),
            ExprKind::Cond(c, a, b) => {
                self.contains_reentrant(c)
                    || self.contains_reentrant(a)
                    || self.contains_reentrant(b)
            }
            _ => false,
        }
    }
}

/// Where a local lives.
#[derive(Debug, Clone)]
enum Storage {
    Slot(u32),
    /// A typed (non-heap) local of a native: a Rust variable that its slot mirrors
    /// (D2000). Writes go to both; typed reads come from the variable.
    Reg(u32, Rep),
    Arg(u32),
    /// A Rust variable (leaf functions).
    Var(String),
}

#[derive(Debug, Clone)]
struct Local {
    ty: Type,
    at: Storage,
}

/// The shared part of both emitters: scopes, typing and pure expressions.
struct Env<'f> {
    f: &'f Function,
    scopes: Vec<HashMap<String, Local>>,
}

impl Env<'_> {
    fn lookup(&self, name: &str) -> &Local {
        self.scopes
            .iter()
            .rev()
            .find_map(|s| s.get(name))
            .unwrap_or_else(|| panic!("bgen: unknown local {name}"))
    }

    fn declare(&mut self, name: &str, ty: Type, at: Storage) {
        self.scopes
            .last_mut()
            .unwrap()
            .insert(name.to_string(), Local { ty, at });
    }

    /// The type of `e` (the program is checked: this mirrors the checker).
    fn ty(&self, cx: &Cx, e: &Expr) -> Type {
        match &e.kind {
            ExprKind::Ident(n) => self.lookup(n).ty,
            ExprKind::This => self.f.this_ty.as_ref().map_or(Type::Value, |t| t.ty),
            ExprKind::NewTarget => Type::Value,
            ExprKind::Undefined => Type::Undefined,
            ExprKind::Null => Type::Null,
            ExprKind::Bool(_) => Type::Bool,
            ExprKind::Num(v, _) => literal_type(*v),
            ExprKind::Str(_) => Type::Str,
            ExprKind::Paren(x) => self.ty(cx, x),
            ExprKind::Unary(op, x) => match (op, self.ty(cx, x)) {
                (UnOp::Not, _) => Type::Bool,
                (UnOp::Neg, Type::IntLit(v)) => Type::IntLit(-v),
                (UnOp::Neg, t) => t,
                (UnOp::BitNot, _) => Type::I32,
            },
            ExprKind::Binary(op, a, b) => {
                let (l, r) = (self.ty(cx, a), self.ty(cx, b));
                match op {
                    BinOp::Lt
                    | BinOp::Le
                    | BinOp::Gt
                    | BinOp::Ge
                    | BinOp::StrictEq
                    | BinOp::StrictNe
                    | BinOp::And
                    | BinOp::Or => Type::Bool,
                    BinOp::Add if l == Type::Str || r == Type::Str => Type::Str,
                    BinOp::Add | BinOp::Sub | BinOp::Mul => match (l, r) {
                        (Type::IntLit(x), Type::IntLit(y)) => literal_type(match op {
                            BinOp::Add => x + y,
                            BinOp::Sub => x - y,
                            _ => x * y,
                        }),
                        _ => unify_numeric(l, r).unwrap_or(Type::F64),
                    },
                    BinOp::Div | BinOp::Rem => Type::F64,
                    BinOp::UShr => Type::U32,
                    _ => Type::I32,
                }
            }
            ExprKind::Cond(_, a, b) => {
                let (at, bt) = (self.ty(cx, a), self.ty(cx, b));
                match (at, bt) {
                    (Type::IntLit(x), Type::IntLit(y)) => {
                        Type::IntLit(if x.min(y) < 0.0 { x.min(y) } else { x.max(y) })
                    }
                    (Type::IntLit(_) | Type::NumLit, Type::IntLit(_) | Type::NumLit) => {
                        Type::NumLit
                    }
                    _ if crate::check::assignable(at, bt) => bt,
                    _ => at,
                }
            }
            ExprKind::Call { callee, .. } => cx.callee(callee).1.ret,
        }
    }

    /// The operand type of an arithmetic or relational operator (literals become f64,
    /// unless they meet an integer type).
    fn operand_type(&self, cx: &Cx, a: &Expr, b: &Expr) -> Type {
        match unify_numeric(self.ty(cx, a), self.ty(cx, b)) {
            Some(Type::IntLit(_) | Type::NumLit) | None => Type::F64,
            Some(t) => t,
        }
    }

    fn read(&self, l: &Local) -> String {
        match &l.at {
            Storage::Slot(i) => decode(format!("ex.n_slot({i})"), l.ty),
            Storage::Reg(i, r) => reg_name(*i, *r),
            Storage::Arg(i) => decode(format!("ex.n_arg({i})"), l.ty),
            Storage::Var(v) => v.clone(),
        }
    }
}

/// `{ let a0 = ..; ..; <call with a0..> }`: arguments are evaluated first and in order,
/// so that calls on `ex` never nest.
fn with_args(args: &[String], call: impl FnOnce(&[String]) -> String) -> String {
    if args.is_empty() {
        return call(&[]);
    }
    let names: Vec<String> = (0..args.len()).map(|i| format!("a{i}")).collect();
    let mut s = String::from("{ ");
    for (n, a) in names.iter().zip(args) {
        let _ = write!(s, "let {n} = {a}; ");
    }
    s.push_str(&call(&names));
    s.push_str(" }");
    s
}

fn fill(template: &str, args: &[String]) -> String {
    let mut s = template.to_string();
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), a);
    }
    s
}

/// Pure expression emission (no resume points inside), shared by both emitters.
trait Pure<'a> {
    fn env(&self) -> &Env<'_>;
    fn cx(&mut self) -> &mut Cx<'a>;
    fn cx_ref(&self) -> &Cx<'a>;

    /// Whether the expression being lowered is a whole statement (its value assigned,
    /// returned or dropped), and clears that: then no other heap Value is live in a Rust
    /// local while its outermost call runs, so that call may collect (D1900).
    fn take_root(&mut self) -> bool {
        false
    }

    /// `e` (no reentrant calls) as Rust code of representation `want`.
    fn pure(&mut self, e: &Expr, want: Rep) -> Code {
        let root = self.take_root();
        match &e.kind {
            ExprKind::Ident(n) => {
                let l = self.env().lookup(n).clone();
                // Slots hold canonical Values: read them as they are.
                match (&l.at, want) {
                    (Storage::Slot(i) | Storage::Reg(i, _), Rep::Val) => {
                        Code::pure(format!("ex.n_slot({i})"))
                    }
                    (Storage::Arg(i), Rep::Val) => Code::pure(format!("ex.n_arg({i})")),
                    _ => Code::pure(coerce(self.env().read(&l), rep(l.ty), want)),
                }
            }
            ExprKind::This => {
                let t = self.env().ty(self.cx_ref(), e);
                Code::pure(coerce(decode("ex.n_this()".into(), t), rep(t), want))
            }
            ExprKind::NewTarget => Code::pure("ex.n_new_target()"),
            ExprKind::Undefined => Code::pure("Value::UNDEFINED"),
            ExprKind::Null => Code::pure("Value::NULL"),
            ExprKind::Bool(b) => Code::pure(coerce(b.to_string(), Rep::Bool, want)),
            ExprKind::Num(v, _) => Code::pure(literal(*v, want)),
            ExprKind::Str(units) => match rust_str(units) {
                Some(s) => Code::effect(format!("ex.n_str({s})?")),
                None => {
                    let units: Vec<String> = units.iter().map(|u| format!("{u:#06x}")).collect();
                    Code::effect(format!("ex.n_str16(&[{}])?", units.join(", ")))
                }
            },
            ExprKind::Paren(x) => self.pure(x, want),
            ExprKind::Unary(op, x) => {
                let t = self.env().ty(self.cx_ref(), e);
                if let (UnOp::Neg, Type::IntLit(v)) = (op, t) {
                    return Code::pure(literal(v, want));
                }
                let r = if *op == UnOp::Not { Rep::Bool } else { rep(t) };
                let inner = self.pure(x, r);
                let s = match (op, r) {
                    (UnOp::Not, _) | (UnOp::BitNot, _) => format!("(!{})", inner.s),
                    (UnOp::Neg, Rep::F64) => format!("(-{})", inner.s),
                    (UnOp::Neg, _) => format!("ck({}.checked_neg())?", inner.s),
                };
                Code {
                    s: coerce(s, r, want),
                    effect: inner.effect,
                }
            }
            ExprKind::Binary(op, a, b) => {
                let (ca, cb, ty) = self.binary_operands(*op, a, b);
                let effect = ca.effect || cb.effect;
                let (s, r) = combine(*op, ty, ca.s, cb.s);
                let s = if root && matches!(ty, OpType::Str) {
                    concat_gc(s)
                } else {
                    s
                };
                Code {
                    s: coerce(s, r, want),
                    effect,
                }
            }
            ExprKind::Cond(c, a, b) => {
                let t = self.env().ty(self.cx_ref(), e);
                let r = if matches!(t, Type::IntLit(_) | Type::NumLit) {
                    want
                } else {
                    rep(t)
                };
                let cc = self.pure(c, Rep::Bool);
                let ca = self.pure(a, r);
                let cb = self.pure(b, r);
                Code {
                    s: coerce(
                        format!("(if {} {{ {} }} else {{ {} }})", cc.s, ca.s, cb.s),
                        r,
                        want,
                    ),
                    effect: cc.effect || ca.effect || cb.effect,
                }
            }
            ExprKind::Call { callee, args, .. } => {
                if let Some(k) = self.cx_ref().virtual_rest_use(callee, args) {
                    let s = if callee == "Get" {
                        let i = self.lower_operand(&args[1], Rep::Val);
                        with_args(&[i.s], |n| format!("ex.n_rest_get({k}, {})", n[0]))
                    } else {
                        format!("ex.n_rest_len({k})")
                    };
                    let ret = self.cx_ref().callee(callee).1.ret;
                    return Code::pure(coerce(decode(s, ret), rep(ret), want));
                }
                let codes = self.call_args(callee, args, e.span);
                self.leaf_call(callee, codes, want, e.span, root)
            }
        }
    }

    /// The operand type of a binary operator and the representation of its operands.
    fn operands(&self, op: BinOp, a: &Expr, b: &Expr) -> (OpType, Rep) {
        let cx = self.cx_ref();
        let env = self.env();
        let (lt, rt) = (env.ty(cx, a), env.ty(cx, b));
        let ty = match op {
            BinOp::And | BinOp::Or => OpType::Bool,
            BinOp::Add if lt == Type::Str || rt == Type::Str => OpType::Str,
            BinOp::StrictEq | BinOp::StrictNe => {
                if lt.is_numeric() && rt.is_numeric() {
                    OpType::Num(match unify_numeric(lt, rt) {
                        Some(Type::IntLit(_) | Type::NumLit) | None => Type::F64,
                        Some(t) => t,
                    })
                } else if lt == Type::Bool && rt == Type::Bool {
                    OpType::Bool
                } else if rt == Type::Undefined {
                    OpType::IsUndefined(false)
                } else if lt == Type::Undefined {
                    OpType::IsUndefined(true)
                } else if rt == Type::Null {
                    OpType::IsNull(false)
                } else if lt == Type::Null {
                    OpType::IsNull(true)
                } else {
                    OpType::Value
                }
            }
            BinOp::Div | BinOp::Rem => OpType::Num(Type::F64),
            BinOp::BitAnd
            | BinOp::BitOr
            | BinOp::BitXor
            | BinOp::Shl
            | BinOp::Shr
            | BinOp::UShr => OpType::Num(Type::I32),
            _ => {
                if let (Type::IntLit(x), Type::IntLit(y), BinOp::Add | BinOp::Sub | BinOp::Mul) =
                    (lt, rt, op)
                {
                    OpType::Fold(match op {
                        BinOp::Add => x + y,
                        BinOp::Sub => x - y,
                        _ => x * y,
                    })
                } else {
                    OpType::Num(env.operand_type(cx, a, b))
                }
            }
        };
        (ty, op_rep(ty))
    }

    /// Both operands of a binary operator (nothing to emit for folded literals).
    fn binary_operands(&mut self, op: BinOp, a: &Expr, b: &Expr) -> (Code, Code, OpType) {
        let (ty, r) = self.operands(op, a, b);
        if let OpType::Fold(_) = ty {
            return (Code::pure(""), Code::pure(""), ty);
        }
        let ca = self.lower_operand(a, r);
        let cb = self.lower_operand(b, r);
        (ca, cb, ty)
    }

    /// An operand: `pure` here; the FSM overrides it to lower resume points.
    fn lower_operand(&mut self, e: &Expr, want: Rep) -> Code {
        self.pure(e, want)
    }

    /// The arguments of a call, each in the callee's parameter representation (Values
    /// for intrinsics called through `call_intrinsic`).
    fn call_args(&mut self, callee: &str, args: &[Expr], _span: Span) -> Vec<Code> {
        let (kind, sig) = self.cx_ref().callee(callee);
        args.iter()
            .enumerate()
            .map(|(i, a)| {
                let want = match kind {
                    Callee::Builtin(b) if !self.cx_ref().reentrant[b] => {
                        sig.params.get(i).map(|p| rep(p.0)).unwrap_or(Rep::Val)
                    }
                    _ => Rep::Val,
                };
                self.lower_operand(a, want)
            })
            .collect()
    }

    /// A call of a leaf intrinsic or leaf builtin with its argument codes.
    fn leaf_call(
        &mut self,
        callee: &str,
        args: Vec<Code>,
        want: Rep,
        span: Span,
        root: bool,
    ) -> Code {
        let (kind, sig) = self.cx_ref().callee(callee);
        let strs: Vec<String> = args.iter().map(|c| c.s.clone()).collect();
        let ret = sig.ret;
        let natural = if matches!(ret, Type::Void | Type::Never) {
            want
        } else {
            rep(ret)
        };
        let s = match kind {
            Callee::Intrinsic { .. } => {
                if let Some(t) = inline_leaf(callee) {
                    let s = with_args(&strs, |n| fill(t, n));
                    // Inline forms give the typed result directly.
                    return Code::effect(coerce(s, natural, want));
                }
                let id = self.cx().id(callee);
                // As a whole statement, an intrinsic D1700 retries is retried (D1900).
                let f = if root && RETRY_LEAVES.contains(&callee) {
                    "n_leaf_gc"
                } else {
                    "n_leaf"
                };
                decode(
                    with_args(&strs, |n| format!("ex.{f}({id}, &[{}])?", n.join(", "))),
                    ret,
                )
            }
            Callee::Builtin(b) => {
                if sig.rest.is_some() {
                    self.cx().errors.push(Diagnostic::new(
                        span,
                        format!("the Rust backend cannot call `{callee}` (a rest parameter) yet"),
                    ));
                }
                let mut strs = strs;
                for (i, (t, _)) in sig.params.iter().enumerate().skip(strs.len()) {
                    if rep(*t) != Rep::Val {
                        self.cx().errors.push(Diagnostic::new(
                            span,
                            format!("the Rust backend needs argument {} of `{callee}`", i + 1),
                        ));
                    }
                    strs.push("Value::UNDEFINED".into());
                }
                let cx = self.cx();
                if cx.leaf_done.insert(b) {
                    cx.leaves.push(b);
                }
                with_args(&strs, |n| {
                    let mut all = vec!["ex".to_string()];
                    all.extend(n.iter().cloned());
                    format!("{}({})?", leaf_fn(callee), all.join(", "))
                })
            }
        };
        Code::effect(if matches!(ret, Type::Void | Type::Never) {
            s
        } else {
            coerce(s, natural, want)
        })
    }
}

#[derive(Debug, Clone, Copy, PartialEq)]
enum OpType {
    Num(Type),
    Bool,
    Str,
    Value,
    /// `x === undefined` (true: the literal is on the left).
    IsUndefined(bool),
    IsNull(bool),
    /// Integer literal arithmetic, folded.
    Fold(f64),
}

/// The Rust code of `a op b` and its representation.
fn combine(op: BinOp, ty: OpType, a: String, b: String) -> (String, Rep) {
    let ne = op == BinOp::StrictNe;
    let not = if ne { "!" } else { "" };
    match ty {
        OpType::Fold(v) => (literal(v, Rep::F64), Rep::F64),
        OpType::Bool => match op {
            BinOp::And => (format!("({a} && {b})"), Rep::Bool),
            BinOp::Or => (format!("({a} || {b})"), Rep::Bool),
            _ => (
                format!("({a} {} {b})", if ne { "!=" } else { "==" }),
                Rep::Bool,
            ),
        },
        OpType::Str => (
            with_args(&[a, b], |n| format!("ex.n_concat({}, {})?", n[0], n[1])),
            Rep::Val,
        ),
        OpType::Value => (
            with_args(&[a, b], |n| {
                format!("{not}ex.n_strict_eq({}, {})", n[0], n[1])
            }),
            Rep::Bool,
        ),
        OpType::IsUndefined(left) => (
            format!("{not}{}.is_undefined()", if left { b } else { a }),
            Rep::Bool,
        ),
        OpType::IsNull(left) => (
            format!("{not}{}.is_null()", if left { b } else { a }),
            Rep::Bool,
        ),
        OpType::Num(t) => {
            let r = rep(t);
            let int = matches!(r, Rep::I32 | Rep::U32);
            let bool_op = |o: &str| (format!("({a} {o} {b})"), Rep::Bool);
            match op {
                BinOp::Lt => bool_op("<"),
                BinOp::Le => bool_op("<="),
                BinOp::Gt => bool_op(">"),
                BinOp::Ge => bool_op(">="),
                BinOp::StrictEq => bool_op("=="),
                BinOp::StrictNe => bool_op("!="),
                BinOp::Add if int => (format!("ck({a}.checked_add({b}))?"), r),
                BinOp::Sub if int => (format!("ck({a}.checked_sub({b}))?"), r),
                BinOp::Mul if int => (format!("ck({a}.checked_mul({b}))?"), r),
                BinOp::Add => (format!("({a} + {b})"), r),
                BinOp::Sub => (format!("({a} - {b})"), r),
                BinOp::Mul => (format!("({a} * {b})"), r),
                BinOp::Div => (format!("({a} / {b})"), Rep::F64),
                BinOp::Rem => (format!("({a} % {b})"), Rep::F64),
                BinOp::BitAnd => (format!("({a} & {b})"), Rep::I32),
                BinOp::BitOr => (format!("({a} | {b})"), Rep::I32),
                BinOp::BitXor => (format!("({a} ^ {b})"), Rep::I32),
                BinOp::Shl => (format!("{a}.wrapping_shl({b} as u32)"), Rep::I32),
                BinOp::Shr => (format!("{a}.wrapping_shr({b} as u32)"), Rep::I32),
                BinOp::UShr => (format!("({a} as u32).wrapping_shr({b} as u32)"), Rep::U32),
                BinOp::And | BinOp::Or => unreachable!(),
            }
        }
    }
}

// ---- the state machine of a @native builtin -----------------------------------------------

#[derive(Debug, Clone)]
enum Term {
    Goto(usize, bool),
    If(String, (usize, bool), (usize, bool)),
    /// `code` evaluates to `Result<Flow, Fault>`; resumes at `next`.
    Call(String, usize),
    Return(String),
    Throw(String),
}

#[derive(Debug, Default, Clone)]
struct Bb {
    code: Vec<String>,
    term: Option<Term>,
    /// Innermost try region.
    try_ctx: Option<usize>,
}

struct FsmCode {
    params: u32,
    locals: u32,
    text: String,
}

struct Fsm<'a, 'c> {
    cx: &'c mut Cx<'a>,
    env: Env<'a>,
    bbs: Vec<Bb>,
    cur: usize,
    slots: u32,
    free_temps: Vec<u32>,
    used_temps: Vec<u32>,
    /// (break target, continue target, continue is a back-edge, `finallys` depth)
    loops: Vec<(usize, usize, bool, usize)>,
    /// The `finally` blocks around the current statement, innermost last: jumps out of
    /// them (`return`, `break`, `continue`) run their copies first.
    finallys: Vec<Finally>,
    /// (catch block, exception slot) per try region, and the current region.
    tries: Vec<(usize, u32)>,
    try_ctx: Option<usize>,
    /// Inlined builtin calls being lowered, innermost last.
    inlines: Vec<Inline>,
    /// The next expression lowered is a whole statement (`Pure::take_root`).
    root: bool,
}

/// An enclosing `finally` block: its statements and the try region outside it.
struct Finally {
    body: Vec<Stmt>,
    ctx: Option<usize>,
}

/// An inlined call of a builtin (a small, internal helper): its body is lowered into the
/// caller's state machine, its locals in pooled slots, `return` stores the result and
/// jumps to `join`.
struct Inline {
    builtin: usize,
    result: Option<Storage>,
    join: usize,
    slots: Vec<u32>,
}

impl<'a> Pure<'a> for Fsm<'a, '_> {
    fn env(&self) -> &Env<'_> {
        &self.env
    }
    fn cx(&mut self) -> &mut Cx<'a> {
        self.cx
    }
    fn cx_ref(&self) -> &Cx<'a> {
        self.cx
    }
    fn lower_operand(&mut self, e: &Expr, want: Rep) -> Code {
        self.lower(e, want)
    }
    fn take_root(&mut self) -> bool {
        core::mem::take(&mut self.root)
    }
}

impl<'a, 'c> Fsm<'a, 'c> {
    fn emit(
        cx: &'c mut Cx<'a>,
        index: usize,
        f: &'a Function,
        sources: &Sources,
        origin: &str,
    ) -> Option<FsmCode> {
        let errors_before = cx.errors.len();
        let mut m = Fsm {
            cx,
            env: Env {
                f,
                scopes: vec![HashMap::new()],
            },
            bbs: vec![Bb::default()],
            cur: 0,
            slots: 0,
            free_temps: Vec::new(),
            used_temps: Vec::new(),
            loops: Vec::new(),
            finallys: Vec::new(),
            root: false,
            tries: Vec::new(),
            try_ctx: None,
            inlines: vec![Inline {
                builtin: index,
                result: None,
                join: 0,
                slots: Vec::new(),
            }],
        };
        let mut params = 0;
        m.cx.virtual_rest = None;
        for p in &f.params {
            if p.rest && rest_is_virtual(&f.body.stmts, &p.name) {
                m.cx.virtual_rest = Some((p.name.clone(), params));
            } else if p.rest {
                let s = m.slot();
                m.env.declare(&p.name, Type::Obj, Storage::Slot(s));
                m.push(format!(
                    "let v = ex.n_rest({params})?; ex.n_set_slot({s}, v);"
                ));
            } else {
                m.env.declare(&p.name, p.ty.ty, Storage::Arg(params));
                params += 1;
            }
        }
        m.block(&f.body.stmts, sources);
        m.cx.virtual_rest = None;
        if m.bbs[m.cur].term.is_none() {
            m.term(Term::Return("Value::UNDEFINED".into()));
        }
        if m.cx.errors.len() > errors_before {
            return None;
        }
        Some(m.finish(f, params, origin))
    }

    fn slot(&mut self) -> u32 {
        self.slots += 1;
        self.slots - 1
    }

    /// A slot for a local: fresh in the builtin itself, pooled in an inlined body (dead
    /// after its call).
    fn local_slot(&mut self) -> u32 {
        if self.inlines.len() == 1 {
            return self.slot();
        }
        let s = self.free_temps.pop().unwrap_or_else(|| {
            self.slots += 1;
            self.slots - 1
        });
        self.inlines.last_mut().unwrap().slots.push(s);
        s
    }

    /// Whether a call of builtin `b` is inlined: a small internal helper (no installs,
    /// so it never shows in a stack trace) without `this`, rest parameters, `try` or
    /// `new.target`, not already being inlined.
    fn inlinable(&self, b: usize) -> bool {
        let bi = &self.cx.p.builtins[b];
        let f = self.cx.p.function(bi);
        !bi.native
            && bi.installs.is_empty()
            && f.this_ty.is_none()
            && !f.params.iter().any(|p| p.rest)
            && self.inlines.len() < 4
            && !self.inlines.iter().any(|i| i.builtin == b)
            && fast_reentrant(&f.name).is_none()
            && inline_size(&f.body.stmts) <= INLINE_SIZE
            && !uses_new_target(&f.body.stmts)
    }

    /// Lowers a call of builtin `b` inline.
    fn inline_call(&mut self, b: usize, args: &[Expr], into: Option<Storage>) {
        let f: &'a Function = self.cx.p.function(&self.cx.p.builtins[b]);
        let name = &f.name;
        let codes = self.spilled_args(name, args);
        // The callee's frame: its parameters in pooled slots, a fresh scope chain.
        let saved_temps = std::mem::take(&mut self.used_temps);
        let join = self.new_bb();
        self.inlines.push(Inline {
            builtin: b,
            result: into,
            join,
            slots: Vec::new(),
        });
        self.push(format!("// inlined: {name}"));
        let mut params = Vec::new();
        for (i, p) in f.params.iter().enumerate() {
            let slot = self.local_slot();
            let v = match codes.get(i) {
                // Arguments of a reentrant builtin are lowered as Values.
                Some(c) => c.s.clone(),
                None => "Value::UNDEFINED".into(),
            };
            self.push(format!("let v = {v}; ex.n_set_slot({slot}, v);"));
            params.push((p.name.clone(), p.ty.ty, slot));
        }
        let env = std::mem::replace(
            &mut self.env,
            Env {
                f,
                scopes: vec![HashMap::new()],
            },
        );
        for (n, t, slot) in params {
            self.env.declare(&n, t, Storage::Slot(slot));
        }
        let sources = Sources::default();
        let rest = self.cx.virtual_rest.take();
        self.block(&f.body.stmts, &sources);
        self.cx.virtual_rest = rest;
        self.term_to(Term::Goto(join, false), join);
        self.env = env;
        let inl = self.inlines.pop().unwrap();
        self.free_temps.append(&mut self.used_temps);
        self.free_temps.extend(inl.slots);
        self.used_temps = saved_temps;
    }

    fn temp(&mut self) -> u32 {
        let t = self.free_temps.pop().unwrap_or_else(|| {
            self.slots += 1;
            self.slots - 1
        });
        self.used_temps.push(t);
        t
    }

    /// The fused dense HasProperty + Get (D2090). `pre` holds the lowered
    /// `HasProperty(o, k)` call, and the branch `bt` its true side. If that side starts with
    /// `Get(o, k)` on the same operands, the check state `chk` runs `n_dense_pre`. When
    /// `o` is an Array with an element at `k`, both calls are what their own fast paths
    /// would answer (true, the element), so `chk` jumps straight to the Get's resume state
    /// with the element as its result. Otherwise `chk` just goes on to `pre`.
    fn fuse_has_get(&mut self, chk: usize, pre: usize, bt: usize) {
        let blank = |code: &[String]| code.iter().all(|c| c.starts_with("//"));
        let norm = |c: &str| -> String {
            let mut out = String::new();
            let mut rest = c;
            while let Some(i) = rest.find("__BB") {
                out.push_str(&rest[..i]);
                let tail = &rest[i + 4..];
                let end = tail.find("__").map_or(tail.len(), |j| j + 2);
                rest = &tail[end..];
            }
            out.push_str(rest);
            out
        };
        let has = match &self.bbs[pre] {
            Bb {
                code,
                term: Some(Term::Call(c, _)),
                ..
            } if blank(code) => c.clone(),
            _ => return,
        };
        let get_next = match &self.bbs[bt] {
            Bb {
                code,
                term: Some(Term::Call(c, next)),
                ..
            } if blank(code)
                && has.contains("ex.n_has_property(")
                && norm(c) == norm(&has).replace("ex.n_has_property(", "ex.n_get(") =>
            {
                *next
            }
            _ => return,
        };
        // `{ let a0 = ..; let a1 = ..; ex.n_has_property(&[a0, a1], ..) }` with the call
        // replaced: the operands are evaluated the same way.
        let Some(i) = has.find("ex.n_has_property(") else {
            return;
        };
        let cond = format!("{}ex.n_dense_pre(a0, a1) }}", &has[..i]);
        if !has.starts_with("{ let a0 = ") {
            return;
        }
        self.bbs[chk].term = Some(Term::If(cond, (get_next, false), (pre, false)));
    }

    fn end_statement(&mut self) {
        self.free_temps.append(&mut self.used_temps);
    }

    fn push(&mut self, s: String) {
        self.bbs[self.cur].code.push(s);
    }

    fn new_bb(&mut self) -> usize {
        self.bbs.push(Bb {
            try_ctx: self.try_ctx,
            ..Default::default()
        });
        self.bbs.len() - 1
    }

    fn term(&mut self, t: Term) {
        if self.bbs[self.cur].term.is_none() {
            self.bbs[self.cur].term = Some(t);
        }
    }

    /// Ends the current block with `t` and continues in `next`.
    fn term_to(&mut self, t: Term, next: usize) {
        self.term(t);
        self.cur = next;
    }

    /// Continues in a fresh (unreachable) block after a jump.
    fn dead(&mut self) {
        let b = self.new_bb();
        self.cur = b;
    }

    fn spill(&mut self, c: Code, r: Rep) -> Code {
        let t = self.temp();
        self.push(format!(
            "let v = {}; ex.n_set_slot({t}, v);",
            coerce(c.s, r, Rep::Val)
        ));
        Code::pure(decode(format!("ex.n_slot({t})"), rep_type(r)))
    }

    /// `e` as code of representation `want`, valid in the block current afterwards.
    fn lower(&mut self, e: &Expr, want: Rep) -> Code {
        if !self.cx.contains_reentrant(e) {
            return self.pure(e, want);
        }
        let root = self.take_root();
        match &e.kind {
            ExprKind::Paren(x) => self.lower(x, want),
            ExprKind::Call { callee, args, .. } if self.cx.resume_call(callee, args) => {
                let t = self.temp();
                self.call(callee, args, e.span, Some(Storage::Slot(t)));
                let ret = self.cx.callee(callee).1.ret;
                Code::pure(coerce(
                    decode(format!("ex.n_slot({t})"), ret),
                    rep(ret),
                    want,
                ))
            }
            ExprKind::Call { callee, args, .. } => {
                let codes = self.spilled_args(callee, args);
                self.leaf_call(callee, codes, want, e.span, root)
            }
            ExprKind::Unary(..) => {
                // Lower the operand to a temporary, then apply the operator purely.
                self.lower_via_temp(e, want)
            }
            ExprKind::Binary(op @ (BinOp::And | BinOp::Or), a, b)
                if self.cx.contains_reentrant(b) =>
            {
                // t = a; if (t is not decided) t = b
                let t = self.temp();
                let ca = self.lower(a, Rep::Bool);
                self.push(format!(
                    "let v = {}; ex.n_set_slot({t}, Value::bool(v));",
                    ca.s
                ));
                let (rhs, join) = (self.new_bb(), self.new_bb());
                let cond = format!("bool_of(ex.n_slot({t}))");
                let cond = if *op == BinOp::And {
                    cond
                } else {
                    format!("!{cond}")
                };
                self.term_to(Term::If(cond, (rhs, false), (join, false)), rhs);
                let cb = self.lower(b, Rep::Bool);
                self.push(format!(
                    "let v = {}; ex.n_set_slot({t}, Value::bool(v));",
                    cb.s
                ));
                self.term_to(Term::Goto(join, false), join);
                Code::pure(coerce(format!("bool_of(ex.n_slot({t}))"), Rep::Bool, want))
            }
            ExprKind::Binary(op, a, b) => {
                let (ty, r) = self.operands(*op, a, b);
                let (mut ca, cb) = if let OpType::Fold(_) = ty {
                    (Code::pure(""), Code::pure(""))
                } else {
                    let mut ca = self.lower(a, r);
                    if ca.effect && self.cx.contains_reentrant(b) {
                        ca = self.spill(ca, r);
                    }
                    (ca, self.lower(b, r))
                };
                let _ = &mut ca;
                let effect = ca.effect || cb.effect;
                let (s, r) = combine(*op, ty, ca.s, cb.s);
                let s = if root && matches!(ty, OpType::Str) {
                    concat_gc(s)
                } else {
                    s
                };
                Code {
                    s: coerce(s, r, want),
                    effect,
                }
            }
            ExprKind::Cond(c, a, b) => {
                let ty = self.env.ty(self.cx, e);
                let r = if matches!(ty, Type::IntLit(_) | Type::NumLit) {
                    want
                } else {
                    rep(ty)
                };
                let t = self.temp();
                let cc = self.lower(c, Rep::Bool);
                let (ba, bb, join) = (self.new_bb(), self.new_bb(), self.new_bb());
                self.term_to(Term::If(cc.s, (ba, false), (bb, false)), ba);
                let ca = self.lower(a, r);
                self.push(format!(
                    "let v = {}; ex.n_set_slot({t}, v);",
                    coerce(ca.s, r, Rep::Val)
                ));
                self.term_to(Term::Goto(join, false), bb);
                let cb = self.lower(b, r);
                self.push(format!(
                    "let v = {}; ex.n_set_slot({t}, v);",
                    coerce(cb.s, r, Rep::Val)
                ));
                self.term_to(Term::Goto(join, false), join);
                Code::pure(coerce(
                    decode(format!("ex.n_slot({t})"), rep_type(r)),
                    r,
                    want,
                ))
            }
            _ => self.pure(e, want),
        }
    }

    fn lower_via_temp(&mut self, e: &Expr, want: Rep) -> Code {
        let ExprKind::Unary(_, x) = &e.kind else {
            unreachable!()
        };
        let xt = self.env.ty(self.cx, x);
        let xr = rep(xt);
        let cx = self.lower(x, xr);
        let t = self.spill(cx, xr);
        // Re-emit the operator over the temporary.
        let ty = self.env.ty(self.cx, e);
        let ExprKind::Unary(op, _) = &e.kind else {
            unreachable!()
        };
        let r = if *op == UnOp::Not { Rep::Bool } else { rep(ty) };
        let s = match (op, r) {
            (UnOp::Not, _) | (UnOp::BitNot, _) => format!("(!{})", t.s),
            (UnOp::Neg, Rep::F64) => format!("(-{})", t.s),
            (UnOp::Neg, _) => format!("ck({}.checked_neg())?", t.s),
        };
        Code::pure(coerce(s, r, want))
    }

    /// Argument codes in order; those with effects before a later resume point are
    /// spilled.
    fn spilled_args(&mut self, callee: &str, args: &[Expr]) -> Vec<Code> {
        let (kind, sig) = self.cx.callee(callee);
        let mut out = Vec::new();
        for (i, a) in args.iter().enumerate() {
            let want = match kind {
                Callee::Builtin(b) if !self.cx.reentrant[b] => {
                    sig.params.get(i).map(|p| rep(p.0)).unwrap_or(Rep::Val)
                }
                _ => Rep::Val,
            };
            let mut c = self.lower(a, want);
            if c.effect && args[i + 1..].iter().any(|x| self.cx.contains_reentrant(x)) {
                c = self.spill(c, want);
            }
            out.push(c);
        }
        out
    }

    /// A reentrant call (a resume point); its result goes to `into` (or is dropped).
    fn call(&mut self, callee: &str, args: &[Expr], span: Span, into: Option<Storage>) {
        let (kind, sig) = self.cx.callee(callee);
        if let Callee::Builtin(b) = kind
            && self.inlinable(b)
        {
            return self.inline_call(b, args, into);
        }
        if let Callee::Builtin(b) = kind
            && !self.cx.p.builtins[b].intrinsic
        {
            self.cx.errors.push(Diagnostic::new(
                span,
                format!("`{callee}` may run user code: a @native builtin can call it only if it is `@intrinsic`"),
            ));
        }
        let codes = self.spilled_args(callee, args);
        let mut vals: Vec<String> = codes.into_iter().map(|c| c.s).collect();
        // Missing optional arguments of a builtin are undefined in its frame anyway.
        let _ = &sig;
        let next = self.new_bb();
        let comment = format!("// resume point: {callee}");
        self.push(comment);
        let code = match fast_reentrant(callee) {
            Some(helper) if vals.len() == fast_arity(callee) => with_args(&vals, |n| {
                format!("ex.{helper}(&[{}], __BB{next}__)", n.join(", "))
            }),
            _ => {
                let id = self.cx.id(callee);
                if vals.is_empty() {
                    vals.clear();
                }
                with_args(&vals, |n| {
                    format!("ex.n_call({id}, &[{}], __BB{next}__)", n.join(", "))
                })
            }
        };
        self.term_to(Term::Call(code, next), next);
        match into {
            Some(Storage::Slot(s)) => {
                self.push(format!("let r = ex.n_result(); ex.n_set_slot({s}, r);"))
            }
            Some(Storage::Reg(s, r)) => self.push(format!(
                "let r = ex.n_result(); ex.n_set_slot({s}, r); {} = {};",
                reg_name(s, r),
                decode_rep("r".into(), r)
            )),
            Some(Storage::Arg(a)) => {
                self.push(format!("let r = ex.n_result(); ex.n_set_arg({a}, r);"))
            }
            Some(Storage::Var(_)) => unreachable!(),
            None => self.push("ex.n_result();".into()),
        }
    }

    fn store(&mut self, at: &Storage, ty: Type, c: Code) {
        let v = coerce(c.s.clone(), rep(ty), Rep::Val);
        match at {
            Storage::Slot(s) => self.push(format!("let v = {v}; ex.n_set_slot({s}, v);")),
            Storage::Reg(s, r) => self.push(format!(
                "let rv = {}; {} = rv; ex.n_set_slot({s}, {});",
                c.s,
                reg_name(*s, *r),
                coerce("rv".into(), *r, Rep::Val)
            )),
            Storage::Arg(a) => self.push(format!("let v = {v}; ex.n_set_arg({a}, v);")),
            Storage::Var(_) => unreachable!(),
        }
    }

    /// `target = value` for a declaration or an assignment.
    fn assign(&mut self, at: Storage, ty: Type, value: &Expr) {
        if let ExprKind::Call { callee, args, .. } = &value.kind
            && self.cx.resume_call(callee, args)
        {
            // The Value goes straight into the slot (an integer stays an int32 Value).
            return self.call(callee, args, value.span, Some(at));
        }
        self.root = true;
        let c = self.lower(value, rep(ty));
        self.root = false;
        self.store(&at, ty, c);
    }

    fn block(&mut self, stmts: &[Stmt], sources: &Sources) {
        self.env.scopes.push(HashMap::new());
        for s in stmts {
            self.stmt(s, sources);
        }
        self.env.scopes.pop();
    }

    fn sub(&mut self, s: &Stmt, sources: &Sources) {
        match s {
            Stmt::Block(b) => self.block(&b.stmts, sources),
            other => {
                self.env.scopes.push(HashMap::new());
                self.stmt(other, sources);
                self.env.scopes.pop();
            }
        }
    }

    fn stmt(&mut self, s: &Stmt, sources: &Sources) {
        match s {
            Stmt::Decl { name, ty, init, .. } => {
                let slot = self.local_slot();
                let at = match rep(ty.ty) {
                    Rep::Val => Storage::Slot(slot),
                    r => Storage::Reg(slot, r),
                };
                self.assign(at.clone(), ty.ty, init);
                self.env.declare(name, ty.ty, at);
            }
            Stmt::Assign {
                target,
                target_span,
                op,
                value,
                span,
            } => {
                let l = self.env.lookup(target).clone();
                let value = match op.binary() {
                    None => value.clone(),
                    Some(b) => Expr {
                        kind: ExprKind::Binary(
                            b,
                            Box::new(Expr {
                                kind: ExprKind::Ident(target.clone()),
                                span: *target_span,
                            }),
                            Box::new(value.clone()),
                        ),
                        span: *span,
                    },
                };
                self.assign(l.at, l.ty, &value);
            }
            Stmt::Update { target, inc, span } => {
                let l = self.env.lookup(target).clone();
                let one = Expr {
                    kind: ExprKind::Num(1.0, "1".into()),
                    span: *span,
                };
                let e = Expr {
                    kind: ExprKind::Binary(
                        if *inc { BinOp::Add } else { BinOp::Sub },
                        Box::new(Expr {
                            kind: ExprKind::Ident(target.clone()),
                            span: *span,
                        }),
                        Box::new(one),
                    ),
                    span: *span,
                };
                self.assign(l.at, l.ty, &e);
            }
            Stmt::Expr(e) => {
                if let ExprKind::Call { callee, args, .. } = &e.kind
                    && self.cx.resume_call(callee, args)
                {
                    self.call(callee, args, e.span, None);
                } else {
                    self.root = true;
                    let c = self.lower(e, Rep::Val);
                    self.root = false;
                    self.push(format!("let _ = {};", c.s));
                }
            }
            Stmt::If {
                cond, then, els, ..
            } => {
                // `if (HasProperty(o, k)) { .. Get(o, k) ..`: a check state in front (D2090),
                // patched below once the branch is lowered.
                let fuse = matches!(&cond.kind, ExprKind::Call { callee, args, .. }
                    if callee == "HasProperty" && args.len() == 2);
                let chk = if fuse {
                    let (chk, pre) = (self.new_bb(), self.new_bb());
                    self.term_to(Term::Goto(chk, false), chk);
                    self.term_to(Term::Goto(pre, false), pre);
                    Some((chk, pre))
                } else {
                    None
                };
                let c = self.lower(cond, Rep::Bool);
                let (bt, join) = (self.new_bb(), self.new_bb());
                let be = if els.is_some() { self.new_bb() } else { join };
                self.end_statement();
                self.term_to(Term::If(c.s, (bt, false), (be, false)), bt);
                self.sub(then, sources);
                if let Some((chk, pre)) = chk {
                    self.fuse_has_get(chk, pre, bt);
                }
                self.term(Term::Goto(join, false));
                if let Some(e) = els {
                    self.cur = be;
                    self.sub(e, sources);
                    self.term(Term::Goto(join, false));
                }
                self.cur = join;
            }
            Stmt::While { cond, body, .. } => {
                let (head, bbody, exit) = (self.new_bb(), self.new_bb(), self.new_bb());
                self.term_to(Term::Goto(head, false), head);
                let c = self.lower(cond, Rep::Bool);
                self.end_statement();
                self.term_to(Term::If(c.s, (bbody, false), (exit, false)), bbody);
                self.loops.push((exit, head, true, self.finallys.len()));
                self.sub(body, sources);
                self.loops.pop();
                self.term(Term::Goto(head, true));
                self.cur = exit;
            }
            Stmt::DoWhile { body, cond, .. } => {
                let (bbody, bcond, exit) = (self.new_bb(), self.new_bb(), self.new_bb());
                self.term_to(Term::Goto(bbody, false), bbody);
                self.loops.push((exit, bcond, false, self.finallys.len()));
                self.sub(body, sources);
                self.loops.pop();
                self.term_to(Term::Goto(bcond, false), bcond);
                let c = self.lower(cond, Rep::Bool);
                self.end_statement();
                self.term_to(Term::If(c.s, (bbody, true), (exit, false)), exit);
            }
            Stmt::For {
                init,
                cond,
                update,
                body,
                ..
            } => {
                self.env.scopes.push(HashMap::new());
                if let Some(i) = init {
                    self.stmt(i, sources);
                }
                let (head, bbody, bupd, exit) =
                    (self.new_bb(), self.new_bb(), self.new_bb(), self.new_bb());
                self.end_statement();
                self.term_to(Term::Goto(head, false), head);
                match cond {
                    Some(c) => {
                        let c = self.lower(c, Rep::Bool);
                        self.end_statement();
                        self.term_to(Term::If(c.s, (bbody, false), (exit, false)), bbody);
                    }
                    None => self.term_to(Term::Goto(bbody, false), bbody),
                }
                self.loops.push((exit, bupd, false, self.finallys.len()));
                self.sub(body, sources);
                self.loops.pop();
                self.term_to(Term::Goto(bupd, false), bupd);
                if let Some(u) = update {
                    self.stmt(u, sources);
                }
                self.term_to(Term::Goto(head, true), exit);
                self.env.scopes.pop();
            }
            Stmt::Return { value, .. } if self.inlines.len() > 1 => {
                let ret = self.env.f.ret.ty;
                let (result, join) = {
                    let i = self.inlines.last().unwrap();
                    (i.result.clone(), i.join)
                };
                if let Some(v) = value {
                    match result {
                        Some(at) => self.assign(at, ret, v),
                        None => {
                            let c = self.lower(v, Rep::Val);
                            if c.effect {
                                self.push(format!("let _ = {};", c.s));
                            }
                        }
                    }
                }
                self.term(Term::Goto(join, false));
                self.dead();
            }
            Stmt::Return { value, .. } => {
                let v = match value {
                    Some(v) => {
                        let t = self.env.ty(self.cx, v);
                        let want = if matches!(t, Type::IntLit(_) | Type::NumLit) {
                            rep(self.env.f.ret.ty)
                        } else {
                            rep(t)
                        };
                        self.root = true;
                        let c = self.lower(v, want);
                        self.root = false;
                        coerce(c.s, want, Rep::Val)
                    }
                    None => "Value::UNDEFINED".into(),
                };
                let v = if self.finallys.is_empty() {
                    v
                } else {
                    // The value waits in a slot while the finally blocks run.
                    let s = self.slot();
                    self.push(format!("let v = {v}; ex.n_set_slot({s}, v);"));
                    self.run_finallys(0, sources);
                    format!("ex.n_slot({s})")
                };
                self.term(Term::Return(v));
                self.dead();
            }
            Stmt::Throw { value, .. } => {
                let c = self.lower(value, Rep::Val);
                self.term(Term::Throw(c.s));
                self.dead();
            }
            Stmt::Break(_) => {
                let (b, _, _, depth) = *self.loops.last().unwrap();
                self.run_finallys(depth, sources);
                self.term(Term::Goto(b, false));
                self.dead();
            }
            Stmt::Continue(_) => {
                let (_, c, back, depth) = *self.loops.last().unwrap();
                self.run_finallys(depth, sources);
                self.term(Term::Goto(c, back));
                self.dead();
            }
            Stmt::Try {
                body,
                catch,
                finally,
                span,
            } => {
                if let Some(fin) = finally {
                    // `try B catch C finally F` is `try { try B catch C } finally F`.
                    let protected = match catch {
                        Some(_) => vec![Stmt::Try {
                            body: body.clone(),
                            catch: catch.clone(),
                            finally: None,
                            span: *span,
                        }],
                        None => body.stmts.clone(),
                    };
                    self.try_finally(&protected, &fin.stmts, sources);
                    self.end_statement();
                    return;
                }
                let c = catch.as_ref().unwrap();
                let slot = self.slot();
                let outer = self.try_ctx;
                let join = self.new_bb();
                let bcatch = self.new_bb();
                self.tries.push((bcatch, slot));
                self.try_ctx = Some(self.tries.len() - 1);
                let bbody = self.new_bb();
                self.end_statement();
                self.term_to(Term::Goto(bbody, false), bbody);
                self.block(&body.stmts, sources);
                self.term(Term::Goto(join, false));
                self.try_ctx = outer;
                self.cur = bcatch;
                self.env.scopes.push(HashMap::new());
                if let Some((name, _)) = &c.name {
                    self.env.declare(name, Type::Value, Storage::Slot(slot));
                }
                self.block(&c.body.stmts, sources);
                self.env.scopes.pop();
                self.term(Term::Goto(join, false));
                self.cur = join;
            }
            Stmt::Block(b) => self.block(&b.stmts, sources),
        }
        self.end_statement();
    }

    /// `try { body } finally { fin }`: the finally block is copied onto each way out of
    /// the body: after its normal end, on an exception (in a handler region of its own,
    /// which rethrows after it) and before each `return`, `break` and `continue` that
    /// leaves it (`run_finallys`). Each copy runs in the try region outside.
    fn try_finally(&mut self, body: &[Stmt], fin: &[Stmt], sources: &Sources) {
        let slot = self.slot();
        let outer = self.try_ctx;
        let join = self.new_bb();
        let bthrow = self.new_bb();
        self.tries.push((bthrow, slot));
        self.try_ctx = Some(self.tries.len() - 1);
        self.finallys.push(Finally {
            body: fin.to_vec(),
            ctx: outer,
        });
        let bbody = self.new_bb();
        self.end_statement();
        self.term_to(Term::Goto(bbody, false), bbody);
        self.block(body, sources);
        self.finallys.pop();
        self.try_ctx = outer;
        // The normal way out.
        let bnormal = self.new_bb();
        self.term_to(Term::Goto(bnormal, false), bnormal);
        self.block(fin, sources);
        self.term(Term::Goto(join, false));
        // An exception: the finally block, then the exception again.
        self.cur = bthrow;
        self.block(fin, sources);
        self.term(Term::Throw(format!("ex.n_slot({slot})")));
        self.cur = join;
    }

    /// Runs copies of the enclosing finally blocks from the innermost down to depth
    /// `to` (a jump out of them), each in the try region outside it.
    fn run_finallys(&mut self, to: usize, sources: &Sources) {
        let saved = core::mem::take(&mut self.finallys);
        let ctx = self.try_ctx;
        for i in (to..saved.len()).rev() {
            // A jump out of this copy only runs the ones further out.
            self.finallys = saved[..i]
                .iter()
                .map(|f| Finally {
                    body: f.body.clone(),
                    ctx: f.ctx,
                })
                .collect();
            self.try_ctx = saved[i].ctx;
            let b = self.new_bb();
            self.end_statement();
            self.term_to(Term::Goto(b, false), b);
            self.block(&saved[i].body, sources);
        }
        self.finallys = saved;
        self.try_ctx = ctx;
        // Back in the region of the jump (its target decides where it goes).
        let b = self.new_bb();
        self.term_to(Term::Goto(b, false), b);
    }

    /// Prunes unreachable blocks, numbers the states and writes the functions.
    fn finish(self, f: &Function, params: u32, origin: &str) -> FsmCode {
        let n = self.bbs.len();
        // Jump threading: a jump to a block that only jumps on goes to its target (a
        // back-edge anywhere on the way stays one).
        let thread = |(mut t, mut back): (usize, bool)| -> (usize, bool) {
            for _ in 0..n {
                match &self.bbs[t] {
                    Bb {
                        code,
                        term: Some(Term::Goto(next, b)),
                        ..
                    } if code.is_empty() && *next != t => {
                        back |= *b;
                        t = *next;
                    }
                    _ => break,
                }
            }
            (t, back)
        };
        let mut reach = vec![false; n];
        let mut work = vec![0];
        work.extend(self.tries.iter().map(|t| t.0));
        while let Some(b) = work.pop() {
            if reach[b] {
                continue;
            }
            reach[b] = true;
            match &self.bbs[b].term {
                Some(Term::Goto(t, back)) => work.push(thread((*t, *back)).0),
                Some(Term::Call(_, t)) => work.push(*t),
                Some(Term::If(_, t, e)) => {
                    work.push(thread(*t).0);
                    work.push(thread(*e).0);
                }
                _ => {}
            }
        }
        let mut state = vec![u32::MAX; n];
        let mut next = 0;
        for b in 0..n {
            if reach[b] {
                state[b] = next;
                next += 1;
            }
        }
        let goto = |target: (usize, bool)| -> String {
            let (t, back) = thread(target);
            if back {
                format!(
                    "if ex.n_backedge({s}) {{ return Ok(None); }} st = {s}; continue;",
                    s = state[t]
                )
            } else {
                format!("st = {}; continue;", state[t])
            }
        };
        // Registers (D2000): the typed locals live in Rust variables within one run of
        // the function; their slots are written through, so a run that starts at state S
        // loads the registers live into S from the slots and nothing else is needed.
        let term_text = |t: &Option<Term>| -> String {
            match t {
                Some(Term::If(c, _, _)) => c.clone(),
                Some(Term::Call(c, _)) => c.clone(),
                Some(Term::Return(v) | Term::Throw(v)) => v.clone(),
                _ => String::new(),
            }
        };
        type Regs = BTreeSet<(u32, Rep)>;
        let mut all_regs: Regs = BTreeSet::new();
        // Per block: registers read before written, and registers written.
        let mut gen_kill: Vec<(Regs, Regs)> = Vec::with_capacity(n);
        for bb in &self.bbs {
            let (mut used, mut written) = (Regs::new(), Regs::new());
            let t = term_text(&bb.term);
            for line in bb.code.iter().chain(core::iter::once(&t)) {
                for (slot, r, w) in reg_uses(line) {
                    all_regs.insert((slot, r));
                    if w {
                        written.insert((slot, r));
                    } else if !written.contains(&(slot, r)) {
                        used.insert((slot, r));
                    }
                }
            }
            gen_kill.push((used, written));
        }
        let succs = |b: usize| -> Vec<usize> {
            match &self.bbs[b].term {
                Some(Term::Goto(t, _)) => vec![*t],
                Some(Term::If(_, t, e)) => vec![t.0, e.0],
                Some(Term::Call(_, t)) => vec![*t],
                _ => Vec::new(),
            }
        };
        let mut live_in: Vec<Regs> = gen_kill.iter().map(|g| g.0.clone()).collect();
        loop {
            let mut changed = false;
            for b in (0..n).rev() {
                let mut l = gen_kill[b].0.clone();
                for s in succs(b) {
                    for x in &live_in[s] {
                        if !gen_kill[b].1.contains(x) {
                            l.insert(*x);
                        }
                    }
                }
                if l != live_in[b] {
                    live_in[b] = l;
                    changed = true;
                }
            }
            if !changed {
                break;
            }
        }
        let name = &f.name;
        let mut text = String::new();
        let _ = writeln!(text, "// {origin}");
        if !all_regs.is_empty() {
            // (A register written in a state that ends the run is not read again.)
            text.push_str("#[allow(unused_assignments)]\n");
        }
        let _ = writeln!(text, "fn {}(ex: &mut Exec<'_>) -> Step {{", native_fn(name));
        // The state in a Rust local (`ex.pc` follows it for faults and calls), so that
        // LLVM threads `st = N; continue` into a direct jump (D2000).
        text.push_str("    let mut st = ex.n_state();\n");
        for &(slot, r) in &all_regs {
            let (ty, zero) = match r {
                Rep::Bool => ("bool", "false"),
                Rep::I32 => ("i32", "0"),
                Rep::U32 => ("u32", "0"),
                _ => ("f64", "0.0"),
            };
            let _ = writeln!(text, "    let mut {}: {ty} = {zero};", reg_name(slot, r));
        }
        // The entry loads, by state (states with the same live registers share an arm).
        let mut arms: Vec<(Regs, Vec<u32>)> = Vec::new();
        for b in 0..n {
            if !reach[b] || live_in[b].is_empty() {
                continue;
            }
            match arms.iter_mut().find(|a| a.0 == live_in[b]) {
                Some(a) => a.1.push(state[b]),
                None => arms.push((live_in[b].clone(), vec![state[b]])),
            }
        }
        if !arms.is_empty() {
            text.push_str("    match st {\n");
            for (regs, states) in &arms {
                let pats: Vec<String> = states.iter().map(|s| s.to_string()).collect();
                let loads: Vec<String> = regs
                    .iter()
                    .map(|&(slot, r)| {
                        format!(
                            "{} = {};",
                            reg_name(slot, r),
                            decode_rep(format!("ex.n_slot({slot})"), r)
                        )
                    })
                    .collect();
                let _ = writeln!(
                    text,
                    "        {} => {{ {} }}",
                    pats.join(" | "),
                    loads.join(" ")
                );
            }
            text.push_str("        _ => {}\n    }\n");
        }
        text.push_str("    loop {\n        ex.n_goto(st);\n        match st {\n");
        for b in 0..n {
            if !reach[b] {
                continue;
            }
            let bb = &self.bbs[b];
            let _ = writeln!(text, "            {} => {{", state[b]);
            for c in &bb.code {
                let _ = writeln!(text, "                {c}");
            }
            let t = match &bb.term {
                Some(Term::Goto(t, back)) => goto((*t, *back)),
                Some(Term::If(c, t, e)) => {
                    format!("if {c} {{ {} }} else {{ {} }}", goto(*t), goto(*e))
                }
                Some(Term::Call(code, next)) => format!(
                    "match {}? {{ Flow::Inline => {{ st = {n}; continue }} Flow::Leave(s) => return Ok(s) }}",
                    code.replace(&format!("__BB{next}__"), &state[*next].to_string()),
                    n = state[*next]
                ),
                Some(Term::Return(v)) => format!("let v = {v}; return ex.n_ret(v);"),
                Some(Term::Throw(v)) => format!("let v = {v}; return Err(Fault::throw(v));"),
                None => "return Err(bad_state());".into(),
            };
            let _ = writeln!(text, "                {t}");
            text.push_str("            }\n");
        }
        text.push_str("            _ => return Err(bad_state()),\n        }\n    }\n}\n\n");
        // The handler table: the states of each try region.
        let _ = writeln!(
            text,
            "fn {}(state: u32) -> Option<(u32, u32)> {{",
            handler_fn(name)
        );
        let mut arms: Vec<(Vec<u32>, String)> = Vec::new();
        for (ctx, (catch, slot)) in self.tries.iter().enumerate() {
            let states: Vec<u32> = (0..n)
                .filter(|&b| reach[b] && self.bbs[b].try_ctx == Some(ctx))
                .map(|b| state[b])
                .collect();
            if !states.is_empty() {
                arms.push((states, format!("Some(({}, {slot}))", state[*catch])));
            }
        }
        if arms.is_empty() {
            text.push_str("    let _ = state;\n    None\n}\n");
        } else {
            text.push_str("    match state {\n");
            for (states, r) in arms {
                let pats: Vec<String> = states.iter().map(|s| s.to_string()).collect();
                let _ = writeln!(text, "        {} => {r},", pats.join(" | "));
            }
            text.push_str("        _ => None,\n    }\n}\n");
        }
        FsmCode {
            params,
            locals: self.slots,
            text,
        }
    }
}

