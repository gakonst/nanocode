//! The Rust backend (0063, ARCH "Generated state machines", D1631): every `@native`
//! builtin becomes a resumable state machine over a native frame, and the leaf builtins
//! they call become plain Rust functions. The output is one file,
//! `crates/djs-core/src/builtins/gen/natives.rs`; its runtime is
//! `crates/djs-core/src/interp/run/native.rs`.
//!
//! A native builtin is lowered to basic blocks; each block is a state (an arm of
//! `match ex.n_state()`). Blocks end at branches, at loop back-edges (which charge fuel
//! and are safepoints) and at every resume point: a call of a reentrant intrinsic or
//! builtin, which either completes inline (`Flow::Inline`: go on at the resume state) or
//! pushes a frame (`Flow::Leave`: back to the interpreter, which re-enters at the resume
//! state with the result on the operand stack). Every local and temporary lives in a
//! frame slot as a Value, so nothing but slots crosses a state boundary. Within an
//! expression that contains a resume point, call results are spilled to temporaries in
//! evaluation order, and `&&`, `||` and `?:` around resume points become branches.
//!
//! Numbers: i32/u32 `+ - *` and negation are checked (an overflow raises an internal
//! error, D1171); f64 is IEEE as in JS; Values are made with `num` (the canonical int32
//! form), so both backends produce the same Values.

use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;

