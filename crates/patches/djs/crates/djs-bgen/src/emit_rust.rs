/// The outermost string concatenation in `s` (the last one: operands come first) as
/// the retrying `n_concat_gc` (D1900).
fn concat_gc(s: String) -> String {
    match s.rfind("ex.n_concat(") {
        Some(i) => format!(
            "{}ex.n_concat_gc({}",
            &s[..i],
            &s[i + "ex.n_concat(".len()..]
        ),
        None => s,
    }
}

fn op_rep(ty: OpType) -> Rep {
    match ty {
        OpType::Bool => Rep::Bool,
        OpType::Num(t) => rep(t),
        OpType::Fold(_) => Rep::F64,
        _ => Rep::Val,
    }
}

/// A type of representation `r`, for decoding a temporary.
fn rep_type(r: Rep) -> Type {
    match r {
        Rep::Val => Type::Value,
        Rep::Bool => Type::Bool,
        Rep::I32 => Type::I32,
        Rep::U32 => Type::U32,
        Rep::F64 => Type::F64,
    }
}

/// Whether the rest parameter `name` is only read as `LengthOfArrayLike(name)` and
/// `Get(name, i)`, so it need not be materialized.
fn rest_is_virtual(stmts: &[Stmt], name: &str) -> bool {
    fn e(x: &Expr, name: &str) -> bool {
        match &x.kind {
            ExprKind::Ident(n) => n != name,
            ExprKind::Unary(_, a) | ExprKind::Paren(a) => e(a, name),
            ExprKind::Binary(_, a, b) => e(a, name) && e(b, name),
            ExprKind::Cond(a, b, c) => e(a, name) && e(b, name) && e(c, name),
            ExprKind::Call { callee, args, .. } => {
                let skip = matches!(callee.as_str(), "LengthOfArrayLike" | "Get")
                    && matches!(args.first().map(|a| &a.kind), Some(ExprKind::Ident(n)) if n == name);
                args.iter().skip(usize::from(skip)).all(|a| e(a, name))
            }
            _ => true,
        }
    }
    fn st(s: &Stmt, name: &str) -> bool {
        match s {
            Stmt::Decl { init, .. } => e(init, name),
            Stmt::Assign { target, value, .. } => target != name && e(value, name),
            Stmt::Update { target, .. } => target != name,
            Stmt::Expr(x) | Stmt::Throw { value: x, .. } => e(x, name),
            Stmt::Return { value, .. } => value.as_ref().is_none_or(|v| e(v, name)),
            Stmt::If {
                cond, then, els, ..
            } => e(cond, name) && st(then, name) && els.as_deref().is_none_or(|x| st(x, name)),
            Stmt::While { cond, body, .. } | Stmt::DoWhile { body, cond, .. } => {
                e(cond, name) && st(body, name)
            }
            Stmt::For {
                init,
                cond,
                update,
                body,
                ..
            } => {
                init.as_deref().is_none_or(|x| st(x, name))
                    && cond.as_ref().is_none_or(|x| e(x, name))
                    && update.as_deref().is_none_or(|x| st(x, name))
                    && st(body, name)
            }
            Stmt::Block(b) => b.stmts.iter().all(|x| st(x, name)),
            Stmt::Try {
                body,
                catch,
                finally,
                ..
            } => {
                body.stmts.iter().all(|x| st(x, name))
                    && catch
                        .as_ref()
                        .is_none_or(|c| c.body.stmts.iter().all(|x| st(x, name)))
                    && finally
                        .as_ref()
                        .is_none_or(|f| f.stmts.iter().all(|x| st(x, name)))
            }
            Stmt::Break(_) | Stmt::Continue(_) => true,
        }
    }
    stmts.iter().all(|s| st(s, name))
}

/// The largest body (in statements) that is inlined.
const INLINE_SIZE: usize = 8;

/// Whether a body reads `new.target` (not inlined: it would read the caller's).
fn uses_new_target(stmts: &[Stmt]) -> bool {
    fn e(x: &Expr) -> bool {
        match &x.kind {
            ExprKind::NewTarget => true,
            ExprKind::Unary(_, a) | ExprKind::Paren(a) => e(a),
            ExprKind::Binary(_, a, b) => e(a) || e(b),
            ExprKind::Cond(a, b, c) => e(a) || e(b) || e(c),
            ExprKind::Call { args, .. } => args.iter().any(e),
            _ => false,
        }
    }
    fn st(s: &Stmt) -> bool {
        match s {
            Stmt::Decl { init, .. } => e(init),
            Stmt::Assign { value, .. } => e(value),
            Stmt::Expr(x) | Stmt::Throw { value: x, .. } => e(x),
            Stmt::Return { value, .. } => value.as_ref().is_some_and(e),
            Stmt::If {
                cond, then, els, ..
            } => e(cond) || st(then) || els.as_deref().is_some_and(st),
            Stmt::While { cond, body, .. } | Stmt::DoWhile { body, cond, .. } => {
                e(cond) || st(body)
            }
            Stmt::For {
                init,
                cond,
                update,
                body,
                ..
            } => {
                init.as_deref().is_some_and(st)
                    || cond.as_ref().is_some_and(e)
                    || update.as_deref().is_some_and(st)
                    || st(body)
            }
            Stmt::Block(b) => b.stmts.iter().any(st),
            Stmt::Try {
                body,
                catch,
                finally,
                ..
            } => {
                body.stmts.iter().any(st)
                    || catch.as_ref().is_some_and(|c| c.body.stmts.iter().any(st))
                    || finally.as_ref().is_some_and(|f| f.stmts.iter().any(st))
            }
            _ => false,
        }
    }
    stmts.iter().any(st)
}

/// The size of a body for the inlining policy: statements, counted recursively.
fn inline_size(stmts: &[Stmt]) -> usize {
    stmts
        .iter()
        .map(|s| match s {
            Stmt::Block(b) => inline_size(&b.stmts),
            Stmt::If { then, els, .. } => {
                1 + inline_size(std::slice::from_ref(then))
                    + els
                        .as_deref()
                        .map_or(0, |e| inline_size(std::slice::from_ref(e)))
            }
            Stmt::While { body, .. } | Stmt::DoWhile { body, .. } | Stmt::For { body, .. } => {
                1 + inline_size(std::slice::from_ref(body))
            }
            // Never inlined.
            Stmt::Try { .. } => 1000,
            _ => 1,
        })
        .sum()
}

fn fast_arity(name: &str) -> usize {
    match name {
        "Get" | "HasProperty" => 2,
        "CreateDataPropertyOrThrow" | "Set" => 3,
        _ => 1,
    }
}

// ---- leaf builtins as plain Rust functions ------------------------------------------------

struct Direct<'a, 'c, 'f> {
    cx: &'c mut Cx<'a>,
    env: Env<'f>,
    out: Vec<String>,
    depth: usize,
    labels: usize,
    /// (break label, continue label)
    loops: Vec<(String, String)>,
}

impl<'a> Pure<'a> for Direct<'a, '_, '_> {
    fn env(&self) -> &Env<'_> {
        &self.env
    }
    fn cx(&mut self) -> &mut Cx<'a> {
        self.cx
    }
    fn cx_ref(&self) -> &Cx<'a> {
        self.cx
    }
}

impl<'a, 'c, 'f> Direct<'a, 'c, 'f> {
    fn emit(cx: &'c mut Cx<'a>, f: &'f Function, origin: &str) -> Option<String> {
        let errors_before = cx.errors.len();
        let mut d = Direct {
            cx,
            env: Env {
                f,
                scopes: vec![HashMap::new()],
            },
            out: Vec::new(),
            depth: 1,
            labels: 0,
            loops: Vec::new(),
        };
        let mut params = vec!["ex: &mut Exec<'_>".to_string()];
        for p in &f.params {
            if p.rest {
                d.cx.errors.push(Diagnostic::new(
                    p.span,
                    "the Rust backend has no rest parameters in leaf builtins yet",
                ));
                continue;
            }
            let v = format!("l_{}", p.name);
            params.push(format!("mut {v}: {}", rust_type(rep(p.ty.ty))));
            d.env.declare(&p.name, p.ty.ty, Storage::Var(v));
        }
        let ret = match f.ret.ty {
            Type::Void | Type::Never => "()",
            t => rust_type(rep(t)),
        };
        d.stmts(&f.body.stmts);
        if d.cx.errors.len() > errors_before {
            return None;
        }
        let mut text = format!(
            "// {origin} (leaf)\nfn {}({}) -> Result<{ret}, Fault> {{\n",
            leaf_fn(&f.name),
            params.join(", ")
        );
        for l in &d.out {
            text.push_str(l);
            text.push('\n');
        }
        if ret == "()" {
            text.push_str("    Ok(())\n");
        } else {
            text.push_str("    #[allow(unreachable_code)]\n    Err(bad_state())\n");
        }
        text.push_str("}\n");
        Some(text)
    }

    fn line(&mut self, s: impl Into<String>) {
        let s = s.into();
        self.out.push(format!("{}{s}", "    ".repeat(self.depth)));
    }

    fn stmts(&mut self, stmts: &[Stmt]) {
        self.env.scopes.push(HashMap::new());
        for s in stmts {
            self.stmt(s);
        }
        self.env.scopes.pop();
    }

    fn sub(&mut self, s: &Stmt) {
        self.depth += 1;
        match s {
            Stmt::Block(b) => self.stmts(&b.stmts),
            other => {
                self.env.scopes.push(HashMap::new());
                self.stmt(other);
                self.env.scopes.pop();
            }
        }
        self.depth -= 1;
    }

    fn value_for(&mut self, e: &Expr, ty: Type) -> String {
        let t = self.env.ty(self.cx, e);
        let r = rep(ty);
        let _ = t;
        self.pure(e, r).s
    }

    fn stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Decl { name, ty, init, .. } => {
                let v = format!("l_{name}");
                let c = self.value_for(init, ty.ty);
                self.line(format!("let mut {v}: {} = {c};", rust_type(rep(ty.ty))));
                self.env.declare(name, ty.ty, Storage::Var(v));
            }
            Stmt::Assign {
                target,
                target_span,
                op,
                value,
                span,
            } => {
                let l = self.env.lookup(target).clone();
                let value = match op.binary() {
                    None => value.clone(),
                    Some(b) => Expr {
                        kind: ExprKind::Binary(
                            b,
                            Box::new(Expr {
                                kind: ExprKind::Ident(target.clone()),
                                span: *target_span,
                            }),
                            Box::new(value.clone()),
                        ),
                        span: *span,
                    },
                };
                let c = self.value_for(&value, l.ty);
                let Storage::Var(v) = l.at else {
                    unreachable!()
                };
                self.line(format!("{v} = {c};"));
            }
            Stmt::Update { target, inc, span } => {
                let l = self.env.lookup(target).clone();
                let e = Expr {
                    kind: ExprKind::Binary(
                        if *inc { BinOp::Add } else { BinOp::Sub },
                        Box::new(Expr {
                            kind: ExprKind::Ident(target.clone()),
                            span: *span,
                        }),
                        Box::new(Expr {
                            kind: ExprKind::Num(1.0, "1".into()),
                            span: *span,
                        }),
                    ),
                    span: *span,
                };
                let c = self.value_for(&e, l.ty);
                let Storage::Var(v) = l.at else {
                    unreachable!()
                };
                self.line(format!("{v} = {c};"));
            }
            Stmt::Expr(e) => {
                let c = self.pure(e, Rep::Val);
                self.line(format!("let _ = {};", c.s));
            }
            Stmt::If {
                cond, then, els, ..
            } => {
                let c = self.pure(cond, Rep::Bool);
                self.line(format!("if {} {{", c.s));
                self.sub(then);
                if let Some(e) = els {
                    self.line("} else {");
                    self.sub(e);
                }
                self.line("}");
            }
            Stmt::While { cond, body, .. } => {
                let (lb, lc) = self.labels();
                let c = self.pure(cond, Rep::Bool);
                self.line(format!("{lb}: loop {{"));
                self.line(format!("    if !{} {{ break {lb}; }}", c.s));
                self.line(format!("    {lc}: {{"));
                self.loops.push((lb, lc));
                self.depth += 1;
                self.sub(body);
                self.depth -= 1;
                self.loops.pop();
                self.line("    }");
                self.line("}");
            }
            Stmt::DoWhile { body, cond, .. } => {
                let (lb, lc) = self.labels();
                self.line(format!("{lb}: loop {{"));
                self.line(format!("    {lc}: {{"));
                self.loops.push((lb.clone(), lc));
                self.depth += 1;
                self.sub(body);
                self.depth -= 1;
                self.loops.pop();
                self.line("    }");
                let c = self.pure(cond, Rep::Bool);
                self.line(format!("    if !{} {{ break {lb}; }}", c.s));
                self.line("}");
            }
            Stmt::For {
                init,
                cond,
                update,
                body,
                ..
            } => {
                let (lb, lc) = self.labels();
                self.line("{");
                self.depth += 1;
                self.env.scopes.push(HashMap::new());
                if let Some(i) = init {
                    self.stmt(i);
                }
                self.line(format!("{lb}: loop {{"));
                if let Some(c) = cond {
                    let c = self.pure(c, Rep::Bool);
                    self.line(format!("    if !{} {{ break {lb}; }}", c.s));
                }
                self.line(format!("    {lc}: {{"));
                self.loops.push((lb, lc));
                self.depth += 1;
                self.sub(body);
                self.depth -= 1;
                self.loops.pop();
                self.line("    }");
                if let Some(u) = update {
                    self.depth += 1;
                    self.stmt(u);
                    self.depth -= 1;
                }
                self.line("}");
                self.env.scopes.pop();
                self.depth -= 1;
                self.line("}");
            }
            Stmt::Return { value, .. } => match value {
                Some(v) => {
                    let c = self.value_for(v, self.env.f.ret.ty);
                    self.line(format!("return Ok({c});"));
                }
                None => self.line("return Ok(());"),
            },
            Stmt::Throw { value, .. } => {
                let c = self.pure(value, Rep::Val);
                self.line(format!("return Err(Fault::throw({}));", c.s));
            }
            Stmt::Break(_) => {
                let l = self.loops.last().unwrap().0.clone();
                self.line(format!("break {l};"));
            }
            Stmt::Continue(_) => {
                let l = self.loops.last().unwrap().1.clone();
                self.line(format!("break {l};"));
            }
            Stmt::Try { span, .. } => self.cx.errors.push(Diagnostic::new(
                *span,
                "the Rust backend has no try in leaf builtins yet",
            )),
            Stmt::Block(b) => {
                self.line("{");
                self.depth += 1;
                self.stmts(&b.stmts);
                self.depth -= 1;
                self.line("}");
            }
        }
    }

    fn labels(&mut self) -> (String, String) {
        self.labels += 1;
        (format!("'l{}", self.labels), format!("'c{}", self.labels))
    }
}
