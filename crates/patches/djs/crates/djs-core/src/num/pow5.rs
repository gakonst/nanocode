/// `C(q)` for `MIN_Q <= q <= MAX_Q`.
pub(crate) fn pow5_128(q: i32) -> u128 {
    debug_assert!((MIN_Q..=MAX_Q).contains(&q));
    let k = q.div_euclid(STRIDE);
    let j = q.rem_euclid(STRIDE) as usize;
    let base = BASE[(k + BASE_OFFSET) as usize];
    if j == 0 {
        return base;
    }
    let m = POW5_U64[j] as u128;
    // 192-bit product base * m = mid * 2^64 + low.
    let lo = (base as u64 as u128) * m;
    let mid = (base >> 64) * m + (lo >> 64);
    let low = lo as u64 as u128;
    // base >= 2^127 and m >= 5, so mid >= 2^65 and lz <= 62.
    let lz = mid.leading_zeros();
    let top = if lz == 0 {
        mid
    } else {
        mid << lz | low >> (64 - lz)
    };
    let i = (q - MIN_Q) as usize;
    top + ((CORR[i / 16] >> ((i % 16) * 2)) & 3) as u128
}

/// Ryu's `DOUBLE_POW5_SPLIT[i]`: 5^i truncated to 125 bits, for 0 <= i <= 325.
pub(crate) fn ryu_pow5(i: u32) -> u128 {
    pow5_128(i as i32) >> 3
}

/// Ryu's `DOUBLE_POW5_INV_SPLIT[q]`: floor(2^(pow5bits(q) - 1 + 125) / 5^q) + 1.
pub(crate) fn ryu_inv_pow5(q: u32) -> u128 {
    if q == 0 {
        (1u128 << 125) + 1
    } else {
        (pow5_128(-(q as i32)) >> 3) + 1
    }
}

/// The Eisel-Lemire table entry for 5^q, -342 <= q <= 308, as generated by the reference
/// script (`dec2flt_table.py` in Rust, `table_generation.py` in fast_float): negative powers
/// with |q| <= 27 are rounded up, all others are truncated.
pub(crate) fn lemire_pow5(q: i32) -> u128 {
    let c = pow5_128(q);
    if (-27..0).contains(&q) { c + 1 } else { c }
}

#[cfg(test)]
mod tests {
    extern crate std;
    use super::super::big::Big;
    use super::*;
    use std::println;

    fn big_to_u128(b: &Big) -> u128 {
        let l = b.limbs();
        assert!(l.len() <= 4, "{b:?}");
        l.iter().rev().fold(0u128, |acc, &x| acc << 32 | x as u128)
    }

    fn pow5_big(n: u32) -> Big {
        let mut b = Big::from_u64(1);
        b.mul_pow(5, n);
        b
    }

    /// floor(2^k / 5^n)
    fn pow2_div_pow5(k: u32, n: u32) -> Big {
        let mut b = Big::from_u64(1);
        b.shl(k);
        b.div_pow(5, n);
        b
    }

    /// Exact `C(q)`.
    fn exact(q: i32) -> u128 {
        if q >= 0 {
            let mut b = pow5_big(q as u32);
            let bits = b.bit_len();
            if bits <= 128 {
                b.shl(128 - bits);
            } else {
                b.shr_sticky(bits - 128);
            }
            big_to_u128(&b)
        } else {
            let n = (-q) as u32;
            let l = pow5_big(n).bit_len() - 1; // floor(log2(5^n))
            big_to_u128(&pow2_div_pow5(l + 128, n))
        }
    }

    /// The Lemire table entry, computed the way the reference script does.
    fn exact_lemire(q: i32) -> u128 {
        if q >= 0 {
            return exact(q);
        }
        let n = (-q) as u32;
        let z = pow5_big(n).bit_len(); // smallest z with 2^z >= 5^n (5^n is not a power of 2)
        let mut c = if q >= -27 {
            pow2_div_pow5(z + 127, n)
        } else {
            pow2_div_pow5(2 * z + 128, n)
        };
        c.add_small(1);
        let bits = c.bit_len();
        if bits > 128 {
            c.shr_sticky(bits - 128);
        }
        big_to_u128(&c)
    }

    fn pow5bits(e: u32) -> u32 {
        ((e * 1217359) >> 19) + 1
    }

    #[test]
    fn table_is_exact() {
        for q in MIN_Q..=MAX_Q {
            assert_eq!(pow5_128(q), exact(q), "q = {q}");
        }
    }

    #[test]
    fn lemire_table_matches_reference_definition() {
        for q in MIN_Q..=308 {
            assert_eq!(lemire_pow5(q), exact_lemire(q), "q = {q}");
        }
        // Spot checks against Rust's core::num::dec2flt::table.
        assert_eq!(lemire_pow5(-342), 0xeef453d6923bd65a_113faa2906a13b3f);
        assert_eq!(lemire_pow5(-251), 0x92a1958a7675175f_0bfacd89ec191ec9);
        assert_eq!(lemire_pow5(136), 0xdc21a1171d42645d_76707543f4fa1f73);
    }

    #[test]
    fn ryu_tables_match_reference_definition() {
        for i in 0..=325u32 {
            let b = pow5_big(i);
            let shift = pow5bits(i) as i32 - 125;
            let mut v = b.clone();
            if shift > 0 {
                v.shr_sticky(shift as u32);
            } else {
                v.shl((-shift) as u32);
            }
            assert_eq!(ryu_pow5(i), big_to_u128(&v), "pow5 {i}");
        }
        for q in 0..=341u32 {
            let mut v = pow2_div_pow5(pow5bits(q) - 1 + 125, q);
            v.add_small(1);
            assert_eq!(ryu_inv_pow5(q), big_to_u128(&v), "inv {q}");
        }
        // Spot checks against ryu's d2s_small_table.rs (DOUBLE_POW5_INV_SPLIT2[1] is 5^-26,
        // DOUBLE_POW5_SPLIT2[2] is 5^52).
        assert_eq!(
            ryu_inv_pow5(26),
            (1784059615882449851u128 << 64) | 5955668970331000884
        );
        assert_eq!(
            ryu_pow5(52),
            (1925929944387235853u128 << 64) | 1032610780636961552
        );
    }

    /// Prints `BASE` and `CORR`. Run with
    /// `cargo test -p djs-core gen_pow5_tables -- --ignored --nocapture`.
    #[test]
    #[ignore]
    fn gen_pow5_tables() {
        println!("static BASE: [u128; 26] = [");
        for k in -BASE_OFFSET..=12 {
            println!("    0x{:032x}, // 5^{}", exact(k * STRIDE), k * STRIDE);
        }
        println!("];");
        let mut corr = [0u32; 42];
        for q in MIN_Q..=MAX_Q {
            let k = q.div_euclid(STRIDE);
            let j = q.rem_euclid(STRIDE) as usize;
            let base = exact(k * STRIDE);
            let approx = if j == 0 {
                base
            } else {
                let m = POW5_U64[j] as u128;
                let lo = (base as u64 as u128) * m;
                let mid = (base >> 64) * m + (lo >> 64);
                let low = lo as u64 as u128;
                let lz = mid.leading_zeros();
                if lz == 0 {
                    mid
                } else {
                    mid << lz | low >> (64 - lz)
                }
            };
            let d = exact(q) - approx;
            assert!(d <= 3, "q = {q}: correction {d}");
            let i = (q - MIN_Q) as usize;
            corr[i / 16] |= (d as u32) << ((i % 16) * 2);
        }
        println!("static CORR: [u32; 42] = [");
        for chunk in corr.chunks(6) {
            let line: std::vec::Vec<std::string::String> =
                chunk.iter().map(|c| std::format!("0x{c:08x}")).collect();
            println!("    {},", line.join(", "));
        }
        println!("];");
    }
}
