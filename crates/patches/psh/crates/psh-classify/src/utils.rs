//! Per-utility knowledge: the category of a utility, which of its options take a value,
//! what its operands are, and which options change its effect (`sed -i` writes its
//! files, `tail -f` runs until stopped).
//!
//! These tables are the shared place for that knowledge: the classifier reads them, and
//! psh's in-process utilities check their own option parsing against them in their
//! tests, so both agree on which flags write. Utilities with subcommands or nested
//! commands (git, package managers, `find`, `xargs`, shells, interpreters) have rules in
//! code instead (`rules.rs`).

use crate::Category::{self, *};

/// What the non-option arguments of a utility are.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Operands {
    /// Not paths (or not tracked): `echo`, `tr`, `seq`.
    None,
    /// Files it reads.
    Read,
    /// Files it writes, creates or removes.
    Write,
    /// The last operand is written, the others read (`cp`, `ln`, `install`).
    LastWrite,
    /// Sources are removed and the last operand written: all are writes (`mv`).
    AllWrite,
    /// The first operand is read, a second one written (`xxd in out`, `uniq in out`).
    ReadThenWrite,
    /// A pattern or script comes first unless one of these short options gives it; the
    /// rest are files read (`grep`, `sed`, `rg`, `awk`).
    Script(&'static str),
}

/// What an option changes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Effect {
    /// The operands are written (`sed -i`, `perl -i`).
    WritesOperands,
    /// The option's value is a file that is written (`sort -o FILE`, `curl -o FILE`).
    WritesValue,
    /// The option's value is a file that is read (`grep -f FILE`).
    ReadsValue,
    /// The command changes state (`date -s`, `xattr -w`).
    Mutates,
    /// The command runs until stopped (`tail -f`).
    LongRunning,
    /// The option runs or loads code the classifier cannot see (`rg --pre CMD`,
    /// `awk -f FILE`, `sort --compress-program`).
    Unknown,
}

/// What psh knows about one utility.
#[derive(Clone, Copy, Debug)]
pub struct Utility {
    pub name: &'static str,
    pub category: Category,
    /// Short options that take a value, attached (`-n5`) or as the next word (`-n 5`).
    pub short_values: &'static str,
    /// Long options that take the next word as their value unless written `--opt=value`.
    pub long_values: &'static [&'static str],
    pub operands: Operands,
    /// Options that change the effect: `-x` for a short option (also inside a cluster such
    /// as `-ni`), `--name` for a long one.
    pub effects: &'static [(&'static str, Effect)],
}

const fn u(name: &'static str, category: Category, operands: Operands) -> Utility {
    Utility {
        name,
        category,
        short_values: "",
        long_values: &[],
        operands,
        effects: &[],
    }
}

const fn v(
    name: &'static str,
    category: Category,
    short_values: &'static str,
    long_values: &'static [&'static str],
    operands: Operands,
    effects: &'static [(&'static str, Effect)],
) -> Utility {
    Utility {
        name,
        category,
        short_values,
        long_values,
        operands,
        effects,
    }
}

