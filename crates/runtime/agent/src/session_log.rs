pub struct SessionLog<H: ?Sized> {
    host: Arc<H>,
    scope: Arc<str>,
    pub(crate) compact: bool,
    ready: AtomicBool,
    limit: Option<usize>,
    physical_limit: Option<usize>,
    blobs: Option<Blobs>,
    writer: Owned<Writer>,
}

impl<H: Sql + ?Sized> SessionLog<H> {
    pub fn new(host: Arc<H>, scope: impl Into<Arc<str>>) -> Self {
        Self {
            host,
            scope: scope.into(),
            compact: false,
            ready: AtomicBool::new(false),
            limit: None,
            physical_limit: None,
            blobs: None,
            writer: Owned::new(Writer::default()),
        }
    }

    #[must_use]
    pub const fn compact_events(mut self) -> Self {
        self.compact = true;
        self
    }

    #[must_use]
    pub const fn value_limit(mut self, bytes: usize) -> Self {
        self.physical_limit = Some(bytes);
        self
    }

    #[must_use]
    pub const fn logical_limit(mut self, bytes: usize) -> Self {
        self.limit = Some(bytes);
        self
    }

    #[must_use]
    pub fn blobs(mut self, store: SharedBlobStore, threshold: usize) -> Self {
        self.blobs = Some(Blobs { store, threshold });
        self
    }

    pub(crate) fn event_fits(&self, request_id: Option<&str>, body: &str) -> bool {
        self.limit
            .is_none_or(|limit| event_bytes(&self.scope, request_id, body.len()) <= limit)
    }

    pub fn scope(&self) -> &str {
        &self.scope
    }

    pub fn host(&self) -> &H {
        &self.host
    }

    async fn run(
        &self,
        operation: &'static str,
        statements: &[SqlStatement<'_>],
    ) -> Result<Vec<Vec<SqlRow>>, StoreError> {
        let results = self.host.transaction(operation, statements).await?;
        if results.len() != statements.len() {
            return Err(StoreError::Backend(format!(
                "SQL host answered {} of {} session log statements",
                results.len(),
                statements.len()
            )));
        }
        Ok(results)
    }

    pub const FORMAT: u32 = MIGRATIONS.len() as u32;

    pub async fn migrate(&self) -> Result<(), StoreError> {
        migrate_format(&*self.host, "session_log", &MIGRATIONS).await?;
        self.ready.store(true, Ordering::Release);
        Ok(())
    }

    async fn execute(
        &self,
        operation: &'static str,
        statements: &[Stmt],
        spill: &Spill,
    ) -> Result<Vec<Vec<SqlRow>>, StoreError> {
        if !self.ready.load(Ordering::Acquire) {
            self.migrate().await?;
        }
        if let Some(limit) = self.physical_limit
            && statements
                .iter()
                .any(|statement| statement.params.iter().any(|value| value.len() > limit))
        {
            return Err(StoreError::NotCommitted(
                "session log binding exceeds the physical value limit".into(),
            ));
        }
        self.put_blobs(&spill.blobs).await?;
        let dialect = self.host.dialect();
        let mut prepared: Vec<SqlStatement<'_>> = spill
            .parts
            .iter()
            .map(|(key, data)| SqlStatement {
                sql: dialect.pick(&PART),
                params: vec![key, data],
            })
            .collect();
        let prefix = prepared.len();
        prepared.extend(statements.iter().map(|statement| SqlStatement {
            sql: dialect.pick(statement.sql),
            params: statement.params.iter().map(String::as_str).collect(),
        }));
        let mut results = self.run(operation, &prepared).await?;
        results.drain(..prefix);
        Ok(results)
    }

    async fn query(
        &self,
        operation: &'static str,
        sql: &'static Dialects,
        params: Vec<String>,
    ) -> Result<Vec<SqlRow>, StoreError> {
        self.execute(operation, &[Stmt { sql, params }], &Spill::default())
            .await?
            .pop()
            .ok_or_else(|| invalid("missing query rows"))
    }

    fn store_value<'a>(
        &self,
        value: &'a str,
        overhead: usize,
        force: bool,
        spill: &mut Spill,
    ) -> Result<Cow<'a, str>, StoreError> {
        if !force
            && !value.starts_with(PAYLOAD_MARK)
            && self
                .physical_limit
                .is_none_or(|limit| value.len().saturating_add(overhead) <= limit)
            && self
                .blobs
                .as_ref()
                .is_none_or(|blobs| value.len() <= blobs.threshold)
        {
            return Ok(Cow::Borrowed(value));
        }
        let keys = if self.blobs.is_some() {
            let key = BlobKey::of(value.as_bytes());
            let reference = key.as_str().to_owned();
            spill
                .blobs
                .entry(key)
                .or_insert_with(|| value.as_bytes().to_vec());
            vec![reference]
        } else {
            self.parts(value, &mut spill.parts)?
        };
        let reference = serde_json::to_string(&PayloadReference {
            parts: keys,
            bytes: value.len(),
        })
        .map_err(encoding)?;
        if self
            .physical_limit
            .is_some_and(|limit| reference.len().saturating_add(overhead) > limit)
        {
            return Err(StoreError::NotCommitted(
                "session log reference exceeds the physical row limit".into(),
            ));
        }
        Ok(Cow::Owned(reference))
    }

    fn parts(
        &self,
        value: &str,
        parts: &mut Vec<(String, String)>,
    ) -> Result<Vec<String>, StoreError> {
        let part_overhead = record_bytes(2, blake3::OUT_LEN * 2, 0);
        let capacity = self
            .physical_limit
            .map_or(value.len(), |limit| limit.saturating_sub(part_overhead));
        if capacity == 0 {
            return Err(StoreError::NotCommitted(
                "physical value limit cannot hold a session log part".into(),
            ));
        }
        let mut remaining = value;
        let mut keys = Vec::new();
        while !remaining.is_empty() {
            let mut end = capacity.min(remaining.len());
            while !remaining.is_char_boundary(end) {
                end -= 1;
            }
            if end == 0 {
                return Err(StoreError::NotCommitted(
                    "physical value limit cannot hold a UTF-8 character".into(),
                ));
            }
            let (data, rest) = remaining.split_at(end);
            let key = blake3::hash(data.as_bytes()).to_hex().to_string();
            keys.push(key.clone());
            parts.push((key, data.to_owned()));
            remaining = rest;
        }
        Ok(keys)
    }

    fn stored_prompt<'p>(&self, prompt: &'p Prompt, writes: &mut BlobWrites) -> Cow<'p, Prompt> {
        if self.blobs.is_none() {
            return Cow::Borrowed(prompt);
        }
        let mut stored = prompt.clone();
        if let PromptInput::Content(items) = &mut stored.instruction {
            for item in items {
                if let UserInput::Image { image_url, .. } = item
                    && let Some((blob, bytes)) = BlobUrl::from_data_url(image_url)
                {
                    *image_url = blob.to_string();
                    writes.entry(blob.key().clone()).or_insert(bytes);
                }
            }
        }
        Cow::Owned(stored)
    }

    async fn put_blobs(&self, writes: &BlobWrites) -> Result<(), StoreError> {
        let Some(blobs) = &self.blobs else {
            return Ok(());
        };
        for (key, bytes) in writes {
            blobs.store.put(key, bytes).await.map_err(|error| {
                StoreError::NotCommitted(format!("store session log blob {key}: {error}"))
            })?;
        }
        Ok(())
    }

    async fn load_value(&self, value: &str) -> Result<String, StoreError> {
        let reference = reference(value)?;
        let mut decoded = String::new();
        for key in reference.parts {
            if let Some(key) = BlobKey::parse(&key) {
                let blobs = self.blobs.as_ref().ok_or_else(|| {
                    invalid(format!(
                        "session log value {key} is in a blob store the log lacks"
                    ))
                })?;
                let bytes = get_blob(&*blobs.store, &key).await?;
                decoded.push_str(
                    std::str::from_utf8(&bytes)
                        .map_err(|error| invalid(format!("session log blob {key}: {error}")))?,
                );
                continue;
            }
            let results = self
                .run(
                    "log_part",
                    &[SqlStatement {
                        sql: self.host.dialect().pick(&READ_PART),
                        params: vec![&key],
                    }],
                )
                .await?;
            let row = single(&results[0])?.ok_or_else(|| invalid("missing session log part"))?;
            let data = text(row, 0)?;
            if blake3::hash(data.as_bytes()).to_hex().as_str() != key {
                return Err(invalid("session log part digest mismatch"));
            }
            decoded.push_str(data);
        }
        if decoded.len() != reference.bytes {
            return Err(invalid("session log payload length mismatch"));
        }
        Ok(decoded)
    }

    async fn loaded(&self, value: &mut Box<RawValue>) -> Result<(), StoreError> {
        if value.get().starts_with(PAYLOAD_MARK) {
            *value = raw(self.load_value(value.get()).await?)?;
        }
        Ok(())
    }

    async fn load_cells(&self, rows: &mut [SqlRow], columns: &[usize]) -> Result<(), StoreError> {
        for row in rows {
            for &column in columns {
                if let Some(Some(value)) = row.get_mut(column)
                    && value.starts_with(PAYLOAD_MARK)
                {
                    *value = self.load_value(value).await?;
                }
            }
        }
        Ok(())
    }

    async fn writer(&self) -> Result<Held<'_, Writer>, StoreError> {
        let mut writer = self.writer.acquire().await;
        if writer.ready && !writer.stale {
            return Ok(writer);
        }
        let scope = self.scope.to_string();
        let open = [
            Stmt {
                sql: &SEQ_HIGH,
                params: vec![scope.clone()],
            },
            Stmt {
                sql: &LAST_CHUNK,
                params: vec![scope.clone()],
            },
            Stmt {
                sql: &HOLDER,
                params: vec![scope],
            },
        ];
        let results = if self.ready.load(Ordering::Acquire) {
            self.execute("log_open", &open, &Spill::default()).await?
        } else {
            let dialect = self.host.dialect();
            let prepared: Vec<_> = open
                .iter()
                .map(|statement| SqlStatement {
                    sql: dialect.pick(statement.sql),
                    params: statement.params.iter().map(String::as_str).collect(),
                })
                .collect();
            let results =
                migrate_format_then(&*self.host, "session_log", &MIGRATIONS, &prepared).await?;
            self.ready.store(true, Ordering::Release);
            results
        };
        let turns = single(&results[0])?;
        let referenced = turns
            .and_then(|row| optional(row, 0))
            .map(counter)
            .transpose()?
            .unwrap_or(0);
        let tails = turns
            .and_then(|row| optional(row, 1))
            .map(counter)
            .transpose()?
            .unwrap_or(0);
        let chunks = single(&results[1])?
            .map(|row| text(row, 0).and_then(counter))
            .transpose()?
            .unwrap_or(0);
        let high = tails.max(chunks);
        let seen = referenced.max(chunks);
        let holder = single(&results[2])?
            .map(|row| {
                Ok::<_, StoreError>(Holder {
                    request_id: text(row, 0)?.to_owned(),
                    last: counter(text(row, 1)?)?,
                    tail: usize::try_from(counter(text(row, 2)?)?).unwrap_or(usize::MAX),
                    other: usize::try_from(counter(text(row, 3)?)?).unwrap_or(usize::MAX),
                })
            })
            .transpose()?
            .filter(|holder| holder.last == high);
        if writer.ready {
            writer.next = writer.next.max(seen.saturating_add(GAP));
            writer.durable = high;
            writer.holder = holder;
            writer.rows.clear();
            writer.stale = false;
        } else {
            *writer = Writer {
                ready: true,
                next: seen.saturating_add(GAP),
                durable: high,
                holder,
                ..Writer::default()
            };
        }
        Ok(writer)
    }

    fn turn_fits(&self, request_id: &str, other: usize, tail: usize, add: usize) -> bool {
        tail.saturating_add(add) <= SEAL_BYTES
            && self.physical_limit.is_none_or(|limit| {
                record_bytes(
                    TURN_TEXTS,
                    self.scope.len() + request_id.len() + other + tail + add,
                    TURN_INTEGERS,
                ) <= limit
            })
    }

    fn chunk_capacity(&self) -> usize {
        self.physical_limit.map_or(SEAL_BYTES, |limit| {
            SEAL_BYTES.min(limit.saturating_sub(record_bytes(
                CHUNK_TEXTS,
                self.scope.len(),
                CHUNK_INTEGERS,
            )))
        })
    }

    fn encode_line(&self, line: &Line, spill: &mut Spill) -> Result<String, StoreError> {
        let request_id = serde_json::to_string(&line.request_id).map_err(encoding)?;
        let overhead = record_bytes(
            TURN_TEXTS,
            self.scope.len() + request_id.len() + LINE_FRAME_BYTES,
            TURN_INTEGERS,
        );
        let body = self.store_value(line.body.get(), overhead, false, spill)?;
        Ok(format!(
            "[{},{},{request_id},{body}]\n",
            line.seq, line.created_at
        ))
    }

    fn chunks(&self, texts: &[(u64, String)]) -> Vec<Stmt> {
        let capacity = self.chunk_capacity();
        let mut statements = Vec::new();
        let mut start = 0;
        while start < texts.len() {
            let mut end = start + 1;
            let mut body = texts[start].1.clone();
            while end < texts.len() && body.len() + texts[end].1.len() <= capacity {
                body.push_str(&texts[end].1);
                end += 1;
            }
            statements.push(Stmt {
                sql: &NEW_CHUNK,
                params: vec![
                    self.scope.to_string(),
                    texts[start].0.to_string(),
                    texts[end - 1].0.to_string(),
                    body,
                ],
            });
            start = end;
        }
        statements
    }

    fn spread(&self, writer: &Writer, texts: &[(u64, String)], last: u64) -> Placed {
        let total: usize = texts.iter().map(|(_, text)| text.len()).sum();
        if texts.is_empty() {
            return Placed {
                own: None,
                statements: Vec::new(),
                holder: writer.holder.clone(),
                last,
                started: None,
                guard: None,
            };
        }
        if let Some(holder) = &writer.holder
            && self.turn_fits(&holder.request_id, holder.other, holder.tail, total)
        {
            let start = writer.started.contains(&holder.request_id);
            return Placed {
                own: None,
                statements: vec![
                    Stmt {
                        sql: &CHECK_TAIL,
                        params: vec![
                            self.scope.to_string(),
                            holder.request_id.clone(),
                            holder.last.to_string(),
                        ],
                    },
                    Stmt {
                        sql: &APPEND_TAIL,
                        params: vec![
                            self.scope.to_string(),
                            holder.request_id.clone(),
                            last.to_string(),
                            texts.iter().map(|(_, text)| text.as_str()).collect(),
                            holder.last.to_string(),
                            if start { "1" } else { "0" }.to_owned(),
                        ],
                    },
                ],
                holder: Some(Holder {
                    request_id: holder.request_id.clone(),
                    last,
                    tail: holder.tail + total,
                    other: holder.other,
                }),
                last,
                started: start.then(|| holder.request_id.clone()),
                guard: Some((holder.request_id.clone(), holder.last)),
            };
        }
        Placed {
            own: None,
            statements: self.chunks(texts),
            holder: None,
            last,
            started: None,
            guard: None,
        }
    }

    fn place(
        &self,
        writer: &Writer,
        lines: &[Line],
        own_lines: usize,
        own: Option<&Own<'_>>,
        spill: &mut Spill,
    ) -> Result<Placed, StoreError> {
        let texts = lines
            .iter()
            .map(|line| Ok((line.seq, self.encode_line(line, spill)?)))
            .collect::<Result<Vec<_>, StoreError>>()?;
        let last = lines.last().map_or(writer.durable, |line| line.seq);
        let joined = |texts: &[(u64, String)]| {
            (
                texts.first().map_or(0, |(seq, _)| *seq),
                last,
                texts
                    .iter()
                    .map(|(_, text)| text.as_str())
                    .collect::<String>(),
            )
        };
        let total: usize = texts.iter().map(|(_, text)| text.len()).sum();
        let split = texts.len() - own_lines;
        let Some(own) = own else {
            return Ok(self.spread(writer, &texts, last));
        };
        if own.fresh {
            let held = |tail| Holder {
                request_id: own.request_id.to_owned(),
                last,
                tail,
                other: own.other,
            };
            if self.turn_fits(own.request_id, own.other, 0, total) {
                return Ok(Placed {
                    own: Some(joined(&texts)),
                    statements: Vec::new(),
                    holder: Some(held(total)),
                    last,
                    started: None,
                    guard: None,
                });
            }
            let mine = &texts[split..];
            let bytes: usize = mine.iter().map(|(_, text)| text.len()).sum();
            if !self.turn_fits(own.request_id, own.other, 0, bytes) {
                return Err(StoreError::NotCommitted(
                    "a turn's own events do not fit its session log row".into(),
                ));
            }
            let before = texts[..split]
                .last()
                .map_or(writer.durable, |(seq, _)| *seq);
            let mut placed = self.spread(writer, &texts[..split], before);
            placed.own = Some(joined(mine));
            placed.holder = Some(held(bytes));
            placed.last = last;
            return Ok(placed);
        }
        match &writer.holder {
            Some(holder) if holder.request_id == own.request_id => {
                if total == 0 {
                    return Ok(Placed {
                        own: None,
                        statements: Vec::new(),
                        holder: Some(Holder {
                            other: own.other,
                            ..holder.clone()
                        }),
                        last,
                        started: None,
                        guard: None,
                    });
                }
                if self.turn_fits(own.request_id, own.other, holder.tail, total) {
                    return Ok(Placed {
                        own: Some(joined(&texts)),
                        statements: Vec::new(),
                        holder: Some(Holder {
                            request_id: own.request_id.to_owned(),
                            last,
                            tail: holder.tail + total,
                            other: own.other,
                        }),
                        last,
                        started: None,
                        guard: None,
                    });
                }
                Ok(Placed {
                    own: None,
                    statements: self.chunks(&texts),
                    holder: None,
                    last,
                    started: None,
                    guard: None,
                })
            }
            _ => Ok(self.spread(writer, &texts, last)),
        }
    }

    async fn commit(
        &self,
        writer: &mut Writer,
        operation: &'static str,
        lines: Vec<Line>,
        own: Option<Own<'_>>,
        mut spill: Spill,
        build: impl FnOnce(Option<&(u64, u64, String)>) -> Vec<Stmt>,
    ) -> Result<Vec<Vec<SqlRow>>, StoreError> {
        let buffered = writer.buffer.len();
        let own_lines = lines.len();
        let mut all = std::mem::take(&mut writer.buffer);
        all.extend(lines);
        let restore = |writer: &mut Writer, mut all: Vec<Line>| {
            all.truncate(buffered);
            writer.buffered = all.iter().map(Line::estimate).sum();
            writer.buffer = all;
        };
        let placed = match self.place(writer, &all, own_lines, own.as_ref(), &mut spill) {
            Ok(placed) => placed,
            Err(error) => {
                restore(writer, all);
                return Err(error);
            }
        };
        let mut statements = placed.statements;
        let extra = statements.len();
        statements.extend(build(placed.own.as_ref()));
        let mut results = match self.execute(operation, &statements, &spill).await {
            Ok(results) => results,
            Err(error) => {
                restore(writer, all);
                writer.stale = true;
                let tail = placed.guard.as_ref().map(|(request_id, last)| Guard {
                    request_id,
                    status: TurnState::Queued,
                    digest: "",
                    tail_last: Some(*last),
                });
                let turn = own.and_then(|own| own.guard);
                return Err(
                    if self.changed(tail, false).await || self.changed(turn, true).await {
                        StoreError::NotCommitted(format!(
                            "session log {} changed outside this writer, which reads it again before its next write",
                            self.scope
                        ))
                    } else {
                        error
                    },
                );
            }
        };
        results.drain(..extra);
        writer.holder = placed.holder;
        writer.durable = writer.durable.max(placed.last);
        writer.outstanding = 0;
        writer.buffered = 0;
        if let Some(holder) = &writer.holder
            && let Some(row) = writer.rows.get_mut(&holder.request_id)
        {
            row.tail_last = Some(holder.last);
        }
        if let Some(id) = placed.started {
            writer.started.remove(&id);
            if let Some(row) = writer.rows.get_mut(&id) {
                row.status = TurnState::Running;
                started(&mut row.record);
            }
        }
        Ok(results)
    }

    async fn changed(&self, guard: Option<Guard<'_>>, whole: bool) -> bool {
        let Some(guard) = guard else {
            return false;
        };
        let Ok(mut rows) = self
            .query(
                "turn",
                &TURN,
                vec![self.scope.to_string(), guard.request_id.to_owned()],
            )
            .await
        else {
            return false;
        };
        if self.load_cells(&mut rows, &[3, 10]).await.is_err() {
            return false;
        }
        match single(&rows).map(|found| found.map(row)) {
            Ok(Some(Ok(found))) => {
                found.tail_last != guard.tail_last
                    || (whole
                        && (found.status != guard.status || found.record.digest != guard.digest))
            }
            Ok(None) => true,
            _ => false,
        }
    }

    async fn flush_locked(&self, writer: &mut Writer) -> Result<(), StoreError> {
        if writer.buffer.is_empty() {
            return Ok(());
        }
        self.commit(writer, "flush", Vec::new(), None, Spill::default(), |_| {
            Vec::new()
        })
        .await
        .map(drop)
    }

    fn buffer(&self, writer: &mut Writer, line: Line) {
        writer.buffered += line.estimate();
        writer.buffer.push(line);
    }

    pub async fn stage(&self, entries: &[LogEntry]) -> Result<Vec<LoggedEvent>, StoreError> {
        if entries.is_empty() {
            return Ok(Vec::new());
        }
        let created_at = now();
        let mut writer = self.writer().await?;
        let mut logged = Vec::with_capacity(entries.len());
        for entry in entries {
            let request_id = entry.request_id.as_deref();
            let body = if self.event_fits(request_id, entry.event.get()) {
                entry.event.clone()
            } else {
                omitted(request_id, entry.event.get())?
            };
            let line = Line {
                seq: writer.allocate()?,
                created_at,
                request_id: entry.request_id.clone(),
                body,
            };
            logged.push(line.logged());
            self.buffer(&mut writer, line);
        }
        if writer.buffered >= self.chunk_capacity() {
            self.flush_locked(&mut writer).await?;
        }
        Ok(logged)
    }

    pub async fn flush(&self) -> Result<(), StoreError> {
        let mut writer = self.writer().await?;
        self.flush_locked(&mut writer).await
    }

    pub async fn append(&self, entries: &[LogEntry]) -> Result<Vec<LoggedEvent>, StoreError> {
        let logged = self.stage(entries).await?;
        self.flush().await?;
        Ok(logged)
    }

    async fn read(&self, writer: &mut Writer, request_id: &str) -> Result<Option<Row>, StoreError> {
        let mut found = match writer.rows.get(request_id) {
            Some(known) => known.clone(),
            None => {
                let mut rows = self
                    .query(
                        "turn",
                        &TURN,
                        vec![self.scope.to_string(), request_id.to_owned()],
                    )
                    .await?;
                self.load_cells(&mut rows, &[3, 10]).await?;
                let Some(found) = single(&rows)? else {
                    return Ok(None);
                };
                let found = row(found)?;
                if !found.status.is_terminal() {
                    writer.rows.insert(request_id.to_owned(), found.clone());
                }
                found
            }
        };
        if writer.started.contains(request_id) {
            started(&mut found.record);
        }
        if found.record.result.is_none()
            && let Some(seq) = found.record.last_seq
        {
            found.record.result = self.event_at(&*writer, seq).await?;
        }
        Ok(Some(found))
    }

    async fn event_at(
        &self,
        writer: &Writer,
        seq: u64,
    ) -> Result<Option<Box<RawValue>>, StoreError> {
        let (events, _) = self
            .select(writer, seq.saturating_sub(1), Some(seq), None, 1, None)
            .await?;
        Ok(events
            .into_iter()
            .find(|event| event.seq == seq)
            .map(|event| event.event))
    }

    pub async fn turn(&self, request_id: &str) -> Result<Option<TurnRecord>, StoreError> {
        let mut writer = self.writer().await?;
        Ok(self
            .read(&mut writer, request_id)
            .await?
            .map(|row| row.record))
    }

    pub async fn pending(&self) -> Result<Vec<TurnRecord>, StoreError> {
        let mut writer = self.writer().await?;
        let mut rows = self
            .query("pending", &PENDING, vec![self.scope.to_string()])
            .await?;
        self.load_cells(&mut rows, &[3]).await?;
        let mut records = Vec::with_capacity(rows.len());
        for found in &rows {
            let found = row(found)?;
            let mut record = found.record.clone();
            writer.rows.insert(record.request_id.clone(), found);
            if writer.started.contains(&record.request_id) {
                started(&mut record);
            }
            records.push(record);
        }
        Ok(records)
    }

    fn line(
        &self,
        writer: &mut Writer,
        request_id: &str,
        body: Box<RawValue>,
    ) -> Result<Line, StoreError> {
        Ok(Line {
            seq: writer.allocate()?,
            created_at: now(),
            request_id: Some(request_id.to_owned()),
            body,
        })
    }

    pub async fn submit(&self, submission: &Submission) -> Result<Submitted, StoreError> {
        let id = submission.request_id.as_str();
        let digest = submission_digest(&submission.prompt, submission.hand.as_deref())?;
        let mut images = BlobWrites::new();
        let stored = self.stored_prompt(&submission.prompt, &mut images);
        let prompt = serde_json::to_string(&*stored).map_err(encoding)?;
        let body = encoded(&Lifecycle {
            kind: "queued",
            request_id: id,
        })?;
        let metadata = submission.metadata.get();
        if let Some(limit) = self.limit {
            let row = record_bytes(
                TURN_TEXTS,
                self.scope.len()
                    + id.len()
                    + digest.len()
                    + TurnState::Running.as_str().len()
                    + prompt.len()
                    + submission.hand.as_deref().map_or(0, str::len)
                    + metadata.len(),
                TURN_INTEGERS,
            );
            let accepted = event_bytes(
                &self.scope,
                Some(id),
                accepted_bytes(id, &stored.instruction).map_err(encoding)?,
            );
            let bytes = row.max(accepted);
            if bytes > limit {
                return Ok(Submitted::TooLarge { bytes, limit });
            }
        }
        self.put_blobs(&images).await?;
        let mut writer = self.writer().await?;
        let existing = |found: Row| {
            if found.record.digest == digest {
                Submitted::Existing(found.record)
            } else {
                Submitted::Conflict(found.record)
            }
        };
        if let Some(found) = writer.rows.get(id).cloned() {
            return Ok(existing(found));
        }
        let mut spill = Spill::default();
        let hand = serde_json::to_string(&submission.hand).map_err(encoding)?;
        let overhead = record_bytes(
            TURN_TEXTS,
            self.scope.len() + id.len() + digest.len() + hand.len() + metadata.len() + SEAL_BYTES,
            TURN_INTEGERS,
        );
        let prompt = self
            .store_value(&prompt, overhead, false, &mut spill)?
            .into_owned();
        let line = self.line(&mut writer, id, body)?;
        let event = line.logged();
        let seq = line.seq;
        let other = digest.len() + prompt.len() + hand.len() + metadata.len();
        let scope = self.scope.to_string();
        let digested = digest.clone();
        let committed = self
            .commit(
                &mut writer,
                "submit",
                vec![line],
                Some(Own {
                    request_id: id,
                    fresh: true,
                    other,
                    guard: None,
                }),
                spill,
                |own| {
                    let (first, last, tail) = own.cloned().unwrap_or_default();
                    vec![Stmt {
                        sql: &NEW_TURN,
                        params: vec![
                            scope,
                            id.to_owned(),
                            digested,
                            prompt,
                            hand,
                            metadata.to_owned(),
                            seq.to_string(),
                            first.to_string(),
                            last.to_string(),
                            tail,
                        ],
                    }]
                },
            )
            .await;
        if let Err(error) = committed {
            return match self.read(&mut writer, id).await {
                Ok(Some(found)) => Ok(existing(found)),
                _ => Err(error),
            };
        }
        let record = TurnRecord {
            request_id: id.to_owned(),
            state: TurnState::Queued,
            digest: digest.clone(),
            prompt: Some(stored.into_owned()),
            hand: submission.hand.clone(),
            metadata: submission.metadata.clone(),
            cancel_requested: false,
            note: None,
            first_seq: seq,
            last_seq: None,
            result: None,
            retry: None,
        };
        let tail_last = writer
            .holder
            .as_ref()
            .filter(|holder| holder.request_id == id)
            .map(|holder| holder.last);
        writer.rows.insert(
            id.to_owned(),
            Row {
                status: TurnState::Queued,
                record: record.clone(),
                edits: None,
                tail_last,
            },
        );
        Ok(Submitted::Accepted { record, event })
    }

    pub async fn start(&self, request_id: &str) -> Result<Option<Started>, StoreError> {
        let body = encoded(&Lifecycle {
            kind: "running",
            request_id,
        })?;
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(None);
        };
        if found.record.state.is_terminal() {
            return Ok(None);
        }
        let previous = found.record.state;
        let mut record = found.record;
        started(&mut record);
        let line = self.line(&mut writer, request_id, body)?;
        let event = line.logged();
        self.buffer(&mut writer, line);
        writer.started.insert(request_id.to_owned());
        if writer.buffered >= self.chunk_capacity() {
            self.flush_locked(&mut writer).await?;
        }
        Ok(Some(Started {
            previous,
            record,
            event,
        }))
    }

    async fn update(
        &self,
        writer: &mut Writer,
        operation: &'static str,
        found: &Row,
        mut change: Change,
        lines: Vec<Line>,
        mut spill: Spill,
    ) -> Result<(), StoreError> {
        let request_id = found.record.request_id.as_str();
        if writer.started.contains(request_id) {
            change.note.get_or_insert(None);
            change.retry.get_or_insert(None);
        }
        let overhead = record_bytes(
            TURN_TEXTS,
            self.scope.len() + request_id.len() + found.record.metadata.get().len() + SEAL_BYTES,
            TURN_INTEGERS,
        );
        if let Some(Some(prompt)) = &mut change.prompt {
            *prompt = self
                .store_value(prompt, overhead, false, &mut spill)?
                .into_owned();
        }
        if let Some(Some(result)) = &mut change.result {
            *result = self
                .store_value(result, overhead, false, &mut spill)?
                .into_owned();
        }
        let added: usize = [
            &change.prompt,
            &change.note,
            &change.retry,
            &change.edits,
            &change.result,
        ]
        .into_iter()
        .map(|value| {
            value
                .as_ref()
                .and_then(Option::as_ref)
                .map_or(0, String::len)
        })
        .sum();
        let other = writer
            .holder
            .as_ref()
            .filter(|holder| holder.request_id == request_id)
            .map_or(0, |holder| holder.other)
            + added
            + change.digest.as_ref().map_or(0, String::len);
        let scope = self.scope.to_string();
        let digest = change
            .digest
            .clone()
            .unwrap_or_else(|| found.record.digest.clone());
        let check = vec![
            scope.clone(),
            request_id.to_owned(),
            found.status.as_str().to_owned(),
            found.record.digest.clone(),
            found
                .tail_last
                .map_or_else(|| "-1".to_owned(), |seq| seq.to_string()),
        ];
        let forget = change.state.is_terminal() || matches!(change.prompt, Some(Some(_)));
        let known = (
            change.state,
            change.digest.clone(),
            change.cancel_requested,
            change.note.clone(),
            change.retry.clone(),
            change.edits.clone(),
        );
        let (prompt_flag, prompt) = flag(change.prompt.as_ref());
        let (note_flag, note) = flag(change.note.as_ref());
        let (retry_flag, retry) = flag(change.retry.as_ref());
        let (edits_flag, edits) = flag(change.edits.as_ref());
        let (result_flag, result) = flag(change.result.as_ref());
        let params = move |own: Option<&(u64, u64, String)>| {
            let (first, last, tail) = own.map_or(
                (String::new(), String::new(), String::new()),
                |(first, last, tail)| (first.to_string(), last.to_string(), tail.clone()),
            );
            vec![
                scope,
                request_id.to_owned(),
                change.state.as_str().to_owned(),
                digest,
                prompt_flag.to_owned(),
                prompt,
                u8::from(change.cancel_requested).to_string(),
                note_flag.to_owned(),
                note,
                retry_flag.to_owned(),
                retry,
                edits_flag.to_owned(),
                edits,
                change
                    .last_seq
                    .map(|seq| seq.to_string())
                    .unwrap_or_default(),
                result_flag.to_owned(),
                result,
                first,
                last,
                tail,
                found.status.as_str().to_owned(),
                found.record.digest.clone(),
                found
                    .tail_last
                    .map_or_else(|| "-1".to_owned(), |seq| seq.to_string()),
            ]
        };
        let applied = self
            .commit(
                writer,
                operation,
                lines,
                Some(Own {
                    request_id,
                    fresh: false,
                    other,
                    guard: Some(Guard {
                        request_id,
                        status: found.status,
                        digest: &found.record.digest,
                        tail_last: found.tail_last,
                    }),
                }),
                spill,
                |own| {
                    vec![
                        Stmt {
                            sql: &CHECK_TURN,
                            params: check,
                        },
                        Stmt {
                            sql: &UPDATE_TURN,
                            params: params(own),
                        },
                    ]
                },
            )
            .await?
            .last()
            .is_some_and(|rows| !rows.is_empty());
        if !applied {
            writer.stale = true;
            return Err(StoreError::Backend(format!(
                "session log turn {request_id} changed outside this writer"
            )));
        }
        writer.started.remove(request_id);
        if forget {
            writer.rows.remove(request_id);
            return Ok(());
        }
        let (state, digest, cancel_requested, note, retry, edits) = known;
        let mut row = writer
            .rows
            .remove(request_id)
            .unwrap_or_else(|| found.clone());
        row.status = state;
        row.record.state = state;
        row.record.cancel_requested = cancel_requested;
        if let Some(digest) = digest {
            row.record.digest = digest;
        }
        if let Some(note) = note {
            row.record.note = note;
        }
        if let Some(retry) = retry {
            row.record.retry = retry
                .map(|retry| serde_json::from_str(&retry))
                .transpose()
                .map_err(|error| invalid(format!("retry: {error}")))?;
        }
        if let Some(edits) = edits {
            row.edits = edits;
        }
        if let Some(holder) = writer
            .holder
            .as_ref()
            .filter(|holder| holder.request_id == request_id)
        {
            row.tail_last = Some(holder.last);
        }
        writer.rows.insert(request_id.to_owned(), row);
        Ok(())
    }

    async fn close(
        &self,
        writer: &mut Writer,
        operation: &'static str,
        found: Row,
        state: TurnState,
        body: Box<RawValue>,
    ) -> Result<(TurnRecord, LoggedEvent), StoreError> {
        let line = self.line(writer, &found.record.request_id, body.clone())?;
        let event = line.logged();
        let seq = line.seq;
        self.update(
            writer,
            operation,
            &found,
            Change {
                state,
                digest: None,
                prompt: Some(None),
                cancel_requested: found.record.cancel_requested,
                note: Some(None),
                retry: Some(None),
                edits: None,
                last_seq: Some(seq),
                result: Some(Some(body.get().to_owned())),
            },
            vec![line],
            Spill::default(),
        )
        .await?;
        let mut record = found.record;
        record.state = state;
        record.prompt = None;
        record.note = None;
        record.retry = None;
        record.last_seq = Some(seq);
        record.result = Some(body);
        Ok((record, event))
    }

    const fn change(record: &TurnRecord) -> Change {
        Change {
            state: record.state,
            digest: None,
            prompt: None,
            cancel_requested: record.cancel_requested,
            note: None,
            retry: None,
            edits: None,
            last_seq: None,
            result: None,
        }
    }

    pub async fn finish(
        &self,
        request_id: &str,
        state: TurnState,
        fields: &Map<String, Value>,
    ) -> Result<Option<(TurnRecord, LoggedEvent)>, StoreError> {
        if !state.is_terminal() {
            return Err(StoreError::NotCommitted(format!(
                "a turn cannot finish as {}",
                state.as_str()
            )));
        }
        let mut state = state;
        let mut body = encoded(&Outcome {
            kind: "result",
            request_id,
            status: state.as_str(),
            fields,
        })?;
        if let Some(limit) = self
            .limit
            .filter(|_| !self.event_fits(Some(request_id), body.get()))
        {
            let mut failure = Map::new();
            failure.insert(
                "error".into(),
                format!(
                    "the turn's {} result is {} bytes, more than the {limit} bytes the session log stores in one event",
                    state.as_str(),
                    body.get().len()
                )
                .into(),
            );
            state = TurnState::Failed;
            body = encoded(&Outcome {
                kind: "result",
                request_id,
                status: state.as_str(),
                fields: &failure,
            })?;
        }
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(None);
        };
        if found.record.state.is_terminal() {
            return Ok(None);
        }
        self.close(&mut writer, "finish", found, state, body)
            .await
            .map(Some)
    }

    pub async fn cancel(
        &self,
        request_id: &str,
        fields: &Map<String, Value>,
    ) -> Result<Option<(TurnRecord, Option<LoggedEvent>)>, StoreError> {
        let body = encoded(&Outcome {
            kind: "result",
            request_id,
            status: TurnState::Cancelled.as_str(),
            fields,
        })?;
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(None);
        };
        match found.record.state {
            TurnState::Running if !found.record.cancel_requested => {
                let mut change = Self::change(&found.record);
                change.cancel_requested = true;
                self.update(
                    &mut writer,
                    "cancel",
                    &found,
                    change,
                    Vec::new(),
                    Spill::default(),
                )
                .await?;
                let mut record = found.record;
                record.cancel_requested = true;
                Ok(Some((record, None)))
            }
            TurnState::Queued => {
                let (record, event) = self
                    .close(&mut writer, "cancel", found, TurnState::Cancelled, body)
                    .await?;
                Ok(Some((record, Some(event))))
            }
            _ => Ok(Some((found.record, None))),
        }
    }

    pub async fn replace_queued(
        &self,
        request_id: &str,
        edit_id: &str,
        text: &str,
    ) -> Result<Replaced, StoreError> {
        if edit_id.is_empty() {
            return Err(StoreError::NotCommitted(
                "an edit ID must not be empty".into(),
            ));
        }
        let edit = submission_digest(&Prompt::new(text), None)?;
        let body = encoded(&Replacement {
            kind: "replaced",
            request_id,
            edit_id,
            digest: &edit,
        })?;
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(Replaced::NotQueued);
        };
        let mut edits: BTreeMap<String, String> = match &found.edits {
            Some(edits) => serde_json::from_str(edits)
                .map_err(|error| invalid(format!("edit receipts: {error}")))?,
            None => BTreeMap::new(),
        };
        if let Some(applied) = edits.get(edit_id) {
            return Ok(if *applied == edit {
                Replaced::Applied(None)
            } else {
                Replaced::Conflict
            });
        }
        let Some(prompt) = found
            .record
            .prompt
            .as_ref()
            .filter(|_| found.record.state == TurnState::Queued)
        else {
            return Ok(Replaced::NotQueued);
        };
        let prompt = edited(prompt, text)?;
        let digest = submission_digest(&prompt, found.record.hand.as_deref())?;
        let mut images = BlobWrites::new();
        let stored = self.stored_prompt(&prompt, &mut images);
        let stored = serde_json::to_string(&*stored).map_err(encoding)?;
        if let Some(limit) = self.limit {
            let row = record_bytes(
                TURN_TEXTS,
                self.scope.len()
                    + request_id.len()
                    + digest.len()
                    + TurnState::Running.as_str().len()
                    + stored.len()
                    + found.record.hand.as_deref().map_or(0, str::len)
                    + found.record.metadata.get().len(),
                TURN_INTEGERS,
            );
            let accepted = event_bytes(
                &self.scope,
                Some(request_id),
                accepted_bytes(request_id, &prompt.instruction).map_err(encoding)?,
            );
            let receipt = event_bytes(&self.scope, Some(request_id), body.get().len());
            let bytes = row.max(accepted).max(receipt);
            if bytes > limit {
                return Ok(Replaced::TooLarge { bytes, limit });
            }
        }
        self.put_blobs(&images).await?;
        edits.insert(edit_id.to_owned(), edit);
        let line = self.line(&mut writer, request_id, body)?;
        let event = line.logged();
        let mut change = Self::change(&found.record);
        change.digest = Some(digest);
        change.prompt = Some(Some(stored));
        change.edits = Some(Some(serde_json::to_string(&edits).map_err(encoding)?));
        self.update(
            &mut writer,
            "replace",
            &found,
            change,
            vec![line],
            Spill::default(),
        )
        .await?;
        Ok(Replaced::Applied(Some(event)))
    }

    pub async fn withdraw_steered(
        &self,
        request_id: &str,
        digest: &str,
    ) -> Result<Option<(TurnRecord, LoggedEvent)>, StoreError> {
        let fields = Map::from_iter([
            ("cancelled".to_owned(), Value::Bool(true)),
            ("steered".to_owned(), Value::Bool(true)),
        ]);
        let body = encoded(&Outcome {
            kind: "result",
            request_id,
            status: TurnState::Cancelled.as_str(),
            fields: &fields,
        })?;
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(None);
        };
        if found.record.state != TurnState::Queued || found.record.digest != digest {
            return Ok(None);
        }
        self.close(
            &mut writer,
            "withdraw_steered",
            found,
            TurnState::Cancelled,
            body,
        )
        .await
        .map(Some)
    }

    pub async fn retry(
        &self,
        request_id: &str,
        error: &str,
        kind: &str,
        retry_at: u64,
    ) -> Result<Option<(TurnRecord, Option<LoggedEvent>)>, StoreError> {
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(None);
        };
        if found.record.state.is_terminal() {
            return Ok(Some((found.record, None)));
        }
        let retry = TurnRetry {
            error: error.to_owned(),
            kind: kind.to_owned(),
            attempts: found
                .record
                .retry
                .as_ref()
                .map_or(0, |retry| retry.attempts)
                + 1,
            retry_at,
        };
        let changed = found
            .record
            .retry
            .as_ref()
            .is_none_or(|old| old.error != error || old.kind != kind);
        let line = if changed {
            let body = encoded(&Retrying {
                tag: "retrying",
                request_id,
                error,
                kind,
                attempts: retry.attempts,
                retry_at,
            })?;
            Some(self.line(&mut writer, request_id, body)?)
        } else {
            None
        };
        let event = line.as_ref().map(Line::logged);
        let mut change = Self::change(&found.record);
        change.retry = Some(Some(serde_json::to_string(&retry).map_err(encoding)?));
        self.update(
            &mut writer,
            "retry",
            &found,
            change,
            line.into_iter().collect(),
            Spill::default(),
        )
        .await?;
        let mut record = found.record;
        record.retry = Some(retry);
        Ok(Some((record, event)))
    }

    pub async fn interrupted(&self, request_id: &str, note: &str) -> Result<(), StoreError> {
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(());
        };
        if found.record.state != TurnState::Running {
            return Ok(());
        }
        let mut change = Self::change(&found.record);
        change.note = Some(Some(note.to_owned()));
        self.update(
            &mut writer,
            "interrupted",
            &found,
            change,
            Vec::new(),
            Spill::default(),
        )
        .await
    }

    async fn select(
        &self,
        writer: &Writer,
        after: u64,
        end: Option<u64>,
        request_id: Option<&str>,
        limit: usize,
        max_bytes: Option<usize>,
    ) -> Result<(Vec<LoggedEvent>, bool), StoreError> {
        let wanted = |seq: u64, id: Option<&str>| {
            seq > after
                && end.is_none_or(|end| seq <= end)
                && request_id.is_none_or(|request_id| id == Some(request_id))
        };
        let mut found: BTreeMap<u64, Event> = BTreeMap::new();
        let most = usize::try_from(i64::MAX).unwrap_or(usize::MAX);
        let mut batch = max_bytes
            .map_or(limit, |bytes| limit.min(bytes / SEAL_BYTES + 1))
            .clamp(1, most);
        let mut chunk_from: Option<u64> = None;
        let mut tail_from: Option<u64> = None;
        let (mut chunks_done, mut tails_done) = (false, false);
        let scope = self.scope.to_string();
        let start = after.to_string();
        let frontier = loop {
            let size = batch.to_string();
            let mut statements = Vec::new();
            if !chunks_done {
                if chunk_from.is_none() {
                    statements.push(Stmt {
                        sql: &CHUNK_AT,
                        params: vec![scope.clone(), start.clone()],
                    });
                }
                statements.push(Stmt {
                    sql: &CHUNKS,
                    params: vec![
                        scope.clone(),
                        chunk_from.map_or_else(|| start.clone(), |seq| seq.to_string()),
                        size.clone(),
                    ],
                });
            }
            if !tails_done {
                statements.push(Stmt {
                    sql: &TAILS,
                    params: vec![
                        scope.clone(),
                        start.clone(),
                        tail_from.map_or_else(|| "-1".to_owned(), |seq| seq.to_string()),
                        size.clone(),
                    ],
                });
            }
            let results = self.execute("page", &statements, &Spill::default()).await?;
            let mut results = results.into_iter();
            let mut take = |rows: Vec<SqlRow>| -> Result<(usize, Option<u64>), StoreError> {
                let mut first = None;
                for row in &rows {
                    first = Some(counter(text(row, 0)?)?);
                    if counter(text(row, 1)?)? <= after {
                        continue;
                    }
                    for event in decode_lines(text(row, 2)?)? {
                        if wanted(event.0, event.2.as_deref()) {
                            found.insert(event.0, event);
                        }
                    }
                }
                Ok((rows.len(), first))
            };
            if !chunks_done {
                if chunk_from.is_none() {
                    take(results.next().unwrap_or_default())?;
                }
                let (count, first) = take(results.next().unwrap_or_default())?;
                chunks_done = count < batch;
                chunk_from = Some(first.unwrap_or(after));
            }
            if !tails_done {
                let (count, first) = take(results.next().unwrap_or_default())?;
                tails_done = count < batch;
                tail_from = first.or(tail_from);
            }
            let frontier = match (chunks_done, tails_done) {
                (true, true) => u64::MAX,
                (true, false) => tail_from.unwrap_or(after),
                (false, true) => chunk_from.unwrap_or(after),
                (false, false) => chunk_from.unwrap_or(after).min(tail_from.unwrap_or(after)),
            };
            if frontier == u64::MAX || end.is_some_and(|end| frontier >= end) {
                break frontier;
            }
            let mut count = 0;
            let mut bytes = 0_usize;
            let mut enough = false;
            for event in found.range(..=frontier).map(|(_, event)| event) {
                count += 1;
                bytes = bytes.saturating_add(decoded_bytes(event.3.get())?);
                if count >= limit || max_bytes.is_some_and(|max| bytes > max) {
                    enough = true;
                    break;
                }
            }
            if enough {
                break frontier;
            }
            batch = batch.saturating_mul(2).min(most);
        };
        let mut events: Vec<Event> = found
            .into_iter()
            .take_while(|(seq, _)| *seq <= frontier)
            .map(|(_, event)| event)
            .collect();
        if frontier == u64::MAX {
            events.extend(
                writer
                    .buffer
                    .iter()
                    .filter(|line| wanted(line.seq, line.request_id.as_deref()))
                    .map(|line| {
                        (
                            line.seq,
                            line.created_at,
                            line.request_id.clone(),
                            line.body.clone(),
                        )
                    }),
            );
        }
        let complete = frontier == u64::MAX || end.is_some_and(|end| frontier >= end);
        let known = events.len();
        events.truncate(limit);
        if let Some(max) = max_bytes {
            let mut running = 0_usize;
            let mut fitting = 0;
            for event in &events {
                running = running.saturating_add(decoded_bytes(event.3.get())?);
                if fitting > 0 && running > max {
                    break;
                }
                fitting += 1;
            }
            events.truncate(fitting);
        }
        let has_more = match max_bytes {
            Some(_) => events.len() < known || !complete,
            None => events.len() == limit,
        };
        let mut logged = Vec::with_capacity(events.len());
        for (seq, created_at, request_id, mut body) in events {
            self.loaded(&mut body).await?;
            logged.push(LoggedEvent {
                seq,
                request_id,
                created_at,
                event: body,
            });
        }
        Ok((logged, has_more))
    }

    pub async fn page(&self, after: u64, limit: usize) -> Result<LogPage, StoreError> {
        if limit == 0 {
            return Ok(page_of(Vec::new(), after, true));
        }
        let writer = self.writer().await?;
        let (events, has_more) = self.select(&writer, after, None, None, limit, None).await?;
        Ok(page_of(events, after, has_more))
    }

    pub async fn page_bounded(
        &self,
        after: u64,
        limit: usize,
        max_bytes: usize,
    ) -> Result<LogPage, StoreError> {
        if limit == 0 {
            return Err(StoreError::NotCommitted(
                "bounded session log pages require a positive event count".into(),
            ));
        }
        let writer = self.writer().await?;
        let (events, has_more) = self
            .select(&writer, after, None, None, limit, Some(max_bytes))
            .await?;
        Ok(page_of(events, after, has_more))
    }

    pub async fn turn_page(
        &self,
        request_id: &str,
        after: u64,
        limit: usize,
    ) -> Result<LogPage, StoreError> {
        self.turn_events(request_id, after, limit, None).await
    }

    pub async fn turn_page_bounded(
        &self,
        request_id: &str,
        after: u64,
        limit: usize,
        max_bytes: usize,
    ) -> Result<LogPage, StoreError> {
        if limit == 0 {
            return Err(StoreError::NotCommitted(
                "bounded session log pages require a positive event count".into(),
            ));
        }
        self.turn_events(request_id, after, limit, Some(max_bytes))
            .await
    }

    async fn turn_events(
        &self,
        request_id: &str,
        after: u64,
        limit: usize,
        max_bytes: Option<usize>,
    ) -> Result<LogPage, StoreError> {
        let mut writer = self.writer().await?;
        let Some(found) = self.read(&mut writer, request_id).await? else {
            return Ok(page_of(Vec::new(), after, false));
        };
        let start = after.max(found.record.first_seq.saturating_sub(1));
        if limit == 0 {
            return Ok(page_of(Vec::new(), start, true));
        }
        let (events, has_more) = self
            .select(
                &writer,
                start,
                found.record.last_seq,
                Some(request_id),
                limit,
                max_bytes,
            )
            .await?;
        Ok(page_of(events, start, has_more))
    }

    pub async fn import(&self, turns: &[ImportedTurn]) -> Result<usize, StoreError> {
        if turns.is_empty() {
            return Ok(0);
        }
        let mut writer = self.writer().await?;
        let ids = serde_json::to_string(
            &turns
                .iter()
                .map(|turn| turn.request_id.as_str())
                .collect::<Vec<_>>(),
        )
        .map_err(encoding)?;
        let existing: BTreeSet<String> = self
            .query("import", &EXISTING, vec![self.scope.to_string(), ids])
            .await?
            .iter()
            .map(|row| text(row, 0).map(str::to_owned))
            .collect::<Result<_, _>>()?;
        let mut spill = Spill::default();
        let mut lines = Vec::new();
        let mut rows = Vec::new();
        for turn in turns {
            if existing.contains(&turn.request_id) {
                continue;
            }
            let result = turn
                .result
                .as_ref()
                .filter(|_| turn.state.is_terminal())
                .map(|fields| {
                    encoded(&Outcome {
                        kind: "result",
                        request_id: &turn.request_id,
                        status: turn.state.as_str(),
                        fields,
                    })
                })
                .transpose()?;
            let last_seq = match (&result, turn.last_seq) {
                (Some(body), None) => {
                    let line = self.line(&mut writer, &turn.request_id, body.clone())?;
                    let seq = line.seq;
                    lines.push(line);
                    Some(seq)
                }
                (_, last_seq) => last_seq,
            };
            rows.push(Imported {
                request_id: &turn.request_id,
                digest: submission_digest(&turn.prompt, turn.hand.as_deref())?,
                status: turn.state.as_str(),
                prompt: (!turn.state.is_terminal())
                    .then(|| {
                        serde_json::to_string(&*self.stored_prompt(&turn.prompt, &mut spill.blobs))
                    })
                    .transpose()
                    .map_err(encoding)?,
                hand: turn.hand.as_deref(),
                metadata: turn.metadata.get(),
                cancel_requested: u8::from(turn.cancel_requested),
                note: turn.note.as_deref(),
                first_seq: turn.first_seq.unwrap_or(0),
                last_seq,
                result: result.map(|body| body.get().to_owned()),
            });
        }
        for row in &mut rows {
            let encoded = serde_json::to_string(row).map_err(encoding)?;
            let force = self.physical_limit.is_some_and(|limit| {
                encoded.len().saturating_add(
                    2 + self.scope.len() + record_bytes(TURN_TEXTS, 0, TURN_INTEGERS),
                ) > limit
            });
            let other = self.scope.len()
                + row.request_id.len()
                + row.digest.len()
                + row.status.len()
                + row.metadata.len()
                + row.hand.map_or(0, str::len)
                + row.note.map_or(0, str::len);
            for value in [&mut row.prompt, &mut row.result].into_iter().flatten() {
                *value = self
                    .store_value(
                        value,
                        record_bytes(TURN_TEXTS, other, TURN_INTEGERS),
                        force,
                        &mut spill,
                    )?
                    .into_owned();
            }
        }
        let batches = self.batches(&rows)?;
        let scope = self.scope.to_string();
        self.commit(&mut writer, "import", lines, None, spill, |_| {
            batches
                .into_iter()
                .map(|batch| Stmt {
                    sql: &IMPORT,
                    params: vec![scope.clone(), batch],
                })
                .collect()
        })
        .await?;
        Ok(turns.len())
    }

    pub async fn import_events(
        &self,
        after: u64,
        events: &[LoggedEvent],
    ) -> Result<u64, StoreError> {
        let Some(last) = events.last() else {
            return Ok(after);
        };
        let mut previous = after;
        for event in events {
            if event.seq <= previous {
                return Err(StoreError::NotCommitted(format!(
                    "imported session log events must ascend after seq {previous}, but seq {} follows it",
                    event.seq
                )));
            }
            if !self.event_fits(event.request_id.as_deref(), event.event.get()) {
                return Err(StoreError::NotCommitted(format!(
                    "imported session log event {} does not fit the log's logical limit",
                    event.seq
                )));
            }
            previous = event.seq;
        }
        let mut writer = self.writer().await?;
        self.flush_locked(&mut writer).await?;
        let ends = writer.durable;
        if ends < after {
            return Err(StoreError::NotCommitted(format!(
                "session log {} ends at seq {ends}, before the seq {after} the imported events follow",
                self.scope
            )));
        }
        let (held, _) = self
            .select(&writer, after, Some(last.seq), None, usize::MAX, None)
            .await?;
        let imported: BTreeMap<u64, &LoggedEvent> =
            events.iter().map(|event| (event.seq, event)).collect();
        for event in &held {
            match imported.get(&event.seq) {
                None => {
                    return Err(StoreError::NotCommitted(format!(
                        "session log {} holds event {}, which the imported events after seq {after} do not",
                        self.scope, event.seq
                    )));
                }
                Some(import)
                    if import.request_id != event.request_id
                        || import.created_at != event.created_at
                        || import.event.get() != event.event.get() =>
                {
                    return Err(StoreError::NotCommitted(format!(
                        "session log {} already holds a different event at seq {}",
                        self.scope, event.seq
                    )));
                }
                Some(_) => {}
            }
        }
        let held: BTreeSet<u64> = held.iter().map(|event| event.seq).collect();
        if let Some(missing) = events
            .iter()
            .find(|event| event.seq <= ends && !held.contains(&event.seq))
        {
            return Err(StoreError::NotCommitted(format!(
                "session log {} lacks imported event {} but holds later events",
                self.scope, missing.seq
            )));
        }
        let fresh = &events[events.partition_point(|event| event.seq <= ends)..];
        if fresh.is_empty() {
            return Ok(last.seq);
        }
        let mut spill = Spill::default();
        let texts = fresh
            .iter()
            .map(|event| {
                let line = Line {
                    seq: event.seq,
                    created_at: event.created_at,
                    request_id: event.request_id.clone(),
                    body: event.event.clone(),
                };
                Ok((event.seq, self.encode_line(&line, &mut spill)?))
            })
            .collect::<Result<Vec<_>, StoreError>>()?;
        let statements = self.chunks(&texts);
        let results = self.execute("import_events", &statements, &spill).await?;
        if results.iter().any(Vec::is_empty) {
            writer.ready = false;
            return Err(StoreError::NotCommitted(format!(
                "session log {} changed while its events were imported",
                self.scope
            )));
        }
        writer.durable = last.seq;
        writer.next = writer.next.max(last.seq.saturating_add(1));
        writer.holder = None;
        Ok(last.seq)
    }

    fn batches(&self, rows: &[Imported<'_>]) -> Result<Vec<String>, StoreError> {
        let mut batches = Vec::new();
        let mut batch = String::from("[");
        for row in rows {
            let encoded = serde_json::to_string(row).map_err(encoding)?;
            if self.physical_limit.is_some_and(|limit| {
                encoded.len().saturating_add(
                    2 + self.scope.len() + record_bytes(TURN_TEXTS, 0, TURN_INTEGERS),
                ) > limit
            }) {
                return Err(StoreError::NotCommitted(
                    "imported turn exceeds the physical row or binding limit".into(),
                ));
            }
            if batch.len() > 1
                && self
                    .physical_limit
                    .is_some_and(|limit| batch.len() + encoded.len() + 2 > limit)
            {
                batch.push(']');
                batches.push(std::mem::replace(&mut batch, String::from("[")));
            }
            if batch.len() > 1 {
                batch.push(',');
            }
            batch.push_str(&encoded);
        }
        batch.push(']');
        if batch.len() > 2 {
            batches.push(batch);
        }
        Ok(batches)
    }
}

impl<H: Sql + Send + Sync + ?Sized + 'static> SessionLog<H> {
    async fn recorded(&self, recording: Recording<'_>) -> Result<Vec<LoggedEvent>, String> {
        let unannotated = Map::new();
        let compact = self.compact.then_some(recording.session_id);
        let (entries, live): (Vec<_>, Vec<_>) = recording
            .events
            .iter()
            .zip(recording.request_ids)
            .map(|(event, request_id)| {
                let mut body = serde_json::value::to_raw_value(&Envelope {
                    event,
                    annotation: recording.annotation,
                })?;
                if !recording.annotation.is_empty()
                    && !self.event_fits(request_id.as_deref(), body.get())
                {
                    body = serde_json::value::to_raw_value(&Envelope {
                        event,
                        annotation: &unannotated,
                    })?;
                }
                let stored = serde_json::value::to_raw_value(&Stored { event, compact })?;
                Ok((
                    LogEntry {
                        request_id: request_id.clone(),
                        event: stored,
                    },
                    body,
                ))
            })
            .collect::<Result<Vec<_>, serde_json::Error>>()
            .map_err(|error| format!("encode agent event: {error}"))?
            .into_iter()
            .unzip();
        let logged = self
            .stage(&entries)
            .await
            .map_err(|error| error.to_string())?;
        Ok(logged
            .into_iter()
            .zip(&entries)
            .zip(live)
            .map(|((mut logged, entry), live)| {
                if logged.event.get() == entry.event.get() {
                    logged.event = live;
                }
                logged
            })
            .collect())
    }
}

impl<H: Sql + Send + Sync + ?Sized + 'static> EventLog for SessionLog<H> {
    fn record<'a>(
        &'a self,
        recording: Recording<'a>,
    ) -> HostFuture<'a, Result<Vec<LoggedEvent>, String>> {
        Box::pin(self.recorded(recording))
    }

    fn flush(&self) -> Logged<'_, ()> {
        Box::pin(Self::flush(self))
    }
}

impl<H: Sql + Send + Sync + ?Sized + 'static> TurnLog for SessionLog<H> {
    fn turn<'a>(&'a self, request_id: &'a str) -> Logged<'a, Option<TurnRecord>> {
        Box::pin(Self::turn(self, request_id))
    }

    fn pending(&self) -> Logged<'_, Vec<TurnRecord>> {
        Box::pin(Self::pending(self))
    }

    fn start<'a>(&'a self, request_id: &'a str) -> Logged<'a, Option<Started>> {
        Box::pin(Self::start(self, request_id))
    }

    fn finish<'a>(
        &'a self,
        request_id: &'a str,
        state: TurnState,
        fields: &'a Map<String, Value>,
    ) -> Logged<'a, Option<(TurnRecord, LoggedEvent)>> {
        Box::pin(Self::finish(self, request_id, state, fields))
    }

    fn cancel<'a>(
        &'a self,
        request_id: &'a str,
        fields: &'a Map<String, Value>,
    ) -> Logged<'a, Option<(TurnRecord, Option<LoggedEvent>)>> {
        Box::pin(Self::cancel(self, request_id, fields))
    }

    fn withdraw_steered<'a>(
        &'a self,
        request_id: &'a str,
        digest: &'a str,
    ) -> Logged<'a, Option<(TurnRecord, LoggedEvent)>> {
        Box::pin(Self::withdraw_steered(self, request_id, digest))
    }
}
