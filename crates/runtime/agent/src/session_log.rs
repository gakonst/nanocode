impl Line {
    fn estimate(&self) -> usize {
        LINE_FRAME_BYTES
            + self.request_id.as_ref().map_or(4, |id| id.len() + 2)
            + self.body.get().len()
    }

    fn logged(&self) -> LoggedEvent {
        LoggedEvent {
            seq: self.seq,
            request_id: self.request_id.clone(),
            created_at: self.created_at,
            event: self.body.clone(),
        }
    }
}

