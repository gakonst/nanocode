fn invalid(detail: impl std::fmt::Display) -> StoreError {
    StoreError::Backend(format!(
        "SQL host answered an invalid session log row: {detail}"
    ))
}

fn encoding(error: serde_json::Error) -> StoreError {
    StoreError::NotCommitted(format!("encode session log entry: {error}"))
}

fn text(row: &SqlRow, column: usize) -> Result<&str, StoreError> {
    row.get(column)
        .and_then(Option::as_deref)
        .ok_or_else(|| invalid(format!("column {column} is missing")))
}

fn optional(row: &SqlRow, column: usize) -> Option<&str> {
    row.get(column).and_then(Option::as_deref)
}

fn counter(value: &str) -> Result<u64, StoreError> {
    value
        .parse()
        .map_err(|error| invalid(format!("counter `{value}`: {error}")))
}

fn single(rows: &[SqlRow]) -> Result<Option<&SqlRow>, StoreError> {
    match rows {
        [] => Ok(None),
        [row] => Ok(Some(row)),
        _ => Err(invalid(format!(
            "{} rows for a single-row query",
            rows.len()
        ))),
    }
}

fn raw(json: String) -> Result<Box<RawValue>, StoreError> {
    RawValue::from_string(json).map_err(|error| invalid(format!("stored JSON: {error}")))
}

fn encoded(value: &impl Serialize) -> Result<Box<RawValue>, StoreError> {
    serde_json::value::to_raw_value(value).map_err(encoding)
}

const fn record_bytes(texts: usize, text_bytes: usize, integers: usize) -> usize {
    VARINT_BYTES * (1 + texts + integers) + INTEGER_BYTES * integers + text_bytes
}

const fn event_bytes(scope: &str, request_id: Option<&str>, body: usize) -> usize {
    let request_id = match request_id {
        Some(request_id) => request_id.len(),
        None => 0,
    };
    record_bytes(EVENT_TEXTS, scope.len() + request_id + body, EVENT_INTEGERS)
}

fn omitted(request_id: Option<&str>, body: &str) -> Result<Box<RawValue>, StoreError> {
    let described = serde_json::from_str::<Value>(body).unwrap_or_default();
    let named = |pointer: &str| described.pointer(pointer).and_then(Value::as_str);
    let source = named("/source").map(str::to_owned);
    let event_type = named("/event/type")
        .or_else(|| named("/update/event/type"))
        .or_else(|| named("/update/type"))
        .or_else(|| named("/type"))
        .map(str::to_owned);
    encoded(&Omitted {
        kind: "omitted",
        request_id,
        source,
        event_type,
        bytes: body.len(),
    })
}

fn reference(value: &str) -> Result<PayloadReference, StoreError> {
    serde_json::from_str(value).map_err(|error| invalid(format!("payload reference: {error}")))
}

fn decoded_bytes(body: &str) -> Result<usize, StoreError> {
    if body.starts_with(PAYLOAD_MARK) {
        Ok(reference(body)?.bytes)
    } else {
        Ok(body.len())
    }
}

pub(crate) fn now() -> u64 {
    nanocode_platform::system_time()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| {
            u64::try_from(elapsed.as_millis()).unwrap_or(u64::MAX)
        })
}

fn decode_lines(body: &str) -> Result<Vec<Event>, StoreError> {
    serde_json::Deserializer::from_str(body)
        .into_iter::<Event>()
        .map(|line| line.map_err(|error| invalid(format!("session log line: {error}"))))
        .collect()
}

fn row(row: &SqlRow) -> Result<Row, StoreError> {
    Ok(Row {
        status: TurnState::parse(text(row, 1)?)?,
        record: TurnRecord {
            request_id: text(row, 0)?.to_owned(),
            state: TurnState::parse(text(row, 1)?)?,
            digest: text(row, 2)?.to_owned(),
            prompt: optional(row, 3)
                .map(|prompt| {
                    serde_json::from_str(prompt)
                        .map_err(|error| invalid(format!("prompt: {error}")))
                })
                .transpose()?,
            hand: optional(row, 4).map(str::to_owned),
            metadata: raw(text(row, 5)?.to_owned())?,
            cancel_requested: text(row, 6)? != "0",
            note: optional(row, 7).map(str::to_owned),
            first_seq: counter(text(row, 8)?)?,
            last_seq: optional(row, 9).map(counter).transpose()?,
            result: optional(row, 10)
                .map(|body| raw(body.to_owned()))
                .transpose()?,
            retry: optional(row, 11)
                .map(|retry| {
                    serde_json::from_str(retry).map_err(|error| invalid(format!("retry: {error}")))
                })
                .transpose()?,
        },
        edits: optional(row, 12).map(str::to_owned),
        tail_last: optional(row, 13).map(counter).transpose()?,
    })
}

pub fn submission_digest(prompt: &Prompt, hand: Option<&str>) -> Result<String, StoreError> {
    EncodedPayload::encode(&(prompt, hand))
        .map(|payload| payload.key().to_owned())
        .map_err(|error| StoreError::NotCommitted(format!("digest turn submission: {error}")))
}

fn edited(prompt: &Prompt, text: &str) -> Result<Prompt, StoreError> {
    let mut prompt = prompt.clone();
    prompt.instruction = match prompt.instruction {
        PromptInput::Text(_) => PromptInput::Text(text.to_owned()),
        PromptInput::Content(items) => {
            let mut text = (!text.is_empty()).then(|| UserInput::Text {
                text: text.to_owned(),
            });
            let mut edited: Vec<_> = items
                .into_iter()
                .filter_map(|item| match item {
                    UserInput::Text { .. } => text.take(),
                    other => Some(other),
                })
                .collect();
            edited.splice(0..0, text);
            PromptInput::Content(edited)
        }
    };
    prompt
        .validate()
        .map_err(|error| StoreError::NotCommitted(format!("edit a queued prompt: {error}")))?;
    Ok(prompt)
}

